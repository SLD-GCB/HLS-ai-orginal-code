#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
酒馆记忆.py — 长期记忆：一串条目，启用的那些拼进提示词

**这个文件不认识 Qt。** 它只管两件事：把条目按"挂载点"存起来、取出来；
以及把启用的条目渲染成一段能拼进提示词的文字。

两层落地（跟 `助手任务` + `助手转录` 同一种分法，见 `酒馆存储` 文件头）：

    记忆.json           {"<编号>": {类型 / 键 / 时间}}      ← 索引
    记忆/<编号>.json     [{一条记忆}, …]                    ← 条目本体

**挂载点**（`类型` + `键`）：

    类型='角色'  键=角色编号     —— "她记得你"，该角色的所有对话共享
    类型='目录'  键=工作目录     —— "这个项目里的事"，编程助手用

条目形状：

    {'文': str, '开': bool, '来源': '手写'|'自动', '会话': n, '序号': i, '指纹': str}

`开` = 参不参与（自动收回来的默认 `False`，等用户去确认）。`会话/序号/指纹`
只有自动收的才有，用来去重（见 `收待定`）。

⚠ **别和另外两样东西搞混**：聊天的 `说话人='系统'` 消息（那是用户一条条写的
系统提示），以及编程助手的「折叠/存根」（那是**转录本**为了省 token 做的压缩）。
这一层是"跨对话、跨任务留下来的长期记忆"。
"""

import hashlib
import os

import 酒馆工具
from 酒馆存储 import 毫秒
from 酒馆模型 import 读JSON, 写JSON

__all__ = ['角色', '目录', '取', '存', '删', '收待定', '渲染', '预算',
           '聊天块', '助手块', '指纹', '每条上限', '取水位', '推进水位']

#: 两种挂载点。**别用裸字符串**，拼错了不会报错、会静默存成第三类。
角色 = '角色'
目录 = '目录'

#: 一条记忆最多多少字。**不是洁癖**：记忆是整段拼进提示词的，它占的每一个
#: token 都是从"还能留几条历史"里扣的。超了就直接拒绝保存（界面上说清楚），
#: **不静默截断** —— 截断过的记忆是半句话，比没有更坏。
每条上限 = 2000


# ── 洗 ──────────────────────────────────────────────────────────────

def 指纹(文):
    """
    一段文字的内容指纹。**给自动回收去重用。**

    ⚠ 为什么非要有它：消息的 `序号` 是**会被复用**的（`酒馆对话.下个序号` 是
    "当前最大 + 1"，删掉末尾那条之后，下一条新消息拿到同一个号），而
    `覆盖消息` 又会保留原来的 `创建于`。所以只按 `(会话, 序号)` 去重，
    会出现"新消息被判成已经收过、内容永远收不进来"，而库里留着一个指向
    已经删掉的那条的旧条目。
    """
    文 = ' '.join(str(文 or '').split())
    return hashlib.sha1(文.encode('utf-8')).hexdigest()[:16]


def _正类型(类型):
    类型 = str(类型 or '')
    if 类型 not in (角色, 目录):
        raise ValueError('记忆的类型只认 %s / %s（给的是 %r）' % (角色, 目录, 类型))
    return 类型


def _正键(类型, 键):
    """挂载点的键。**目录一律走 `realpath`** —— 同一个目录换个写法（斜杠/大小写/
    相对路径）不该变成两份记忆。"""
    if 类型 == 目录:
        return os.path.realpath(str(键 or ''))
    try:
        return str(int(键))
    except (TypeError, ValueError):
        return str(键 or '')


def _正条目(条):
    """一条记忆 → 规规矩矩的 dict。**缺列给默认、坏类型当没写，绝不抛。**"""
    条 = 条 if isinstance(条, dict) else {}
    开 = 条.get('开')
    来 = str(条.get('来源') or '手写')
    出 = {'文': str(条.get('文') or '').strip(),
          '开': bool(开) if isinstance(开, bool) else str(开).lower() in ('1', 'true', '是'),
          '来源': 来 if 来 in ('手写', '自动') else '手写'}
    if 出['来源'] == '自动':
        出['会话'] = int(条.get('会话') or 0)
        出['序号'] = int(条.get('序号') or 0)
        出['指纹'] = str(条.get('指纹') or 指纹(出['文']))
    return 出


# ── 索引 ────────────────────────────────────────────────────────────

def _找行(库, 类型, 键):
    """按 `(类型, 键)` 找索引行。**扫一遍小表** —— 它是整张读进内存的，
    而且行数就是"几个角色 + 几个目录"，不值得为它加一列主键。"""
    for 行 in 库.全都('记忆'):
        if str(行.get('类型') or '') == 类型 and str(行.get('键') or '') == 键:
            return 行
    return None


def _新行(库, 类型, 键):
    现在 = 毫秒()
    return {'编号': 库.发号('记忆'), '类型': 类型, '键': 键,
            '创建于': 现在, '更新于': 现在}


# ── 自动回收的水位 ──────────────────────────────────────────────────
#
# ⚠ **没有这个水位，自动回收会变成"用户删一次、下一轮又长回来"。**
# 回收是"从消息流里现算"的：一条老消息只要还老在边界外面，每轮都会被算成
# 待收。用户嫌它烦、删掉了 —— 下一轮它照样回来，永远删不掉。
#
# 水位 = "这个会话已经被处理到第几号了"（`{会话编号: 最大序号}`，一个 JSON 列）。
# 只收序号**大于**水位的那些；收完把水位推到这次收的最大序号。这样
# "处理过"是一去不回的，删掉的候选不会复活。
#
# 代价（说清楚，别当没有）：**重说/编辑一条已经被收过的老消息，记忆里那份
# 不会跟着更新** —— 它的序号低于水位，不会再被看第二眼。这是刻意的取舍：
# 宁可漏一次更新，也不要每轮把用户删过的东西再塞回来。

def 取水位(库, 类型, 键):
    """这个挂载点的回收水位：`{会话编号(int): 已处理到的最大序号(int)}`。"""
    行 = _找行(库, _正类型(类型), _正键(_正类型(类型), 键))
    if 行 is None:
        return {}
    原始 = 读JSON(行.get('回收水位'))
    if not isinstance(原始, dict):
        return {}
    出 = {}
    for k, v in 原始.items():
        try:
            出[int(k)] = int(v)
        except (TypeError, ValueError):
            continue
    return 出


def 推进水位(库, 类型, 键, 会话编号, 到):
    """
    把某个会话的水位推到 `到`（**只往前推，不退**）。

    单独一个函数是给"这次没收到东西但也不想再看到它们"用的；正常收东西
    走 `收待定` 的 `水位=` 参数，跟条目写在同一次 `独占` 里。
    """
    类型, 键 = _正类型(类型), _正键(_正类型(类型), 键)
    到 = int(到 or 0)
    if 到 <= 0:
        return False
    with 库.独占():
        行 = _找行(库, 类型, 键)
        if 行 is None:
            行 = _新行(库, 类型, 键)
        水 = 取水位(库, 类型, 键)
        if 到 <= 水.get(int(会话编号), 0):
            return False
        水[int(会话编号)] = 到
        库.存('记忆', dict(行, 回收水位=写JSON(水), 更新于=毫秒()))
    return True


# ── 读 ──────────────────────────────────────────────────────────────

def 取(库, 类型, 键):
    """这套记忆的全部条目（有停用的也有）。没有就返回 `[]`。"""
    类型 = _正类型(类型)
    键 = _正键(类型, 键)
    行 = _找行(库, 类型, 键)
    if 行 is None:
        return []
    条目们 = 库.取记忆们(行.get('编号')) or []
    return [_正条目(x) for x in 条目们 if isinstance(x, dict)]


# ── 写 ──────────────────────────────────────────────────────────────

def 存(库, 类型, 键, 条目们):
    """
    把这套记忆整个换掉（界面那边就是"保存"）。

    ⚠ **先写大件、后写索引行**（同 `酒馆助手存.存一次`）：反过来的话，
    索引写成功而大件失败，就留下一个"有记忆、点开是空的"的挂载点。
    """
    类型 = _正类型(类型)
    键 = _正键(类型, 键)
    干净 = [_正条目(x) for x in (条目们 or []) if isinstance(x, dict)]
    干净 = [x for x in 干净 if x['文']]
    for x in 干净:
        if len(x['文']) > 每条上限:
            raise ValueError('有一条记忆 %d 字，超过上限 %d 字了 —— 拆成几条吧'
                            % (len(x['文']), 每条上限))
    with 库.独占():                  # 发号 + 两次写是一段，见 `库.独占`
        行 = _找行(库, 类型, 键)
        if 行 is None:
            行 = _新行(库, 类型, 键)
        else:
            行 = dict(行, 更新于=毫秒())
        库.存记忆们(行['编号'], 干净)      # 先大件
        库.存('记忆', 行)                 # 后索引
    return 干净


def 删(库, 类型, 键):
    """把这套记忆整个删掉（条目 + 索引行）。删到了返回 `True`。"""
    类型 = _正类型(类型)
    键 = _正键(类型, 键)
    with 库.独占():
        行 = _找行(库, 类型, 键)
        if 行 is None:
            return False
        库.删记忆们(行['编号'])           # 先大件
        库.删('记忆', 行['编号'])         # 后索引
    return True


def 收待定(库, 类型, 键, 候选们, 水位=None, 按序号去重=True):
    """
    把一批**自动回收**来的候选并进这套记忆里，返回这次真收了几条。

    收进来的都是 `开=False`（停用）—— 它们只是"候选"，用户去界面上看一眼、
    确认了才生效。**这就是为什么自动回收不会污染提示词。**

    `水位` 给了就一并写进去（形状见 `取水位`）—— **必须跟条目在同一次
    `独占` 里写**：分两次的话，中间死掉就是"条目收了、水位没动"，
    下一轮同样的一批会再收一遍（虽然会被去重挡住，但水位从此永远落后）。

    `按序号去重=False`：**不走那套 `(会话, 序号)` 规则，只按内容指纹去重。**
    编程助手那边要这个 —— 它的候选是"某次任务里被折叠的步骤"，没有
    "会话/序号"这回事（`(0, 0)` 会让所有候选互相顶掉，只剩最后一条）。
    同一段文字收过一次就不再收；不同任务、不同措辞的各自留着。

    按序号去重的三条规则（缺一条都会出事）：

      ① `(会话, 序号, 指纹)` 一模一样 → 收过了，跳过。
      ② **同 `(会话, 序号)` 但指纹不同** → 序号被复用了（删掉末尾那条之后，
         下一条新消息会拿到同一个号，见 `酒馆对话.下个序号`）。这时候
         **只有当那条还是「自动 + 停用」（= 用户从没碰过）才替换**。
      ③ 用户启用过或手改过的条目，**永远不覆盖** —— 他确认过的东西不该被
         后面跑出来的一条自动候选顶掉。
    """
    类型 = _正类型(类型)
    键 = _正键(类型, 键)
    干净 = []
    for x in (候选们 or []):
        if not isinstance(x, dict):
            continue
        条 = _正条目(dict(x, 来源='自动', 开=False))
        if 条['文']:
            干净.append(条)

    with 库.独占():
        行 = _找行(库, 类型, 键)
        新挂 = 行 is None
        if 新挂:
            行 = _新行(库, 类型, 键)
        现有 = [] if 新挂 else [
            _正条目(x) for x in (库.取记忆们(行['编号']) or [])
            if isinstance(x, dict)]
        收了 = 0
        for 候 in 干净:
            if not 按序号去重:
                if any(t.get('指纹') == 候['指纹'] for t in 现有):
                    continue                       # 同一段文字收过了
                现有.append(候)
                收了 += 1
                continue
            同名 = [i for i, t in enumerate(现有)
                   if t.get('来源') == '自动'
                   and t.get('会话') == 候['会话']
                   and t.get('序号') == 候['序号']]
            if any(现有[i].get('指纹') == 候['指纹'] for i in 同名):
                continue                                  # ① 收过了
            换过 = False
            if len(同名) == 1:
                旧 = 现有[同名[0]]
                if not 旧.get('开'):
                    现有[同名[0]] = 候                       # ② 序号被复用，替换
                    换过 = True
            if not 换过:
                现有.append(候)                              # ③ 没碰过的就新加
            收了 += 1
        if 收了 or 水位:
            if 水位:
                行 = dict(行, 回收水位=写JSON(水位))
            库.存记忆们(行['编号'], 现有)                 # 先大件
            库.存('记忆', dict(行, 更新于=毫秒()))         # 后索引
    return 收了


# ── 渲染 ────────────────────────────────────────────────────────────

def 预算(窗口, 上限=1200):
    """
    记忆最多能占多少 token。**跟窗口挂钩，不能写死。**

    ⚠ 写死一个数的话，`n_ctx` 小的模型照样会被记忆顶爆 —— 而
    `酒馆大脑.窗口内` 对"系统提示本身就把窗口占满"是**没有保护**的（它的
    下限只是"至少留一条消息"）。提示词真超了 `n_ctx`，llama.cpp 会**从最
    前面截断**，先丢的正是系统提示（角色设定、规矩、记忆全没），界面上
    一点异常都没有。

    `窗口 = 0`（云端，读不到窗口）时回固定的 `上限` —— 云端本来就不按窗口
    裁，走的是会话设定里的「字数上限」。
    """
    上限 = max(0, int(上限 or 0))
    窗口 = int(窗口 or 0)
    if not 窗口:
        return 上限
    return min(上限, max(200, 窗口 // 8))


def 渲染(条目们, 上限=0, 标题=''):
    """
    启用的条目 → 一段能拼进提示词的文字。返回 `(文本, 带了N, 没带M, token)`。

    ⚠ **必须是确定性的**：同样一批条目，两次渲染出来的字符串要逐字节相同
    —— 不带时间戳、不带序号、顺序不变。原因不是洁癖：这段文字是拼进
    **系统提示**的，而 llama.cpp 只复用"和上次**完全一样**的前缀"的 KV。
    渲染结果每轮抖一下，就等于每轮从系统提示那个位置起全部重算
    （实测 17K 提示要 52 秒）。

    `上限` 是**记忆自己**能占多少 token（0 = 不限）。超了就从后面截断，
    并在文末**明说还有几条没带** —— 不静默丢。⚠ 调用方给的上限要跟
    `n_ctx` 挂钩（`窗口内` 对"系统本身就把窗口占满"是没有保护的）。

    ⚠ 界面上的"带了 N 条 / 没带 M 条"**必须取这个函数的返回值**，别再自己
    按"启用的有几条"数一遍 —— 那样界面说的和真发出去的会不是一份，
    而这个功能存在的全部意义就是"这次到底发出去什么"能对得上账。
    """
    上限 = max(0, int(上限 or 0))
    条 = [x for x in (条目们 or [])
         if isinstance(x, dict) and x.get('开') and (x.get('文') or '').strip()]
    if not 条:
        return '', 0, 0, 0

    行 = []
    共 = 0
    没带 = 0
    for i, x in enumerate(条):
        块 = '- ' + str(x['文']).strip().replace('\n', '\n  ')
        大 = 酒馆工具.估token(块) + 1
        if 上限 and 行 and 共 + 大 > 上限:
            没带 = len(条) - i
            break
        行.append(块)
        共 += 大

    文本 = ('\n'.join(行) if not 标题 else '%s\n%s' % (标题, '\n'.join(行)))
    if 没带:
        文本 += ('\n（还有 %d 条这次没带上 —— 记忆太长，窗口装不下。'
                '去「上下文」里停用几条，或者把 n_ctx 调大。）' % 没带)
    return 文本, len(行), 没带, 共


def 聊天块(条目们, 上限=0):
    """角色记忆拼进**聊天**系统的样子。见 `渲染`。"""
    return 渲染(条目们, 上限, 标题=(
        '【长期记忆】下面是之前发生过、现在已经不在上面的对话里了的事。'
        '请当作你本来就知道，不要复述它们，也不要问"你怎么知道的"：'))


def 助手块(条目们, 上限=0):
    """项目记忆拼进**编程助手**系统提示的样子。见 `渲染`。"""
    return 渲染(条目们, 上限, 标题=(
        '【这个项目的记忆】之前在这个目录里干过的事，以及用户交代过的约定。'
        '把它当背景，不要复述：'))
