#: 调用形状的名字。**只给界面/记录用** —— 不是给判定用的（没有第二种形状可判）。
形状 = 'XML'


def 工具清单():
    """
    工具清单文本。**从 `酒馆工具.定义们` 生成，不手写第二份。**

    ⚠ **手写第二份的代价不是"多维护一处"，是"漏改的那一处不报错"**：
    新加一个工具、忘了改这份表，模型就**不知道有这个工具** —— 而它不可能
    调用一个没被告知的工具。表现是"模型死活不用那个工具"，
    从界面上完全看不出原因（提示词里少一行，没人会去数）。

    只列名字和参数键（`酒馆工具._函` 让所有参数都进 required，所以不用标
    哪些必填），说明取工具自己的 description，去掉 markdown 星号
    （那是给人读的，进提示词是白占 token）。
    """
    行 = ['可用工具（要调就输出 XML 形状的 <tool_call>）：', '']
    for 工 in 酒馆工具.定义们:
        函 = 工['function']
        键 = '、'.join(函['parameters']['properties'])
        说明 = str(函['description']).replace('**', '').replace('\n', ' ')
        行.append('  %s  %s  ——  %s' % (函['name'], 键, 说明))
    return '\n'.join(行)


#: 一次调用长什么样。**给模型看的**，解析不依赖这段文字。
#:
#: ⚠ **例子必须示范"多个参数"**。早先拿 `list_dir`（只有一个 `path`）当例子，
#: 模型很容易把"一条调用只有一个参数"当成规则 —— 实测 Qwen3.5-9B 写
#: `write_file` 时 `content` 就写走样了。换成三个参数的工具，顺带把
#: `<parameter=名字>值</parameter>` 这个完整写法示范三次。
协议例 = """一次可以给多个 <tool_call>，会按顺序执行。
例：
<tool_call>
<function=read_file>
<parameter=path>main.py</parameter>
<parameter=start>1</parameter>
<parameter=count>50</parameter>
</function>
</tool_call>"""


def 协议文本():
    """
    系统提示里那一段工具协议。**它取代了原来那三份（JSON / XML / GLM）。**

    ⚠ 只有一份是有意的：教哪种形状**不该由模型是谁决定**。多一份就多一个
    "该怎么选"的判据，而那个判据正是被否掉的东西。
    """
    return '%s\n\n%s' % (工具清单(), 协议例)


def 包结果(名, 参, 文):
    """
    一次工具执行的结果 → 回喂给模型的**那一条消息的正文**。

    ⚠ **全模型一个形状，不按族分支。** 两个理由：
      · 大量模板不认 `role='tool'`（发过去被静默丢掉），而**丢掉不会报错** ——
        模型从此看不见工具结果，它会开始**自己编**工具结果，界面上一切正常；
      · `装进去了吗` / `并进首条` 那套自检也只推理 user / assistant / system。
    不分支 = 不需要任何"这个模型认什么角色"的判据，也就没有判错的可能。

    参数只列前几个 —— 它是给模型"想起自己干过什么"的索引，不是完整记录
    （完整参数和结果在转录本里，界面能全文摊开）。
    """
    对 = []
    for k, v in list((参 or {}).items())[:4]:
        s = str(v).replace('\n', ' ')
        对.append('%s=%r' % (k, s[:60]))
    头 = '%s(%s)' % (名, ', '.join(对))
    return '[工具结果] %s\n%s\n[/工具结果]' % (头, 文 or '（空）')


#: 强制轮的起手。停在**工具名之前** —— 我们只收走"要不要动手"这一格，
#: 调哪个工具第一阶段仍交给模型填。
强制起手 = '<tool_call>\n<function='


def _预填(头, 深, 工具名='', 参数名=''):
    """
    按 `深` 拼预填。**只该由 `起点` 调** —— 它保证 `深` 和语法那份是同一个。

    ⚠ 之所以拆成私有：**"切点"是一个量，不能两处各解释一遍。** 见 `起点`。
    """
    if 深 == '值':
        return 头 + '<tool_call>\n<function=%s>\n<parameter=%s>' % (工具名, 参数名)
    if 深 == '参数':
        return 头 + '<tool_call>\n<function=%s>\n' % 工具名
    # ⚠ **`强制起手` 本身就含 `<tool_call>\n`** —— 别再拼一次。
    # （自测撞到过：拼重了会吐成 `<tool_call>\n<tool_call>\n<function=`。）
    return 头 + 强制起手


def 起点(渲串='', 工具名='', 参数名=''):
    """
    一次强制轮的**起点**，以及从它派生的**两样东西** —— `{'深','预填','语法'}`。

    ⚠⚠⚠ **这是全层唯一一处决定"切点"的地方。** 改这一层只能来这儿改。

    ## 为什么要合成一个函数（这是踩过大坑的）

    预填和语法**必须描述同一个切点**：预填说"我已经写到这儿了"，
    语法说"从这儿往后该长什么样"。而 llama.cpp 的 grammar
    **只管生成的 token、不管提示词** —— 所以语法描述的是
    "**从预填那一刀往后**"那一段。

    我第一版把它们写成两个函数、在 `跑一轮` 里**分别调用**，然后为了骨架
    加深了预填、忘了跟着改语法 —— 结果生成的第一口被语法按着头写了一个
    **工具名**（真跑原文：`<parameter=path>edit_file>`）。

    ⚠ **症状出现在最不该出现的地方**：表现为"4 个模型都很蠢"。
    而跨 4 个互不相关的模型出现同一种畸形，只可能是共同那一环错了。
    **一次错误的前提，足以让你得出"本地小模型都不行"这种把整条路线带偏的结论。**

    所以：**一处决定，两样一起产出。** 想给它们不同的深度，得先改这个函数。

    ## 三档深度（拨到哪一档由"这一步有多确定"决定，不由模型是谁决定）

        `深='形状'`  只抢"要不要动手" —— 工具名它自己填
        `深='参数'`  连"调哪个"也定
        `深='值'`    连"参数名"也定，只剩值一格

    ⚠ 后两档要能成立，前提是"我们知道该调哪个" —— 那个判断在**骨架**里
    （`酒馆助手.骨架`），它看的是**转录本的状态**，跟模型无关。

    ⚠ 预填是**提示词的末尾**、不在生成结果里 —— 解析前必须把
    `预填 + 生成` 拼起来（见 `酒馆本地.跑一轮`）。不拼的话开标签丢了、
    解析必崩，而崩出来的症状是"格式不合法"，方向完全指错。

    ⚠⚠ **绝不能无条件用。** 无条件预填 `<tool_call>` 等于**取消了"给最终
    答复"这个可能** —— 模型永远只能调工具、永远收不了尾。它只在
    "这一轮该死磕"的时候出现（两段式的判断在 `酒馆助手.跑`）。

    开头那半截治的是**模板自己种了一个未闭合 `<think>`** 的模型：实测
    R1-Distill-1.5B 的模板收尾就是 `{{'<｜Assistant｜><think>\\n'}}` ——
    它一开口就在想，想完常常自认为答完了（工具清单还摆在上面，一个字没碰）。
    先替它把思考**闭合**再抢开标签，它就没有"再想想"这个位置了。

    依据是那条实测结论（GLM-Z1，真跑）：**改文本没有用，改状态才有用。**
    掐掉思维标记会让它疯狂复读（状态机不因为标签被抽走就消失），
    而预填让它**根本不用开**思考块。
    """
    头 = '</think>\n' if 酒馆协议.思考没闭合(渲串) else ''
    # ⚠ **这一行就是"切点"。** 下面两样都从它派生，谁也别自己再算一遍。
    深 = '值' if (工具名 and 参数名) else ('参数' if 工具名 else '形状')
    return {'深': 深,
            '预填': _预填(头, 深, 工具名, 参数名),
            '语法': _语法文本(深, 工具名, 参数名)}


# ══ 中间层：采样期约束（grammar）═══════════════════════════════════
#
# ⚠ **这是三段里最硬的一段。** 输入侧（提示词）是"告诉它怎么做"，
# 中间层是"**让它做不出别的**" —— 每一 token 都在算，不合语法的候选直接抹掉。
#
# 跟输入侧那两件（预填、提示词）的关系：
#
#     预填    管**起手**   —— 它第一个 token 只能往这儿走
#     grammar 管**全程**   —— 它每一步都不许走出这个语法
#
# ⚠ **只用在强制轮。** 套上语法的模型**只能输出工具调用、给不出答复** ——
# 所以自由轮绝不能带它，否则模型永远收不了尾。
#
# ⚠⚠ **判据来自我们自己的协议和工具定义**（六个工具名、每个工具声明的参数名），
# **不是"某个模型爱怎么写"** —— 同 `整参数` 那把尺子。

#: 值的终止符。**语法要把"值里不含它"这件事表达出来**，见 `_段支`。
终止串 = '</parameter>'


def _类(字):
    """把单个字符转义成 GBNF 字符类里能用的写法。"""
    if 字 in ']\\^-':
        return '\\' + 字
    if 字 == '\n':
        return '\\n'
    if 字 == '\t':
        return '\\t'
    return 字


def _段支(终止):
    """
    GBNF 里"**匹配任意文本，但不含 `终止` 这个字面串**"的写法。

    ⚠ **为什么不能简单写成 `[^<]*`**：那样值里就出不了 `<` —— 而代码里
    满地都是 `<`（HTML 标签、`a < b`、`List<int>`）。写不出来等于把
    `write_file` 废了。

    ⚠ **为什么不能写 `.*` 了事**：那模型可以在值里写一个 `</parameter>`，
    值提前结束、**后半段内容凭空消失**，而文件照样写成功 —— 静默写坏，
    正是这个项目最怕的那一类。

    做法是把"差的**一步**"全列出来：已经对了 `终止[:k]` 这么多，
    下一个字符只要不是 `终止[k]` 就走得通。**没有负向前瞻也能表达"不含"。**
    """
    支 = ['[^%s]' % _类(终止[0])]
    for k in range(1, len(终止)):
        支.append('"%s" [^%s]' % (终止[:k], _类(终止[k])))
    return ' | '.join(支)


def _语法文本(深, 工具名='', 参数名=''):
    """
    这一轮生成的 **GBNF**，**按 `深`（切点）来定 `root` 从哪开始**。

    ⚠⚠ **只该由 `起点` 调。** `深` 必须和预填那份是同一个值 ——
    这是踩过大坑的地方，见 `起点` 的 docstring。**别在外面单独调它。**

        `深='形状'`  → root 从**工具名**开头
        `深='参数'`  → root 从 `">"` 开头
        `深='值'`    → root 从**值**开头

    ⚠ **它锁的是三件事**（都来自工具定义，不来自模型）：

      · **工具名只能是那六个** —— 编不出 `的是子文件名` 这种东西；
      · **参数名只能是这个工具声明过的** —— 编不出 `old_path` / `directory`；
      · **结构必须合法** —— 不会出现缺收尾、半截参数。

    ⚠ **它锁不了两件事，得知道**：
      · **该给的参数没给** —— 上下文无关语法表达不了"每个必填各出现一次"
        （要枚举排列，组合爆炸）。缺参数只能靠工具报错 + 喂回去；
      · **值填得对不对** —— 语法管形状，管不了"路径该写 `a.py`"。

    ⚠ **它顺带把输出侧的两件事也办了**（白送的）：生成到 `</tool_call>` 就
    没得可续，模型自然停（不会接着演）；**一次生成只可能有一条调用**。

    ⚠ `深='值'` 那一档**必须指名一个工具** —— 不知道是哪个工具就不知道
    有哪些参数名可写，语法也就无从谈起。
    """
    if not 酒馆工具.定义们:
        return None
    名字们 = [工['function']['name'] for 工 in 酒馆工具.定义们]
    if 深 == '形状':
        选的 = list(名字们)
    elif 工具名 in 名字们:
        选的 = [工具名]
    else:
        return None                    # 深了却没给合法的工具名 —— 宁可不要语法
    if not 选的:
        return None

    # ⚠⚠ **规则名只能用 ASCII，不能写中文。**
    #
    # 我第一版拿 `段` / `值` / `空` / `身0` 当规则名，结果：
    #   · llama.cpp 的 GBNF 解析器**认不出中文标识符**，报
    #     `expecting name at 值 ::= 段* "X"`；
    #   · 而 `LlamaGrammar.from_string` **不抛异常** —— 只在 stderr 打一行
    #     `parse: error parsing grammar`，然后返回一个**坏掉的对象**；
    #   · 那个坏对象一路漂到采样，**段错误**（`access violation reading 0x0`），
    #     整个进程没了 —— 从 Python 侧完全看不出跟语法有关。
    # 规则名一律用 ASCII，是这里唯一的安全做法。
    行 = [
        # 值 = 任意多个"段"，而段里禁止出现终止串
        'seg ::= %s' % _段支(终止串),
        'v ::= seg*',
        # 换行可有可无 —— 模型爱写不写都行，别为了这个把它堵死
        'ws ::= ("\\n")*',
    ]
    根支, 深根 = [], None
    for i, 名 in enumerate(选的):
        键们 = sorted(_参数名们(名))
        if not 键们:
            continue
        # `p<i>`：一个参数，`<parameter=键>值</parameter>` 后面跟着可有可无的换行
        行.append('p%d ::= %s' % (i, ' | '.join(
            '"<parameter=%s>" v "%s" ws' % (键, 终止串) for 键 in 键们)))
        # `b<i>`：从工具名之后那一口开始（`深='形状'` 那一档用）
        行.append('b%d ::= ">" ws ( p%d )* "%s" ws "</tool_call>"'
                 % (i, i, '</function>'))
        根支.append('"%s" b%d' % (名, i))
        if 深 == '值' and 名 == 工具名:
            深根 = ('v "%s" ws ( p%d )* "%s" ws "</tool_call>"'
                  % (终止串, i, '</function>'))
    if not 根支:
        return None
    if 深 == '参数':
        行.append('root ::= ' + 根支[0])       # `选的` 只有一个（上面已收窄）
    elif 深 == '值':
        if 深根 is None:
            return None
        行.append('root ::= ' + 深根)
    else:
        行.append('root ::= ' + ' | '.join(根支))
    文 = '\n'.join(行)
    # ⚠ **自检：规则名全是 ASCII 吗。** 现在写死的都是 ASCII，这条永远不会响 ——
    # 留着是因为**踩中它的症状是段错误**（见上面那段）：从 Python 侧看
    # 就跟"语法"无关，能查到天亮。宁可在这儿响亮地报一句。
    for 条 in 文.split('\n'):
        名 = 条.split(' ::= ')[0]
        if not (名.isascii() and 名.replace('-', '').replace('_', '').isalnum()):
            raise ValueError('GBNF 规则名必须是 ASCII 标识符，收到 %r' % 名)
    return 文


# ══ 输出侧：停止条件 ═══════════════════════════════════════════════

def 回合标记(实例, 模板=''):
    """
    喂给 `stop` 的**回合标记** —— 模型干完活、开始"演下一轮"时吐的那个东西。

    ⚠ **为什么要它**：模板自带的 `stop` 一般只有结束符（eos token）。
    模型干完活之后 **接着演"用户又说了什么"** 时吐的回合标记，不在 stop 里
    就拦不住 —— 那就"活干完了也不停"。

    ## 来源有两条，**第一条是最权威的**

    **① 模型自己的 `bos` / `eos`** —— 这是**回合边界最权威的定义**，
    每个模型都有，而且**不用任何清单**。从 `实例` 的元数据取字面串。

    ⚠⚠ **第二条曾经是唯一的一条，而它漏得很难看：**

      我第一版只从**模板源码**里抠 `<|…|>` 形状的字面串。两个洞：
        · 只认竖线族，**漏了方括号族** `<[…]`>（豆包 / Seed-Coder 用的就是它）；
        · 更根本的：**有些模板里压根没有字面量** —— Seed-Coder 的模板写的是
          `{{ bos_token }}` / `{{ eos_token }}`，**渲染时才变成 `<[…]>`**。
          所以对这类模型，"从模板源码里抠"**从根上就不通**（抠出来永远是空的）。
      2026-09-21 用户实测撞到：豆包**活干完了也不停** —— 因为对它一个回合
      标记都没加上，它照模板再吐一个 `bos` 去开下一轮，而 **bos 不是 eos**，
      采样器不停。

    所以顺序是：**先要模型自己的 bos/eos**（一定有、不用认），
    再**补模板里写死的字面量**（有些模板确实写死，比如 Phi 的 `<|user|>`）。

    ⚠ **模板那一支的筛法没变，两头理由不同**：
      · **留**：`user` / `assistant` / `system` / `end` / `start` / `sentence` 这类
        —— 那是回合边界，一冒出来就说明它在替别人说话；
      · **扔**：含 `tool` / `function` / `think` / `channel` 的 —— 那些是
        **工具调用和思维链自己的标记**，拿它们当停止串会**把调用切碎**。

    ⚠ **`bos` 也当停止串，这一条曾经让我犹豫**，但它是对的：
    模型在生成里吐出 `bos` 只有一种意思 —— **它在开新一轮**。
    正常内容里不会出现它（那是它的控制符，不是它写的字）。

    ⚠ **还没做、但更彻底的那一层**：直接从模型**词表的 token_type** 里取
    所有控制类 token。**暂时不做** —— 因为思维链标记本身也是特殊 token
    （DeepSeek 的 `<｜begin▁of▁thinking｜>` 这类），全量加进去会让模型
    **一个字正文都吐不出来**。要做得先把"回合标记"和"内容标记"分开。
    """
    出 = []

    # ① 模型自己的 bos / eos —— 最权威，不用清单
    #
    # ⚠⚠ **但要多一道闸：它得像"控制符"。**
    #
    # 因为有些模型的 bos **长得跟正常标记一模一样** —— 实测 `Phi-3.5-mini`
    # 的 bos 就是 **`<s>`**。那东西**既是控制符、又是合法的 HTML 标签**：
    # 让 agent 写一个网页、内容里出现 `<s>`（删除线），stop 一匹配上就
    # **把文件从那儿切断** —— 文件写成了、报"已写入"、**内容是坏的**。
    #
    # 闸就是"含 `|` / `｜` / `[` / `▁` 之一" —— 那是**控制符的形状**
    # （真有 `|` 或 SentencePiece 分隔符的，正常文本里不会出现）。
    # 代价是丢掉 `<s>` / `<bos>` 这种，**但它们对应的 eos 还在**，
    # 而 eos 才是真正的终止符。
    #
    # ⚠ 判据是"**它会不会出现在正常文本里**"（形状），不是"我认不认识它"（清单）。
    for 号 in (实例.token_bos(), 实例.token_eos()):
        try:
            文 = 酒馆协议.词(实例, 号) if int(号) >= 0 else ''
        except (TypeError, ValueError, AttributeError):
            文 = ''
        文 = (文 or '').strip()
        if len(文) < 2 or 文 in 出:
            continue
        if not any(c in 文 for c in '|｜[▁'):
            continue
        出.append(文)

    # ② 模板里写死的字面量（有些模板确实写死）
    模板 = 模板 or ''
    import re
    # ⚠ **形状认两族**：竖线族 `<|…|>` / `<｜…｜>` **和方括号族** `<[…]>`。
    # 只认一族会漏（第一版就漏了，见 docstring）。
    留 = ('user', 'assistant', 'system', 'end_of_turn', 'eot', 'eom',
         'end▁of▁', 'endoftext', 'sentence', '▁of▁', 'start')
    扔 = ('tool', 'function', 'think', 'channel', 'python', 'observation',
         'json', 'code')
    for 记 in re.findall(r'<[|｜\[][^<>]{1,30}[|｜\]]>', 模板):
        小 = 记.lower()
        if any(词 in 小 for 词 in 扔):
            continue
        if not any(词 in 小 for 词 in 留):
            continue
        if 记 not in 出:
            出.append(记)
    return tuple(出)


