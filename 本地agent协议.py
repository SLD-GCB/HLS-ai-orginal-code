"""
本地agent协议.py — 本地 agent 的协议层：一套**我们自定**的协议 + 自己写的工具调用解析器

**纯逻辑**：不 import Qt、不碰存储（跟 `酒馆工具` / `酒馆协议` 同一个定位）。

════════════════════════════════════════════════════════════════════
这一层要办的事
════════════════════════════════════════════════════════════════════

**不论模型原生支不支持工具调用，都让它在我们的协议之下调用工具。**

留在模型手里的只该有一件事 —— **预测下一个 token**（写内容）。其余都是权力，
权力都收走：要不要动手、调用写成什么形状、结果怎么回填、什么时候收尾，
全由这儿说了算。

⚠ **设计准则（改这个文件之前先拿它卡一遍）**：

    这一层里不该有任何一个分支在问「这个模型会不会调工具」。

有这种分支，就说明权力还没剥夺干净。

⚠⚠ **几条被明确否掉的老做法，别捡回来：**

  · **不读模型的聊天模板来决定"教它哪种形状"。** 那是"做适配层去追模型"，
    用户连着否过四次（最近一次原话是"胡闹，乱来"）。模板里**只读物理事实**
    —— eos / 认不认 system 插槽 / 回合标记 —— 那些是它**改不了的身体**，
    不是它的协议。
  · **不做"原生 / 文本"二选一。** 原生 = 把**形状决定权**让给模板，正是要
    收回来的东西。agent 链路只走这一套。
  · **不做"认得出就多教一种形状"的三份提示词。** 只此一套。

════════════════════════════════════════════════════════════════════
形状为什么定成 XML
════════════════════════════════════════════════════════════════════

    <tool_call>
    <function=工具名>
    <parameter=参数名>值</parameter>
    </function>
    </tool_call>

**唯一的理由：值就是原文。** 代码、多行内容、引号**零转义**。

JSON 形状下小模型最难缠的两个坑 —— 「引号没转义」「内容被截断在字符串中间」
—— 在这儿**根本不存在**。（早先 `_解析催话` 里那三条"照着改"的毛病，
在这个形状下一条都写不出来。）代价是参数值里若出现字面 `</parameter>`
会被提前截断：已知、可接受。

════════════════════════════════════════════════════════════════════
顺带说清：解析器为什么必须自己写
════════════════════════════════════════════════════════════════════

实测 `llama-cpp-python` 0.3.35 **不会**把模型吐出来的工具调用解析回
`tool_calls` 字段 —— 连 `tool_choice='required'` 都不解析，原始文本原样躺在
`content` 里、`tool_calls` 是 None。模型那边是对的（它照协议吐了），
坏的只是绑定这一层。

顺带一个好处：既然无论如何都要自己解析 `content`，那就没有理由不用
`stream=True` —— 而流式是**唯一能在解码阶段提供打断点**的方式。
"""

