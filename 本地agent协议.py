# ── 参数值整理 ──────────────────────────────────────────────────────
#
# ⚠⚠ **这一层的判据只能来自"我们自己的协议和工具定义"，不能来自"哪个模型吐过什么"。**
#
# 前者对**任何**模型都成立；后者是**适配** —— 而适配这条路用户否过很多次，
# 理由很硬：**清单永远补不完**（`空话标记` 那次就是活例子，我写了 `看来`，
# 模型写的是 `看起来`，白写）。
#
# 我第一版在这儿写了一张 `当前目录说法` 的清单，词是从 R1 的输出里抄的 ——
# **那正是"针对一种模型适配"**，2026-09-21 被用户当场点掉，整张删了。
#
# 那"当前目录"这类该怎么治？**不靠事后猜，靠两条更硬的路**（都还没接）：
#   · **约束**：grammar 把 `path` 的值限在路径字符集里 —— 中文描述**写不出来**；
#   · **反馈**：值不合法 → 工具报错 → 喂回去让它重写（这条环本来就有）。
# 事后归一只能做**无损**的那一半：格式脏了抹掉，**意思不猜**。

#: 哪些参数是**正文**（任意文本，一个字都不能动）。
#:
#: ⚠ 这份表来自**我们自己的工具定义**（`酒馆工具.定义们` 里那三个自由文本参数），
#: 不是从模型输出总结的 —— 前者是协议声明，后者是适配。
#:
#: ⚠ **它们必须排除掉一切清洗**，哪怕"剥一层成对引号"都不行：
#: 让模型写一个内容就是 `"hello"` 的 JSON 文件，剥完就成了 `hello` ——
#: 文件写成了、报"已写入"、退出码 0，**内容却是错的**。那正是这个项目
#: 最怕的一类坏法（见 `酒馆工具.改文件` 的注释）。
正文参数 = ('content', 'old', 'new')

#: 表示"是" / "否"的说法。
#:
#: ⚠ 候选值来自**工具自己的 description**（`edit_file.all` 写着"填 否 或 是"），
#: 不是从模型输出里观察来的 —— 前者是协议声明，后者是适配。
是说法 = ('是', 'yes', 'true', 'y', '1', 'all', '全部', '所有', '替换全部')
否说法 = ('否', 'no', 'false', 'n', '0', '不', '只替换一处', '只改一处',
        '第一处', '只一处')


def _型们(名):
    """
    这个工具**每个参数声明的是什么类型**。`{参数名: 'string' / 'integer'}`。

    ⚠ **从 `酒馆工具.定义们` 读，不在这儿写死键名。** 硬编码键名的话，
    以后加一个 integer 参数就得回来改一次 —— 而漏改不报错，只是那个参数
    不再被归一（症状是"只有它老是报'得是个整数'"，很难联想到这儿）。
    """
    for 工 in 酒馆工具.定义们:
        函 = 工['function']
        if 函['name'] == 名:
            return {k: (v or {}).get('type')
                    for k, v in (函['parameters'].get('properties') or {}).items()}
    return {}


def _去包装(文):
    """
    一个文本值 → 抹掉**纯格式**上的脏东西。**无损，不改意思。**

      ① 首尾空白；
      ② 模型爱给整个值套一层引号（`"a.py"` / `'a.py'` / 中文引号都见过）——
         **成对**才剥，一头有一头没有的不动（那多半是内容本身）。

    ⚠ **正文参数不许走这儿**（见 `正文参数`）。
    """
    净 = str(文 if 文 is not None else '').strip().strip('`').strip()
    对 = (('"', '"'), ("'", "'"), ('“', '”'), ('‘', '’'), ('「', '」'))
    for 左, 右 in 对:
        if len(净) >= 2 and 净.startswith(左) and 净.endswith(右):
            净 = 净[1:-1].strip()
            break
    return 净


def _整数字(文):
    """
    一个数字值 → 里面的那个整数。

    ⚠ **判据是"工具声明这个参数是 integer"，不是"某个模型爱怎么写"。**
    声明了 integer 而值里带着一堆字（`"第 1 行"` / `"100 行"`），
    抠出那个整数是**无损**的 —— 工具那边 `float()` 会直接抛 `工具错`
    （"参数 start 得是个整数"），而那个数字明明就在值里。

    ⚠ **抠不到就原样返回**，别自己编一个默认值 —— 让它报错比我们猜强。
    """
    m = re.search(r'-?\d+', str(文 if 文 is not None else ''))
    return m.group(0) if m else 文


def _整是否(文):
    """`是` / `否` 的归一。认不出原样返回（工具那边会报）。"""
    净 = str(文 if 文 is not None else '').strip().lower()
    if 净 in 是说法:
        return '是'
    if 净 in 否说法:
        return '否'
    return 文


def _整路径(文, 根=''):
    """
    一个路径值 → **我们协议规定的那一种写法**。全程无损：

      ① 去掉尾巴上的斜杠（`'./'` 和 `'.'` 在**我们的协议里**是一回事）；
      ② **绝对路径若落在工作目录底下 → 剥成相对路径**；
      ③ 其余原样。

    ## ② 是"执行协议约定"，不是"给某个模型打补丁"

    ⚠ **我们的工具自己声明过**："只接受相对工作目录的路径，不要给绝对路径"
    （`酒馆工具.定界` 的报错原文就是这么写的）。
    所以"路径相对工作目录"是**协议的一部分** —— 协议层把它**执行**掉，
    是天经地义的事；写成"某个模型会这么干，所以加一条"就变成了适配。

    ⚠ **它无损**：`D:\\proj\\x.py` 和 `x.py`（工作目录是 `D:\\proj`）指的是
    **同一个文件**。这跟"把『当前目录』猜成 `.`"不是一回事 —— 后者要**猜意思**。
    而且**剥完正好是根本身时就是 `.`**，一个字都不用猜。

    ⚠ **不在工作目录底下的绝对路径，一个字都不动。** 那是"它想去别处"，
    我们不替它做决定 —— 让工具照旧报错、让它自己改。
    这条边界是**客观判断**（在不在根底下），不是猜。

    ⚠ **只动绝对路径。** 相对路径一律不碰 —— 免得 `realpath` 顺手把符号链接
    和 `..` 解掉，那会**悄悄改掉**它本来的意思。
    """
    净 = str(文 if 文 is not None else '').strip().rstrip('/\\')
    if not 净:
        return 净
    if 根 and os.path.isabs(净):
        try:
            根真 = os.path.realpath(根)
            绝 = os.path.realpath(净)
        except (OSError, ValueError):
            return 净
        if 绝 == 根真:
            return '.'
        if 绝.startswith(根真 + os.sep):
            return os.path.relpath(绝, 根真)
    return 净


def 整参数(名, 参, 根=''):
    """
    一次调用的参数 → **工具真能吃的那一份**。

    ⚠ **只管"形式"，不管"意思"。** 四条，全部无损：

      ① **工具声明是数的**（schema 里 `type == 'integer'`）→ 抠出里面的整数；
      ② **其他字符串** → 去掉首尾空白、剥掉成对包装的引号；
      ③ `path` 额外去掉尾斜杠，**绝对路径若在 `根` 底下就剥成相对路径**（见 `_整路径`）；
      ④ `all` → `是` / `否`。

    ⚠ **正文参数（`content` / `old` / `new`）一个字都不动** —— 见 `正文参数`。

    ⚠ **"意思对不对"这一层，这里不管。** 模型写「当前目录路径」而不是 `.`，
    我们不猜它想说什么 —— 那是 grammar（让它写不出来）和反馈（报错让它重写）
    该管的事。**事后猜是适配，清单永远补不完。**

    `根` 是**工作目录**（协议层原来不知道它，所以第 ③ 步的绝对路径那半
    一直没法执行）。空就不做那半 —— 那是老行为。
    """
    出 = dict(参 or {})
    型 = _型们(名)
    for 键, 值 in list(出.items()):
        if 键 in 正文参数:
            continue
        if 型.get(键) == 'integer':
            出[键] = _整数字(值)
        elif isinstance(值, str):
            出[键] = _去包装(值)
            if 键 == 'path':
                出[键] = _整路径(出[键], 根)
    if 'all' in 出:
        出['all'] = _整是否(出['all'])
    return 出


def _落在调用里(文, 位):
    """`文[位]` 那个位置是不是落在某个 `<tool_call>` 块**里面**。"""
    前 = 文[:位].lower()
    return 前.count('<tool_call') > 前.count('</tool_call>')


def 剥思维(文):
    """
    把**思维链**切掉，只留可能藏着工具调用的那一段。**解析前必须先过这一道。**

    ⚠⚠ **不过这一道，模型的草稿会被当成命令执行。**

    推理模型的输出长这样：

        <think>
        嗯，用户让我列目录……我应该调用
        <tool_call><function=list_dir><parameter=path>.</parameter></function></tool_call>
        —— 不对，先看看有没有别的办法……
        </think>
        好，我来列一下。
        <tool_call><function=list_dir><parameter=path>.</parameter></function></tool_call>

    上面那个是**草稿里的示例**，下面那个才是真要调的。两个在文本上一模一样，
    `解工具调用` 分不出来 —— 它会把**两个都收下来执行两遍**。
    `write_file` 看不出来（写两遍内容一样），`run_cmd` 是**真会把命令跑两次**。

    ## 切法：切**最早那个"干净的"闭合标记**

    "干净"= **那个位置不在任何 `<tool_call>` 块里面**（`_落在调用里`）。

    我前两版都错在这条上，别捡回来：

      · 第一版："只切第一个 `<tool_call>` 之前的那一段" —— 草稿里的调用排在
        真调用**前面**时完全失效（`</think>` 在草稿调用**之后**，什么都切不掉）。
        而"草稿里带一个示例"正是最常见的情形。
      · 第二版："切第一个闭合标记" —— 会把 `write_file` 正文里的 `</think>`
        **连着一整条调用一起切掉**（在写一段讲思维链标记的文档时就会撞上）。

    合起来的规则：**从头往后找第一个不在调用块里的闭合标记，切到它为止。**

    找不到干净标记的时候分两种，差别很重要：

      · 文字**自己带开标记**（`<think>` 开了没闭）→ 整段就是没写完的草稿，
        回空串。里面出现的任何 `<tool_call>` 都只是它在"想"。**一条都不该收。**
      · 文字里**没有开标记** → 我们看不懂，**原样返回，一个字不动**。
        这一支兜的就是上面那个 `write_file` 的场景：一份结构完整的调用，
        里头 `</think>` 只是参数值的一部分。

    ⚠ 不需要调用方传"提示词有没有把思考位留开着"。R1 蒸馏系那种
    **只吐 `</think>` 不吐 `<think>`** 的，靠的是"闭合标记出现在调用之前"——
    那已经够了。
    """
    文 = 文 or ''
    最早, 位 = None, -1
    候选 = []
    for 闭 in 酒馆协议.思考闭标记:
        i = 文.find(闭)
        while i >= 0:
            候选.append((i, len(闭)))
            i = 文.find(闭, i + 1)
    候选.sort()
    for i, 长 in 候选:
        if not _落在调用里(文, i):
            最早, 位 = i, i + 长
            break
    if 最早 is not None:
        return 文[位:]
    for 标 in 酒馆协议.思考开标记:
        if 标 in 文:
            return ''          # 开着的草稿，没写完 —— 一条都不收
    return 文


# ⚠ **三种形状的兜底全部留着。**
#
# 它们**不再被用来反推"该教哪种形状"**（教什么由本文件上面那两个常量说了
# 算），留着纯粹是因为：**认多一种没有代价，认少一种就是整轮白费。**
# 一个模型可能没照我们的协议写、却写出了它自己那套完全正确的东西 ——
# 那种时候把它判成"格式不合法"，用户看到的会是"模型答非所问"，
# 而真正发生的事是"它做对了、我们没接住"。

def _扫平衡(文, 起):
    """
    从 `文[起]` 的 `{` 开始，找与它配对的那个 `}` 的下标（含）。找不到回 -1。

    ⚠ **不能用「第一个 `{` 到最后一个 `}`」那种切法。** 工具参数里经常
    整个塞着一份代码（`write_file` 的 `content` 就是），里面 `{` `}` 满地
    都是，还有字符串里的引号和转义。所以这里是一个**字符串/转义感知**的
    深度计数器：

        "…"  和 '…' 里的括号不算数（要处理 \\ 转义）
        裸括号才计数

    小模型的 JSON 本来就不严谨（单引号、没转义），所以这里只求**切得准**，
    切出来能不能 parse 交给下一次判断。
    """
    深 = 0
    i = 起
    串 = None           # 当前在哪个引号里：'"' / "'" / None
    while i < len(文):
        c = 文[i]
        if 串:
            if c == '\\':
                i += 2
                continue
            if c == 串:
                串 = None
        elif c in '"\'':
            串 = c
        elif c == '{':
            深 += 1
        elif c == '}':
            深 -= 1
            if 深 == 0:
                return i
        i += 1
    return -1


def _去双括号(文):
    """
    `{{"name": …}}` → `{"name": …}`。**只在字符串字面量之外动。**

    Qwen 系的模板教的是 `<tool_call>{{…}}</tool_call>`（双大括号），实测
    qwen2.5-3b 就是照这个吐的。

    ⚠ **绝不能无脑 `文.replace('{{', '{')`。** 工具参数里整个塞着一份代码是
    常态（`write_file` 的 `content`），代码里出现 `{{`（格式化字符串、
    嵌套字面量、字典推导）太正常了。无脑替换会**静默改坏要写进文件的
    内容** —— 不报错、写进去的是错的，是最坏的一类 bug。
    """
    出 = []
    i = 0
    串 = None
    while i < len(文):
        c = 文[i]
        if 串:
            if c == '\\' and i + 1 < len(文):
                出.append(文[i:i + 2]); i += 2; continue
            if c == 串:
                串 = None
            出.append(c); i += 1; continue
        if c in '"\'':
            串 = c; 出.append(c); i += 1; continue
        # 字符串外才动双括号
        if c == '{' and 文[i:i + 2] == '{{':
            出.append('{'); i += 2; continue
        if c == '}' and 文[i:i + 2] == '}}':
            出.append('}'); i += 2; continue
        出.append(c); i += 1
    return ''.join(出)


def _救换行(文):
    """
    把 JSON 字符串字面量里**没转义的真换行**换成转义写法，再交给 `json.loads`。

    ⚠ **这不是锦上添花，是小模型写多行代码时的常态。** 实测：让它写一个
    三十行的 `todo.py`，它把 `content` 的值直接写成一串**真的换行符**：

        {"name":"write_file","arguments":{"path":"todo.py",
         "content":"from todo import add   ← 这儿是真的 0x0A，不是 \\n
           ..."}}

    JSON 规范里字符串里不许有裸控制字符，`json.loads` 当场报
    `Invalid control character`。而内容是**完全正确**的代码 —— 只是没转义。
    不救的话每次让它写多行文件都会失败，或者更糟：被别的候选解析出半截内容，
    **静默写出一个坏文件**（实测撞到过，写出来的文件头几行粘成了一行）。

    只动字符串**里面**的控制字符；结构部分的空白照旧（那是合法的，不用管）。
    """
    出 = []
    i = 0
    串 = None
    while i < len(文):
        c = 文[i]
        if 串:
            if c == '\\' and i + 1 < len(文):
                出.append(文[i:i + 2]); i += 2; continue
            if c == 串:
                串 = None
                出.append(c); i += 1; continue
            if c == '\n':
                出.append('\\n')
            elif c == '\r':
                出.append('\\r')
            elif c == '\t':
                出.append('\\t')
            else:
                出.append(c)
            i += 1
            continue
        if c in '"\'':
            串 = c
        出.append(c); i += 1
    return ''.join(出)


def _补括号(文):
    """
    把没闭合的 `{` `[` 补上。**字符串/转义感知**，跟 `_扫平衡` 同一套逻辑。

    ⚠ **这不是锦上添花，是必需的。** 小模型写工具调用时**漏掉最后一个右
    大括号是常态**，实测就撞上了：

        {{"name": "edit_file", "arguments": { ... "all": "否"}}
          ↑ 开了 3 个 {，只闭了 2 个 —— 少一个

    这种 JSON 用任何标准解析器都过不了，但内容是**完全正确**的，只是少个
    收尾。不补的话每一轮都会判"格式不合法"然后中止任务，而模型其实做对了。

    只补不删：多出来的右括号不归这里管（那是模型真的写错了，应该报错）。
    """
    栈 = []
    i = 0
    串 = None
    while i < len(文):
        c = 文[i]
        if 串:
            if c == '\\':
                i += 2
                continue
            if c == 串:
                串 = None
        elif c in '"\'':
            串 = c
        elif c in '{[':
            栈.append(c)
        elif c in '}]':
            if 栈:
                栈.pop()
        i += 1
    if not 栈:
        return 文
    补 = ''.join('}' if x == '{' else ']' for x in reversed(栈))
    return 文 + 补


def _取调用(块):
    """
    从一段 `<tool_call>` 的内脏里抠出 `(名字, 参数字典)`。抠不出回 `None`。

    候选按"干净程度"降序试，全试不过才放弃：

        ① 切出平衡的 JSON 区间（`_扫平衡`）—— 最干净，能甩掉后面跟着的废话
        ② 整段原样
        ③ 上面前两个各去一次双大括号（Qwen 教的是 `{{…}}`，实测它就是照这个吐）
        ④ 再各补一次缺失的收尾括号（小模型漏最后一个 `}` 是常态）
        ⑤ 再各救一次没转义的真换行（写多行代码时的常态，见 `_救换行`）

    每一轮都在上一轮的候选上继续加工，所以最后那一批是"去了双括号 + 补了
    括号 + 救了换行"的全套处理 —— 那是小模型写多行文件时最常见的样子。

    ⚠ 切区间用的是 `_扫平衡`，**不是「第一个 `{` 到最后一个 `}`」** ——
    参数里塞着一整份代码时大括号满地都是，那种切法必错。
    """
    import json
    候 = [块.strip()]
    头 = 块.find('{')
    if 头 >= 0:
        尾 = _扫平衡(块, 头)
        if 尾 > 头:
            候.insert(0, 块[头:尾 + 1])
    for 步 in (_去双括号, _补括号, _救换行):
        候 += [步(t) for t in list(候)]
    for 试文 in 候:
        try:
            载 = json.loads(试文.strip())
        except ValueError:
            continue
        if not isinstance(载, dict):
            continue
        名 = 载.get('name') or 载.get('tool') or 载.get('function')
        参 = 载.get('arguments')
        if 参 is None:
            参 = 载.get('parameters') or 载.get('args') or {}
        if isinstance(参, str):
            try:
                参 = json.loads(_救换行(_补括号(_去双括号(参))))
            except ValueError:
                参 = {'_原样': 参}          # 留着给模型看它自己写了什么
        if 名:
            return str(名), (参 if isinstance(参, dict) else {'_原样': 参})
    return None


# ── 第二种形状：XML（**现在这是我们的主协议**）─────────────────────
#
# ⚠ 这一支的历史值得留着：最早加它是因为 Qwen3 系的模板教的就是这套，
# 而我们只认 JSON，于是**一份写得完完整整的网页被整个扔掉**（`stop_reason`
# 还是 `stop`，一个字都没丢）。现在的地位变了 —— 它不再是"顺手多支持一种"，
# 而是**我们自己定的那一种**（理由见文件头：值即原文，零转义）。
#
# 剩下那两种（JSON / GLM）留着兜底，理由见上面那段。

def _参数名们(名):
    """
    这个工具**声明了哪些参数名**。给 `_取XML参数` 判"裸标签 `<path>` 算不算一个参数"。

    ⚠ 这份名单是**从工具定义里读出来的，不是猜的** —— 正因为我们知道
    `write_file` 只有 `path` / `content`，才敢把 `<div>` 当成正文、把
    `<content>` 当成参数。不知道的话这两种标签长得一模一样。
    """
    for 工 in 酒馆工具.定义们:
        函 = 工['function']
        if 函['name'] == 名:
            return set(函['parameters']['properties'])
    return set()


#: 开标签。**宽容到"只要能认出是个开标签"** —— 见 `_取XML参数` 上面那段。
_开标签 = re.compile(r'<\s*([A-Za-z_][\w.\-]*)\s*(?:=\s*([^<>]*?))?\s*>')


def _取XML参数(体, 允许=()):
    """
    从 `<function=…>` 的内脏里抠 `{键: 值}`。

    ⚠⚠ **形状故意放宽，这是被真模型逼出来的。**

    协议教的是 `<parameter=键>值</parameter>`，实测 **Qwen3.5-9B 三条任务里
    两条写走样了**（2026-09-21 真跑，原文）：

        <path>a.py</path>                    ← 忘了 `parameter=`，用了裸标签
        <parameter>count>100</parameter>     ← 把 `>` 当成了键值分隔符
        <parameter=start>0</parameter>       ← 这个是标准写法
        <path>.</parameter>                  ← 开标签对不上收尾标签

    **而它写的值全是对的** —— `a.py`、`print("hello")`、`.` 一个不差。
    只认标准写法的话，这些调用会被整条判成"格式不合法"然后扔掉，模型重写
    一遍还是这样 —— 用户看到的是"这模型带不动"，而真相是**它做到了，我们没接住**。
    按"认多一种没有代价，认少一种就是整轮白费"同一条道理放宽。

    ⚠ **放宽要有边界，不然会啃掉正文。** `write_file` 的 `content` 经常是
    一份 HTML，满篇 `<div>` `<html>` —— 把它们也当成参数的话，写进去的东西
    就被吃掉了。所以裸标签**只在"它正好是这个工具声明的参数名"时才算数**
    （`允许`，从 `酒馆工具.定义们` 读的）。`<div>` 不是 `write_file` 的参数，
    就老老实实当正文。

    ⚠ 值是**原文**，只剥一层包装换行，**绝不用 `strip()`** —— 见下面那段。
    """
    许可 = set(允许)
    词们 = ['parameter', 'function', 'tool_call'] + sorted(许可)
    收尾 = re.compile(r'</\s*(?:%s)\s*>' % '|'.join(re.escape(x) for x in 词们))
    下个参 = re.compile(r'<\s*(?:%s)\b'
                       % '|'.join(re.escape(x) for x in
                                  (['parameter'] + sorted(许可))))

    参 = {}
    位 = 0
    while 位 < len(体):
        m = _开标签.search(体, 位)
        if not m:
            break
        标签 = m.group(1)
        等值 = m.group(2)
        值起 = m.end()
        if 标签 == 'parameter':
            if 等值 is not None:
                键 = 等值.strip()
            else:
                # `<parameter>键>值` / `<parameter>键=值` —— 键在开口之后
                mm = re.match(r'\s*([^<>=]+?)\s*[>=]\s*', 体[值起:])
                if not mm:
                    位 = 值起
                    continue
                键 = mm.group(1).strip()
                值起 += mm.end()
        elif 标签 in 许可:
            # 裸标签：`<path>a.py</path>`
            键 = 标签
        else:
            # 既不是 `parameter`、又不是这个工具声明的参数名 —— 是正文里的
            # 普通标签（写 HTML 时的 `<div>`）。**跳过它继续扫**：
            # 它既不该结束别人的值，也不该自己变成一个参数。
            位 = 值起
            continue
        # 值的终点：**优先找收尾标签**；一个都没有才切在下一个参数的开头。
        # 顺序不能反：正文里的 `<div>` 满地都是，拿"下一个开标签"当终点
        # 会把一份 HTML 切成渣。
        闭 = 收尾.search(体, 值起)
        下个 = 下个参.search(体, 值起)
        if 闭 and (下个 is None or 闭.start() <= 下个.start()):
            值 = 体[值起:闭.start()]
            位 = 闭.end()
        elif 下个 is not None:
            值 = 体[值起:下个.start()]
            位 = 下个.start()
        else:
            值 = 体[值起:]
            位 = len(体)
        # ⚠ **只剥一个首尾换行，绝不用 `strip()`。** 协议教的形状是
        # `<parameter=x>\n值\n</parameter>`，那两层换行是**包装**不是内容；
        # 而 `strip()` 会把值自己的缩进也吃掉 —— 对 `content` 是致命的
        # （写进去的代码整个前几行会粘在一起）。
        if 值.startswith('\n'):
            值 = 值[1:]
        if 值.endswith('\n'):
            值 = 值[:-1]
        if 键:
            参[键] = 值
    return 参


def _取XML调用(块):
    """
    从 `<tool_call>` 的内脏里抠 **XML 形状**的调用。抠不出回 `[]`。

    支持一条 `<tool_call>` 里多个 `<function=…>`（并行调用），也容忍缺
    `</parameter>` / `</function>`（生成被截断）。

    ⚠ **参数名清单要传给 `_取XML参数`**（`允许=`）—— 它靠这个判"裸标签
    `<path>` 算不算一个参数"。见 `_取XML参数` 上面那段。
    """
    if '<function' not in 块:
        return []
    出 = []
    i = 0
    while True:
        头 = 块.find('<function', i)
        if 头 < 0:
            break
        名起 = 块.find('=', 头)
        名尾 = 块.find('>', 头)
        if 名起 < 0 or 名尾 < 名起:
            break
        名 = 块[名起 + 1:名尾].strip()
        下个 = 块.find('<function', 名尾)
        体 = 块[名尾 + 1:下个 if 下个 >= 0 else len(块)]
        # ⚠ **名字里混进尖括号/花括号，就当这条不存在** —— 别拿它去"调工具"。
        #
        # 什么时候会混进来：**强制轮的预填本身就是 `<tool_call>\n<function=`**，
        # 而预填必须和生成拼在一起再解析（不拼的话开标签丢了，见 `预填串`）。
        # 万一模型在预填之后**又自己重写了一遍 `<tool_call>`**，两段就会粘成
        # `<function=<tool_call>` —— 抠出来的"名字"是 `<tool_call`，
        # 一个根本不存在的工具。报给用户的会是「没有 `<tool_call` 这个工具」，
        # 纯噪声；而**真那条调用就在后面等着被认**。
        #
        # 跳过它继续找下一个 `<function`，什么都不会丢。
        if 名 and not any(c in 名 for c in '<>{}'):
            净 = 规整工具名(名)
            出.append({'名': 净, '参数': _取XML参数(体, 允许=_参数名们(净)),
                      '原始': 体})
        if 下个 < 0:
            break
        i = 下个
    return 出


# ── 第三种形状：GLM 的 `<arg_key>`/`<arg_value>` ──────────────────
#
# ⚠ **这是 GLM-4-9B-Chat 聊天模板里明文教的形状**（2026-09-20 核过官方
# `tokenizer_config.json`），既不是 JSON、也不是上面那种 XML：
#
#     <tool_call>list_dir
#     <arg_key>path</arg_key>
#     <arg_value>"."</arg_value>
#     </tool_call>
#
# **函数名裸写在 `<tool_call>` 后面**，参数是 `<arg_key>`/`<arg_value>` 成对。
# 值是模板拿 `|tojson` 渲染的，所以字符串带着 JSON 的引号。
#
# ⚠ 也就是说"工具格式 = JSON 还是 XML"这个二选一**装不下 GLM** ——
# 只认那两种的话，GLM 的调用会一路走到"解析失败"。**它其实是照模板做对了的**，
# 白费一整轮。所以补第三种：认多一种没有代价。

def _GLM值(文):
    """
    GLM 的一个 `<arg_value>` → Python 值。

    模板拿 `|tojson` 渲染，所以正常情况值就是 JSON 文本（字符串带引号）。

    ⚠ **但不能见到 JSON 就当 JSON 收。** `write_file` 的 `content` 经常整份
    就是一个 `.json` 文件的内容，模型原样写出来是 `{"a": 1}` —— 那会被
    `json.loads` 解成 dict，工具拿到的是字典而不是字符串，**写进去的东西
    全是错的**（而且不报错）。所以只认标量（字符串 / 数字 / 真假），
    解出来是容器就退回原文。我们的工具参数没有一个是对象或数组，
    这条规则不会有副作用。
    """
    import json
    净 = (文 or '').strip()
    if not 净:
        return ''
    try:
        解 = json.loads(净)
    except ValueError:
        return 文
    if isinstance(解, (dict, list)):
        return 文
    return 解


def _取GLM参数(体):
    """从 GLM 形状的内脏里抠 `{键: 值}`。见 `_取GLM调用` 上面那段。"""
    import re
    完整 = re.findall(
        r'<arg_key>(.*?)</arg_key>\s*<arg_value>(.*?)</arg_value>', 体, flags=re.S)
    if 完整:
        对们 = 完整
    else:
        # ⚠ **只有一对都没收全时才走这条**（生成被截断，少了 `</arg_value>`）。
        #
        # 截断那版得靠"下一个 `<arg_key>` 或末尾"来断值 —— 所以**绝不能当
        # 常规路径用**：值里真出现 `<arg_key>` 字样（`write_file` 写一段
        # 讲这个格式的文本就完全可能）时，它会把那儿当终点，**静默把参数
        # 截断**。上面那版拿 `</arg_value>` 当终点，不受这个影响。
        #
        # 代价是"最后一个参数被截断"这种半截情况会被整条丢掉 —— 但那本来
        # 就要重来一轮，**丢掉比写进一个半截值强**（后者不报错、错得看不见）。
        对们 = re.findall(
            r'<arg_key>(.*?)</arg_key>\s*<arg_value>'
            r'(.*?)(?=</arg_value>|<arg_key>|$)', 体, flags=re.S)
    if not 对们:
        return {}
    参 = {}
    for 键, 值 in 对们:
        键 = 键.strip()
        if not 键:
            continue
        # ⚠ 只剥一层包装换行，不用 `strip()`，理由同 `_取XML参数`。
        # （这里其实更安全：GLM 的值是 `|tojson` 渲染的，换行是 `\n`
        #  转义而不是真换行，不存在"吃掉内容缩进"的风险。）
        if 值.startswith('\n'):
            值 = 值[1:]
        if 值.endswith('\n'):
            值 = 值[:-1]
        参[键] = _GLM值(值)
    return 参


def _取GLM调用(块):
    """
    从 `<tool_call>` 的内脏里抠 **GLM 形状**的调用。抠不出回 `[]`。

    ⚠ 判据放在 **`<arg_key`** 上，不是 `<tool_call` —— 外层已经把块切出来了，
    这里只负责认"这是不是 GLM 那一种"。认不出就回空，让 `解工具调用` 继续往下走。
    """
    if '<arg_key' not in 块:
        return []
    名前 = 块[:块.find('<arg_key')].replace('</tool_call>', '')
    名 = ''
    for 行 in 名前.splitlines():
        行 = 行.strip().strip('`').strip().strip('"').strip("'").strip()
        # 名字行里混进标签或者花括号就说明这不是干净的"裸函数名"，放弃
        if 行 and not any(c in 行 for c in '<>{}'):
            名 = 行
            break
    if not 名:
        return []
    return [{'名': 规整工具名(名), '参数': _取GLM参数(块), '原始': 块}]


#: 模型爱用的别名 → 我们的规范名。归一不到就当一个不认识的工具报错，
#: **不是崩** —— 把"没有这个工具"喂回模型，它多半会换个名字重试。
工具别名 = {
    'read': 'read_file', 'readfile': 'read_file', 'cat': 'read_file',
    'ls': 'list_dir', 'list': 'list_dir', 'listdir': 'list_dir', 'dir': 'list_dir',
    'grep': 'search', 'find': 'search', 'search_file': 'search',
    'write': 'write_file', 'writefile': 'write_file', 'create_file': 'write_file',
    'edit': 'edit_file', 'replace': 'edit_file', 'patch': 'edit_file',
    'run': 'run_cmd', 'bash': 'run_cmd', 'shell': 'run_cmd',
    'cmd': 'run_cmd', 'execute': 'run_cmd', 'terminal': 'run_cmd',
}


def 规整工具名(名):
    """模型给的工具名 → 我们的规范名。认不出来就原样回（让上层报"没这个工具"）。"""
    净 = str(名 or '').strip().strip('`').strip()
    小 = 净.lower().replace('-', '_').replace(' ', '_')
    if 小 in 工具别名:
        return 工具别名[小]
    return 小 or 净


def 解工具调用(文, 原生=None, 给过工具=False, 认得的=()):
    """
    从模型输出里抠出工具调用。回 `(调用们, 剩下的正文, 解析失败吗)`。

    `调用们` 每项是 `{'名': str, '参数': dict, '原始': str}`。

    分级，从强到弱：

      ① **原生字段**（`原生` 参数）：某些 chat_format 会回填 `tool_calls`。
         这条路是**将来升级绑定之后白赚的**，现在实测拿不到。留着不删 ——
         它不依赖任何"模型会不会调工具"的判断。
      ② **抠 `<tool_call>…</tool_call>`**（大小写不敏感，容忍缺闭合）。
         里面**三种形状都认**，按这个顺序试，认出来就不往下走：
         XML（**我们的主协议**，见 `_取XML调用`）、
         GLM（`<arg_key>`/`<arg_value>`，见 `_取GLM调用`）、
         JSON（Qwen2.5 系模板教的）。
         同一条 `<tool_call>` 里名字不认得也放行 —— 理由见 `收` 里那段。
      ③ **markdown 围栏里的 JSON** —— 见下面那条注释，要过一道名字校验。
      ④ 整段就是个 JSON 对象且有 `name` 字段 —— **只在这次确实给模型看过
         工具定义时才走**（`给过工具`）。不给这个条件的话，模型正常回答里
         写一段带 `name` 键的示例 JSON 就会被当成工具调用。

    ⚠ **解析失败必须能被上层看出来**（第三个返回值）。把"模型写了
    `<tool_call>` 但格式崩了"静默当成最终回答的话，用户看到的是模型
    答非所问，完全不知道是格式问题。
    """
    import re
    文 = 文 or ''
    出 = []

    # ① 原生字段
    for 条 in (原生 or []):
        try:
            函 = 条.get('function') or {}
            名 = 函.get('name') or 条.get('name')
            参 = 函.get('arguments')
            if 参 is None:
                参 = 条.get('arguments') or {}
            if isinstance(参, str):
                try:
                    import json
                    参 = json.loads(参)
                except ValueError:
                    参 = {'_原样': 参}
            if 名:
                出.append({'名': 规整工具名(名), '参数': 参 or {}, '原始': ''})
        except (AttributeError, TypeError):
            continue

    def 收(块, 原始, 查名=True):
        取 = _取调用(块)
        if not 取:
            return False
        名 = 规整工具名(取[0])
        # ⚠ **名字这道门槛只该管"猜"的那两条路（③ 围栏 / ④ 裸 JSON），
        # 不该管 `<tool_call>`。**
        #
        # 门槛的来历见 ③ 那段：正文里展示一段带 `name` 键的示例 JSON 太常见，
        # 收了就成了"它只是举个例子，我们却真去改文件"。可 `<tool_call>` 标签
        # 是**模型明确在说"这是工具调用"**，没有误判的余地。
        #
        # 让它管 ② 会怎样（实测过）：模型调了个名字稍有不同的工具
        # （`save_file` 这种），JSON **完全合法**，整条却被静默丢掉，然后报给
        # 用户一句「格式不合法」—— 而格式明明是合法的。用户于是跑去换模型、
        # 改提示词，真正该做的却是**让它换个名字重试**。
        #
        # 放行之后正好接上 `酒馆助手.跑` 里本来就有的一条路：
        # 「没有 xxx 这个工具。能用的只有：…」喂回去，它多半自己就改对了。
        if 查名 and 认得的 and 名 not in 认得的:
            return False
        出.append({'名': 名, '参数': 取[1], '原始': 原始})
        return True

    # ② `<tool_call>` 块
    #
    # ⚠ **① 已经收到东西了就别再抠文本。** 原生模式下工具调用走 `tool_calls`
    # 通道，可正文里**很可能又写了一遍** —— 协议教的写法就是
    # `<tool_call>…</tool_call>`，两边都给是模型的常态。不拦的话同一个调用
    # 会被收两遍、执行两遍：`write_file` 看不出来，`run_cmd` 是真会把命令跑两次。
    捞过 = 0
    块们 = []
    if not 出:
        块们 = re.findall(r'<tool_call>\s*(.*?)\s*</tool_call>', 文,
                         flags=re.S | re.I)
        if not 块们:
            # 缺闭合（生成被截断）也要捞 —— 从最后一个开标签到末尾
            位 = 文.lower().rfind('<tool_call>')
            if 位 >= 0:
                块们 = [文[位 + len('<tool_call>'):]]
    for 块 in 块们:
        块 = 块.strip()
        if 块.startswith('```'):
            块 = re.sub(r'^```[a-zA-Z_]*\s*', '', 块)
            块 = re.sub(r'\s*```$', '', 块).strip()
        # ⚠ **顺序是 XML → GLM → JSON，前面认出来了就不走后面。**
        #
        # XML 放第一位是因为**它是我们的协议**，绝大多数调用都长这样；
        # 而 JSON 那一支（`收`）在"参数里整份塞着内容"时会误伤 ——
        # `write_file` 写一份 `.json` 文件、内容里正好有 `"name"` 键的话，
        # `收` 会把它当成一次**别的**调用收走（查名在这里是关的，拦不住），
        # 而真正的那次调用被跳过。XML 那支不存在这个问题：
        # 它只认 `<function=` / `<parameter=`，值一律当原文。
        #
        # （反过来"JSON 块里出现 `<function=` 字样"是 XML 支的风险，但那种
        #  模型本来就不是我们的目标 —— 它只是兜底，抖一下可以接受。）
        本块 = 0
        for 条 in _取XML调用(块):
            出.append(条)
            捞过 += 1
            本块 += 1
        # ⚠ 兜一层 **GLM 形状**（`<arg_key>`/`<arg_value>`）：它照自己模板
        # 吐对了也照样会被判成"没调工具"，整轮白费。
        if not 本块:
            for 条 in _取GLM调用(块):
                出.append(条)
                捞过 += 1
                本块 += 1
        # ⚠ 最后兜 **JSON**（Qwen2.5 系模板教的那套）。见上面那段顺序说明。
        # `查名=False` —— 这里是 `<tool_call>` 标签里，模型是**明确在调工具**，
        # 名字认不认得都该放行（理由见 `收` 里那段）。名字真错了，上层会把
        # "能用的只有…"喂回去让它重试，比在这儿静默丢掉强得多。
        if not 本块 and 收(块, 块, 查名=False):
            捞过 += 1

    # ③ markdown 围栏里的 JSON
    #
    # ⚠ 有模型**会用围栏而不是 `<tool_call>` 标签**。实测 R1-Distill-Qwen-7B
    # 在文本协议下就是这么吐的：
    #
    #     好的，我来帮你列出当前目录下的所有文件。
    #     ```json
    #     {"name": "list_dir", "arguments": {"path": ".", "depth": 1}}
    #     ```
    #
    # 内容完全正确，只是包装形式不对。早先只认 ```` ```tool_call ````，
    # 这种全被判成"没调工具"，任务当场结束。
    #
    # ⚠ **但不能见围栏就收。** 模型在正文里展示一段带 `name` 键的示例 JSON
    # 太常见了，收了就是"它只是举个例子，我们却真去改文件"。
    # 所以加一道硬门槛：**解析出来的工具名必须在下发过的工具清单里**
    # （`认得的`）。示例 JSON 里的名字几乎不可能正好撞上我们的工具名。
    if not 出 and 认得的:
        for 块 in re.findall(r'```[a-zA-Z_]*\s*(.*?)\s*```', 文, flags=re.S):
            块 = 块.strip()
            if 收(块, 块):
                捞过 += 1

    # ④ 裸 JSON 兜底（只在这次确实给模型看过工具定义时才敢用）
    if not 出 and 给过工具:
        净 = 文.strip()
        if 净.startswith('{') and 净.endswith('}'):
            取 = _取调用(净)
            if 取:
                出.append({'名': 规整工具名(取[0]), '参数': 取[1], '原始': 净})

    # 剩下的正文：把工具调用那几段挖掉，其余的留给用户看
    残 = re.sub(r'<tool_call>\s*.*?\s*</tool_call>', '', 文, flags=re.S | re.I)
    开 = 残.lower().find('<tool_call>')          # 缺闭合的尾巴也要挖掉
    if 开 >= 0:
        残 = 残[:开]
    if 捞过:
        # 围栏里的内容已经当成工具调用收走了，别在正文里再露一遍
        残 = re.sub(r'```[a-zA-Z_]*\s*.*?\s*```', '', 残, flags=re.S)
    残 = 残.strip()

    失败 = bool(出 == [] and ('<tool_call' in 文.lower()))
    return 出, 残, 失败
