# ══ 基础 ═══════════════════════════════════════════════════════════

def 模板文本(实例):
    """这个模型自带的聊天模板原文。取不到回空串（**不回 None**，免得调用方漏判）。"""
    try:
        return (实例.metadata or {}).get('tokenizer.chat_template') or ''
    except Exception:
        return ''


def 词(实例, 编号):
    """
    token 编号 → 它的字面文本。

    ⚠ `special=True` 不能省：`<|im_start|>` 这类特殊 token
    **只有开这个才解得出来**，否则回空串，模板里那个
    `bos_token` / `eos_token` 就成了空占位。
    """
    try:
        编号 = int(编号)
        if 编号 < 0:
            return ''
        return 实例.detokenize([编号], special=True).decode('utf-8', 'replace')
    except Exception:
        return ''


# ══ 族 ═════════════════════════════════════════════════════════════
#
# ⚠ **族是用来"兜底"和"补停止串"的，不是用来决定怎么渲染的。**
# 怎么渲染由模型自带的模板说了算 —— 那一份比我们任何手写都准。
# 只有模板**缺失**时才轮到族默认上场，那是救急，不是主路。

#: `general.architecture` 前缀 → 族名。**按前缀匹配**，所以 `qwen35` / `qwen3`
#: / `qwen2` 都会落到 `'qwen'`。
#:
#: ⚠ **Mixtral 故意没列。** 它在 llama.cpp 里的 arch 就是 `llama`，所以
#: `('mixtral', …)` 那条**永远轮不到**（`llama` 在前面先命中）—— 留着是死规则，
#: 只会让人以为它有用。同理，所有"以别人底座跑的模型"（Mixtral / 各种 llama
#: 底座微调）在 arch 这一层都分不开，**这本来就是 arch 的信息量上限**。
族头 = (
    ('qwen', 'qwen'), ('glm', 'glm'), ('chatglm', 'glm'),
    ('phi', 'phi'), ('llama', 'llama'), ('gemma', 'gemma'),
    ('mistral', 'mistral'),
)

#: 每个族的**回合标记** —— 模板不一定给全，补齐它防"答完不停、自己把用户
#: 的话也演了"。这些串模型**只会在开新回合时吐**，所以拿它们当停止串是安全的。
#:
#: ⚠ **这张表还没在真模型上验过**（截至 2026-09-20）。接进链路时要盯着：
#: 会不会误伤 —— 万一某个串会在正常输出里出现，就会把回复从中间截断。
#: 尤其 `gemma` 那两条（`<start_of_turn>` 出现的场合比别的宽）。
族停 = {
    'qwen': ('<|im_end|>', '<|im_start|>'),
    'glm': ('<|user|>', '<|system|>', '<|observation|>'),
    'phi': ('<|end|>', '<|user|>', '<|system|>', '<|assistant|>'),
    'llama': ('<|eot_id|>', '<|start_header_id|>', '<|end_header_id|>'),
    'gemma': ('<end_of_turn>', '<start_of_turn>'),
    'mistral': ('[INST]', '[/INST]'),
}


def _库模板(常量名):
    """
    从 `llama-cpp-python` 里取**它自带的官方模板常量**。取不到回空串。

    ⚠ 为什么绕这一道：那几份常量是库从各家 `tokenizer_config.json` 抄下来的，
    **比我们凭记忆手写的可信**。凡是库里有现成的，一律不自己写。
    """
    try:
        import llama_cpp.llama_chat_format as 格式
        return getattr(格式, 常量名, '') or ''
    except Exception:
        return ''


#: 模板缺失时的兜底模板 —— **best-effort，不是精确还原**。
#:
#: ⚠ 它是救急用的：一个 GGUF 的模板丢了，用这个比**静默退成 llama-2** 强得多
#: （那等于拿 `[INST]` 去喂一个 Qwen，必崩）。但**能不用就别用** ——
#: 换一个带模板的量化重下，永远比这个准。
#:
#: ⚠ **凡是库里有官方常量的，一律用库的**（`qwen`/`llama`/`mistral` 三份）。
#: 自己手写的只有 `glm` / `phi`，而且那两份**拿真模型对过**：
#:
#:   `phi`  对过 `Phi-3.5-mini-instruct-Q4_K_M.gguf` —— 形状完全一致，只少了
#:          "system 内容为空就不渲染"和"未知 role 跳过"两个边角。
#:   `glm`  对过 `GLM-Z1-9B-0414-Q4_K_M.gguf` —— `[gMASK]<sop>` / `<|role|>`
#:          标记 / 收尾 `<|assistant|>` 都对得上，但**少了它对历史的
#:          `content.split('</think>')[-1]`**（推理模型的历史思维链不会被剥）。
#:          兜底场景下能接受，但要知道它不是等价还原。
#:
#: ⚠ **`gemma` 故意没有。** Gemma 没有 `system` 角色、模板形状也特殊，手写一份
#: 猜错的**比"报出来让人换个量化"更坏**。宁可兜不住，也不喂错的东西。
族默认模板 = {
    'qwen': _库模板('CHATML_CHAT_TEMPLATE'),
    'llama': _库模板('LLAMA3_INSTRUCT_CHAT_TEMPLATE'),
    'mistral': _库模板('MISTRAL_INSTRUCT_CHAT_TEMPLATE'),
    'phi': ("{% for m in messages %}{{'<|' + m['role'] + '|>' + '\n' + m['content']"
            " + '<|end|>' + '\n'}}{% endfor %}"
            "{% if add_generation_prompt %}{{'<|assistant|>' + '\n'}}{% endif %}"),
    'glm': ("[gMASK]<sop>{% for m in messages %}<|{{ m['role'] }}|>\n{{ m['content'] }}"
            "{% endfor %}{% if add_generation_prompt %}<|assistant|>{% endif %}"),
}


def 族(实例):
    """
    这个模型属于哪个族。认不出回 `''`（**不要瞎猜一个**）。

    读的是 `general.architecture`（如 `qwen35` / `glm4` / `phi3`）。
    """
    try:
        a = str((实例.metadata or {}).get('general.architecture') or '').lower()
    except Exception:
        return ''
    for 头, 名 in 族头:
        if a.startswith(头):
            return 名
    return ''


def 停止词(实例):
    """
    这个族的**回合标记**，补在模板给的停止串后面。

    ⚠ 为什么需要：模板给的 `stop` 只有 eos（比如 Qwen 的 `<|im_end|>`、
    Phi 的 `<|endoftext|>`）。模型**答完想接着演用户**时吐的是回合标记
    （GLM 的 `<|user|>`、Llama3 的 `<|eot_id|>`），那个不在 stop 里就拦不住，
    表现是"它自己把用户的话也写了"。
    """
    return list(族停.get(族(实例), ()))


