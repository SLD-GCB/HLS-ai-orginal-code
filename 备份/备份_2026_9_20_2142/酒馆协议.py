#: 占位符 → `填卡` 取值的键。**对齐 SillyTavern 的 `{{char}}` / `{{user}}`**，
#: 这样外面的角色卡能直接吃进来；同时认一整套中文别名，用户手写也顺手。
#:
#: ⚠ **能填的只有 `角色卡` 里真有的列**（名字/简介/人设/开场白/示例对话）。
#: `场景` 是**故意留在这儿但填不上**的：`角色卡` 里没有这一列（场景靠
#: 开场白 + 会话预设拼出来），所以要靠调用方用 `额外=` 喂。
#: **喂不上就原样留着**，不假装认识 —— 见 `填卡` 里那条。
占位符 = {
    'char': '名字', '角色': '名字', '角色名': '名字', 'name': '名字',
    'user': '用户', '用户': '用户', 'persona': '用户', '用户名': '用户',
    'description': '简介', 'desc': '简介', '简介': '简介',
    'personality': '人设', '人设': '人设',
    'greeting': '开场白', 'first_message': '开场白', '开场白': '开场白',
    'examples': '示例对话', 'example_dialogue': '示例对话', '示例对话': '示例对话',
    'scenario': '场景', '场景': '场景',
}


def 填卡(文, 角色=None, 用户='', 额外=None):
    """
    把 `{{char}}` / `{{user}}` 这类占位符换成实际值。**认不出的一律原样留着。**

    ⚠ **这是"外层"那半** —— 跟模型无关，纯字符串。它管的是
    "角色设计怎么写才能搬到别的软件去"，跟内层（模板怎么渲染）是两件事。

    ⚠ **认不出、或者这儿没东西喂，就原样留着，绝不删。** 两条理由：

      · 用户写错一个占位符（`{{chra}}`），看到的就是 `{{chra}}` 留在正文里
        —— 一眼能改。静默删掉的话，他永远不知道自己写错了什么。
      · **我们只填 `角色卡` 里真有的列。** `{{场景}}` 在 `角色卡` 里没有对应
        列 —— 它**不会被填成空串**，而是原样留着，用户一眼看得出"这个占位符
        这儿没东西喂"。
        （早先的写法是把它初始化成 `''` 然后**再没人管**，等于**假装认识**，
        而且跟 `示例对话` 不一致 —— 同一个函数里一半填一半不填。）

    `额外` 是 `{占位符名: 值}`，**在 `角色卡` 之上覆盖** —— 给调用方补
    `场景` 这类自己算出来的东西用。
    """
    if not 文:
        return 文 or ''
    值 = {'用户': (用户 or '').strip()}
    if 角色 is not None:
        取 = lambda k: (getattr(角色, k, '') or '').strip()      # noqa: E731
        值['名字'] = 取('名字')
        值['简介'] = 取('简介')
        值['人设'] = 取('人设')
        值['开场白'] = 取('开场白')
        值['示例对话'] = 取('示例对话')
    for k, v in (额外 or {}).items():
        值[str(k).strip()] = str(v or '').strip()
    import re

    def 换(命):
        键 = 占位符.get(命.group(1).strip().lower())
        if 键 is None or 键 not in 值:
            return 命.group(0)          # 认不出 / 这儿没东西喂 → **原样留着**
        return 值[键]

    return re.sub(r'\{\{\s*([A-Za-z_\u4e00-\u9fff]+)\s*\}\}', 换, 文)


def 填默认模板(实例, 开关=True):
    """
    这个模型该用哪份模板：**自带的优先，没有才轮到族默认**。

    回 `(模板文本, 是不是兜底)`。两个都空 = 兜不了，调用方该报错让人换量化。

    ⚠ **族默认是 best-effort，不是精确还原。** 它存在的唯一理由是
    **别让库静默退成 llama-2**（那等于拿 `[INST]` 喂 Qwen，必崩）。
    真碰上模板丢了的 GGUF，**换个量化重下永远比这个准**。
    """
    自 = 模板文本(实例)
    if 自:
        return 自, False
    if not 开关:
        return '', False
    return 族默认模板.get(族(实例), ''), True


# ══ 控制开关 ═══════════════════════════════════════════════════════
#
# ⚠ **接线原则：会改变"发出去什么"的，默认都关；保护性的，默认开。**
#
# 理由是项目一贯那条"别牵连现有可用链路"：`要点复述` / `预填` 会改动提示词，
# 而它们的收益**只在部分模型上体现**（实测 GLM-Z1 有改善、Qwen 本来就听话）
# —— 默认开等于**拿全体换局部**。反过来 `停止词` / `分流` 只会"少说"不会
# "多说"，错也错在保守那一侧，所以默认开。

def _拆禁吐(v):
    """
    用户在设定里写的"额外要掐的东西"。**三种写法都认**：列表 / 换行分隔 / 逗号分隔。

    ⚠ 为什么要认三种：会话预设那一格是**能手打的 JSON**，用户想写
    `"禁吐": ["xxx"]` 还是 `"禁吐": "xxx\\nyyy"` 都该能用。写坏了当没写、
    **不抛** —— 跟 `读JSON` 那条"坏配置不该让功能打不开"一个道理。
    """
    if not v:
        return ()
    if isinstance(v, (list, tuple)):
        return tuple(str(x).strip() for x in v if str(x).strip())
    import re
    return tuple(x.strip() for x in re.split(r'[\n,，;；]', str(v)) if x.strip())


def 取控制(设定):
    """
    从会话设定里取"这次生成的人格控制"。**全都是可选的，缺了就按默认。**

    回 `{'要点', '预填', '分流', '中间层', '禁吐'}`：

        `要点`   一两句角色核心，复述到**最后一条 user 消息末尾**（见 `锁人格`）。
                 默认从 `设定['__要点__']` 取 —— 那是 `拼提示` **按角色卡算好
                 塞进去的**（跟 `__记忆__` 一个路子），用户不用管。
                 ⚠ **但要不要用它，得用户在设定里写 `人格锁='开'`** ——
                 默认**关**（见上面那段接线原则）。
        `预填`   替模型开头的几个字（`渲染` 的 `预填`）。**默认空** ——
                 它得用户自己写（会话预设里手填），我们编不出来，硬编就是替用户
                 决定角色该怎么开口。
        `分流`   思维链剥不剥。`'自动'`（默认）交给 `该分流吗` 判；
                 `'开'` / `'关'` 由用户说了算 —— 判定错了时这是逃生口。
        `中间层` 解码期干预的总开关。`'自动'`（默认）**开**，写 `'关'` 全关。
                 ⚠ **它跟上面三样反着**：那个默认关，这个默认开 ——
                 因为它只会"少说"不会"多说"（松紧原则见上面那段）。
        `禁吐`   用户额外要掐的东西（`_拆禁吐` 那一套写法）。默认空，
                 意味着只用 `默认禁吐`。
    """
    设 = 设定 or {}
    锁 = str(设.get('人格锁') or '').strip().lower()
    要点 = '' if 锁 in ('关', 'off', '0', '否', '不') else \
        (str(设.get('__要点__') or '').strip() if 锁 in ('开', 'on', '1', '是') else '')
    return {'要点': 要点,
            '预填': str(设.get('预填') or '').strip(),
            '分流': str(设.get('分流') or '自动').strip() or '自动',
            '中间层': str(设.get('中间层') or '自动').strip() or '自动',
            '掐思维': str(设.get('掐思维') or '关').strip() or '关',
            '禁吐': _拆禁吐(设.get('禁吐'))}


def 该分流(控, 实例, 提示词, 名字=''):
    """
    这次到底开不开分流 —— 把用户的三态（自动/开/关）和 `该分流吗` 合起来。

    ⚠ 用户写 `'关'` 就是关，**不再问模型** —— 那是他踩过坑之后的自救开关，
    不能被"自动判定"覆盖掉。反过来 `'开'` 也不问 —— 他明确要剥。
    """
    选 = str((控 or {}).get('分流') or '自动').strip()
    if 选 == '关':
        return False
    if 选 == '开':
        return True
    return 该分流吗(实例, 提示词, 名字)


