#: 自检用的探针。挑一个**几乎不可能在正常文本里出现**的形状。
系统探针 = '《协议层探针·系统·9f3a》'
用户探针 = '《协议层探针·用户·9f3a》'


def 认工具(模板):
    """
    这个模板认不认**顶层** `tools` —— 也就是 `tools=` 传下去它会不会渲染。

    ⚠ **判据是模板里有没有 `tools` 这个变量，不是 `tool_call`。** 这两个
    容易搞混，实测踩过：

        qwen2.5-3b      有 `{%- if tools %}` 那段，把工具定义渲染进提示词   → 认
        R1-Distill-Qwen 模板里**没有** `tools`，但**有** `tool_call`
                        （它只是渲染 role='tool' 的历史消息）              → 不认

    按 `tool_call` 判的话 R1 会被判成"认"，于是我们传了 `tools=` 但模板
    根本没渲染进去 —— 模型压根不知道有哪些工具，表现是**完全无视工具、
    自顾自地思考**。

    ⚠ **`item['tools']` 那种"挂在消息上"的写法要单独判死。** 实测
    `glm-4-9b-chat`（2024 版）的模板写的是 `{% if item['tools'] is defined %}` ——
    工具挂在**某条 message** 上，而 `llama-cpp-python` 只传顶层，所以这种
    模板**永远收不到我们下发的 `tools=`**。只看 `'tools' in 模板` 会把它
    判成"认"，然后走原生、传了 `tools=`、模板一个字没渲染。

    ⚠ **注意 `GLM-Z1-9B-0414` 用的是顶层写法，判出来是"认"** —— 所以
    "GLM 的模板把工具挂在消息上"这句话**只对 2024 那版成立，别一概而论**。
    """
    模板 = 模板 or ''
    import re
    if re.search(r"\w+\s*\[\s*['\"]tools['\"]\s*\]", 模板):
        return False
    return 'tools' in 模板


def 画像(实例):
    """
    这个模型**到底是什么样** —— 一次性问清楚，全链路共用。

    回的字典：

        `模板`      `tokenizer.chat_template` 原文（可能空）
        `族`        认出来的族名（可能空）
        `arch`      `general.architecture`
        `停`        这个族该补的回合标记
        `认system`  **渲染自检**：把我们的一段探针当 system 发过去，看它
                    出不出现在渲染结果里 —— **实证，不是查模板字符串**
        `认tools`   模板认不认顶层 `tools`
        `回退`      模板缺失（= 库会静默退成 llama-2，必须报出来）

    ⚠ **`认system` 必须真渲染一次，不能查字符串。** 这个项目的字符串判据
    已经被骗过两次（`tool_call` vs `tools`、`item['tools']`），不打算来第三次。
    `GLM-Z1` 的模板里就同时有 `'system'` 字样**和**一段被 `{%- if tools -%}`
    包着的人设块 —— 查字符串根本分不清它到底认不认。

    ⚠ **不缓存。** 它便宜（一次 jinja 渲染 + 一次小 tokenize，**不跑推理**），
    而且按 `id(实例)` 缓存有"对象回收后 id 被复用"的坑。调用方要缓存自己缓存。
    """
    模板 = 模板文本(实例)
    出 = {'模板': 模板,
         '族': 族(实例),
         'arch': '',
         '停': 停止词(实例),
         '认system': False,
         '认tools': 认工具(模板),
         '回退': not 模板}
    try:
        出['arch'] = str((实例.metadata or {}).get('general.architecture') or '')
    except Exception:
        pass
    if 模板:
        试 = 渲染(实例, [{'role': 'system', 'content': 系统探针},
                        {'role': 'user', 'content': 用户探针}])
        出['认system'] = bool(试 and 系统探针 in 试['串'])
    return 出


# ══ 渲染 ═══════════════════════════════════════════════════════════
#
# ⚠ **喂法必须跟库内部一模一样，否则就不是"等价替换"。**
# 库的 `chat_formatter_to_chat_completion_handler`（`llama_chat_format.py:658-666`）
# 是 `tokenize(串, add_bos=not added_special, special=True)` 之后**喂 token 表**，
# 并且把 formatter 给的 `stop` **追加**到调用方给的 `stop` 后面。
# 喂字符串的话 `create_completion` 会按 `tokenizer.ggml.add_bos_token` 自己决定
# 加不加 BOS —— 两条路可能差一个 BOS，而**多一个 BOS 正是 GLM 那类前缀敏感
# 模型最怕的事**。所以这里逐条照抄它的喂法。

def 渲染(实例, 消息, 预填='', 用默认模板=False):
    """
    `messages` → 模型真正吃掉的那串。回一个 dict，**渲染不了回 `None`**。

    回的字典：

        `串`       渲染出来的提示词原文（给人看的）
        `token们`  同一个串的 token 表（**喂给 `create_completion` 的是这个**）
        `停`       这个模板要求的停止串（要紧跟调用方给的 stop 后面）
        `停止`     模板给的 stopping_criteria（可能没有）
        `默认模板` 这次是不是用的族默认模板（`用默认模板=True` 且模板缺失时）

    `预填` 是**替模型开个头**（见 `锁人格`）：它被拼在**渲染结果的最末尾**，
    也就是模板已经吐完 `<|assistant|>` 之后 —— 模型只能接着这几个字往下写。

    ⚠ **为什么预填只能在这儿做、不能塞进 `messages`：** 标准模板会给每条
    消息补收尾符（`<|im_end|>` / `<|end|>` / `<|endoftext|>`），塞进 messages
    的 assistant 会被渲染成**一句已经说完的话**，模型看到的是"我说过了"，
    不是"我正在说"。只有**渲染完之后再接字**才是真正的续写起点。
    **`create_chat_completion` 那条路做不到这件事** —— 这也是拿到渲染权的价值之一。

    ⚠ **`用默认模板=True` 才允许走族默认。** 默认是 `False` —— 因为
    "拿一个手写的近似模板顶上"和"报出来让用户换个量化重下"之间，
    后者更稳。这个开关留给调用方按场合决定（界面上一句"要不要试试兜底"）。

    ⚠ **回 `None` 时调用方不许自己猜一个格式顶上** —— 那正是
    `llama-cpp-python` 干的事：模板缺了就**静默退成 `llama-2`**，而
    `verbose=False` 时连声响都没有。退回旧路可以，但**必须留下原因**给人看。
    """
    模板, 用默认 = 填默认模板(实例, 开关=用默认模板)
    if not 模板:
        return None                       # 没有插槽说明书，说什么都白搭
    try:
        import llama_cpp.llama_chat_format as 格式
    except Exception:
        return None
    try:
        eos = 实例.token_eos()
    except Exception:
        eos = -1
    try:
        格 = 格式.Jinja2ChatFormatter(
            template=模板,
            eos_token=词(实例, eos),
            bos_token=词(实例, 实例.token_bos()),
            stop_token_ids=[eos] if int(eos) >= 0 else None,
        )
        答 = 格(messages=消息)
    except Exception:
        return None                       # 模板本身坏了 / 它自己 raise
    # ⚠ **预填接在渲染结果后面，不接在 messages 里。** 理由见 docstring。
    串 = 答.prompt + (预填 or '')
    try:
        表 = 实例.tokenize(串.encode('utf-8'),
                          add_bos=not 答.added_special, special=True)
    except Exception:
        return None
    return {'串': 串, 'token们': 表,
            '停': [x for x in (答.stop or []) if x],
            '停止': 答.stopping_criteria,
            '默认模板': 用默认}


def 探针(系统):
    """
    从系统提示里挑一段**模板不会改写**的样本，用来验它有没有被渲染进去。

    ⚠ 拿整段比不行：模板常写 `| trim`，首尾空白会被改掉。**中间那一行不会。**
    所以挑第一行够长的（≥12 字）取前 80 字；一行都不够长就退回整段前 60 字。
    """
    净 = (系统 or '').strip()
    for 行 in 净.splitlines():
        行 = 行.strip()
        if len(行) >= 12:
            return 行[:80]
    return 净[:60]


def 装进去了吗(串, 系统):
    """
    我们的系统提示**真的在**渲染结果里吗 —— 也就是"人格装进去了没有"。

    系统是空的就当进去了（没什么可验的）。这是**实证**，不是看模板里有没有
    `system` 字样：这个项目的字符串判据已经被骗过两次，不打算来第三次。
    """
    探 = 探针(系统)
    if not 探:
        return True
    return 探 in (串 or '')


def 并进首条(消息, 系统):
    """
    把系统提示**并进第一条 user 消息**，并从数组里去掉那条 system。

    ⚠ **这是"没有 system 插槽"的模型的标准补偿方式，不是逐模型特判** ——
    一条规则覆盖这一类，以后再来同类模型不用做任何事。**这才是"通用"。**

    ⚠ 第一条 user 之前如果只有 assistant（新会话时开场白就是这种），
    要**在它前面插一条**，而不是把设定并进开场白 —— 那等于把旁白塞进
    角色嘴里，模型会以为设定是它自己说过的话。
    """
    消息 = [dict(m) for m in 消息 if (m.get('role') or '') != 'system']
    设 = (系统 or '').strip()
    if not 设:
        return 消息
    for i, m in enumerate(消息):
        if m.get('role') == 'user':
            消息[i]['content'] = 设 + '\n\n' + (m.get('content') or '')
            return 消息
    消息.insert(0, {'role': 'user', 'content': 设})
    return 消息


def 锁人格(消息, 要点=''):
    """
    把人格**锁在离生成最近的位置**。回一份新的消息数组。

    ⚠ **这跟 `并进首条` 不是一回事，别混：**

        `并进首条`  管"设定**进不进得去**" —— 放对位置，别被模板丢掉（**安装**）
        `锁人格`     管"它**听不听**"       —— 离生成越近，服从度越高（**控制**）

    `要点` 是一两句角色核心（名字 + 最要紧的一条），追加在**最后一条 user
    消息的末尾**。为什么放那儿：提示词里**离生成越近的位置，小模型的服从度
    越高**（recency）—— 跟 `酒馆大脑.本地规矩` 压在整个系统提示最末尾是
    同一个道理，只是这里再近一层。

    ⚠ **它不是用来"补充信息"的**（信息在 system 里已经有了），是用来
    **重申**的。写长了会跟 system 打架，一两句就够。

    ⚠ 实测（2026-09-20，GLM-Z1-9B-0414）：**光加要点救不了** —— 它让人格
    进了"思维"（思维链里出现"我要以沈砚的身份回应"），但思维链照样吃光预算。
    要点要跟**预填**一起用。
    """
    消息 = [dict(m) for m in 消息]
    要 = (要点 or '').strip()
    if not 要:
        return 消息
    for i in range(len(消息) - 1, -1, -1):
        if 消息[i].get('role') == 'user':
            原 = (消息[i].get('content') or '').rstrip()
            消息[i]['content'] = (原 + '\n\n（' + 要 + '）') if 原 else '（' + 要 + '）'
            return 消息
    # 一条 user 都没有（整段都是开场白那种），补一条，把要点放进去
    消息.append({'role': 'user', 'content': '（' + 要 + '）'})
    return 消息


# ══ 中间段：解码期的干预 ═══════════════════════════════════════════
#
# ⚠ **这一段的位置在"输入"和"输出"之间** —— 提示词已经拼好、模型还没吐字，
# 中间是**一步一步采样**。在这儿干预，**token 还没生成**，比事后过滤干净得多：
# 事后过滤是"等它说完再剪"，token 和时间全白烧了。
#
# 实测过的对照（2026-09-20）：GLM-Z1-9B-0414 给它 160 token，**305 字全是草稿、
# 正文零**；而同一件事换成"不让它想"的办法（`渲染(预填=…)`），`<think>`
# **完全消失** —— 因为**思考根本没发生**。这一节是同一思路的**更强版本**：
# 预填只能在开头拦，这儿能**全程**拦。
#
# ⚠ **工具只有 `logits_processor` 够用，`logit_bias` 不够。**
# `logit_bias` 是**单 token** 的，而中文标记在多数词表里是**多个 token** ——
# 实测 GLM-Z1 的 `<think>` 是 `[13699, 766, 29]`（`<` · `think` · `>`），
# 而 `13699` 就是**单独的 `<`**。压死它等于**禁掉所有 `<`**，误伤太大。
# 所以多 token 的序列必须**按前缀匹配**：只在"前面已经对上了"的时候压下一个。

#: ⚠ **思维链标记：单独放着，默认不掐 —— 实测会适得其反。**
#:
#: 2026-09-20 实测（GLM-Z1-9B-0414，真跑）：
#:
#:     不掐：  `<think>\n嗯，用户现在在扮演掌柜…`         → 至少是完整草稿
#:     掐掉：  `<three星</think>` × 十几次                → **疯狂复读**
#:
#: **拦截本身是生效的**（`<think>` 确实写不出来了），但**结果是反的**：
#: 模型内部那个"开一段思考 / 闭一段思考"的状态机**不因为你抽掉标签就消失** ——
#: 它只会在那儿打转找别的写法，甚至绕道 `</think>`（`<` 后面跟的是 `/`，
#: 不撞 `<think>`，所以溜过去了）。
#:
#: **所以"掐标记"不是"不让它思考"，是"不让它把思考写成形"。** 两个办法里，
#: 真正管用的是 `渲染(预填=…)` —— 它改的是模型的**状态**（思考块已经闭合了，
#: 它就不需要再开一个），不是改文本。见 `project_ai_protocol_module.md`。
#:
#: 留着它是为了**别的模型**可能没这个状态机问题（比如那个标记纯粹是个装饰）。
#: **要开就先真跑一段看看，别默认开。**
思维标记 = ('<think>',)

#: 默认要**从生成里掐掉**的 —— **只留"自称 AI"的整句**。
#:
#: 兑现 `酒馆大脑.本地规矩` 第 3 条。在提示词里求它是"求"，在这儿压死 token 是
#: "做不到" —— 但**注意掐的是"短语"不是"词"**：`助手` / `程序` / `机器人`
#: 角色**可能合法地说**（"我的助手"、"走法律程序"），掐词就是误伤。
#:
#: ⚠ **这一类还没在真模型上验过**（不像 `思维标记` 那样测出过反效果）。
#: 它的机制上不该有状态机问题 —— 模型没有"必须说出我是一个助手"的内在驱动力，
#: 挡了它换个说法就是了。但**接进链路后要盯**。
默认禁吐 = (
    '作为AI', '作为 AI', '我是一个AI', '我是一个 AI', '我是个AI', '作为一个AI',
    '作为人工智能', '我是一个人工智能',
    '作为一个语言模型', '我是一个语言模型', '作为语言模型',
    '我是一个助手', '作为一个助手', '我是一个程序', '我是一个机器人',
)


def _词表索引(实例):
    """
    给"**按文字**匹配"用的词表索引：`{首字符: [(token 编号, 该 token 的文字), …]}`。

    ⚠ **为什么必须按文字匹配，不能按 token 匹配：** BPE 里**同一个字符串有多种
    合法切法**，模型按概率挑，**不一定走贪心那一种**。

    实测（2026-09-20，GLM-Z1-9B-0414）：

        `tokenize('<think>')`      -> [13699, 766, 29]    最后一个 token 是 `>`
        `tokenize('<think>\\n')`    -> [13699, 766, 397]   最后一个 token 是 `>\\n`
        模型**实际生成**的         -> [13699, 766, 397]   ← 走的是后者

    按标准切法压 `29`，压的是一个**永远不会出现的 token** —— 看着"压了"，实际
    一点用没有。（这个坑真踩到了：接完之后实测 GLM-Z1 的 `<think>` 照样出来。）

    所以只能退到**文字层**：把尾巴的文字抠出来，看它是不是目标的一个前缀，
    再去词表里找"能接着往下写"的 token 压掉。

    ⚠ 建一次约 **0.3 秒**（15 万词表），**缓存在模型对象上**。
    不按 `id(实例)` 缓存是因为对象回收后 id 会被复用。
    """
    已 = getattr(实例, '_协议词表索引', None)
    if 已 is not None:
        return 已
    按首 = {}
    try:
        宽 = int(实例.n_vocab())
    except Exception:
        return {}
    for i in range(宽):
        try:
            s = 实例.detokenize([i], special=True).decode('utf-8', 'replace')
        except Exception:
            continue
        if s:
            按首.setdefault(s[0], []).append((i, s))
    try:
        实例._协议词表索引 = 按首          # 挂模型对象上，跟着它的生命周期走
    except Exception:
        pass
    return 按首


#: 判断"尾巴是不是目标前缀"时，往回看多少个 token 的文字。
#: 目标都是短串（十几字以内），24 个 token 的文字远远够。
尾长 = 24


def 禁吐(实例, 序列们, 强=-1e4):
    """
    造一个 `logits_processor`，把指定的字符串**从生成里掐掉**。

    回一个能直接塞进 `create_completion(logits_processor=…)` 的东西；
    一个都编不出 token 就回 `None`（调用方当没这回事）。

    ⚠ **匹配在"文字层"，不在"token 层"。** 理由见 `_词表索引` —— BPE 里同一个
    字符串有多种切法，按标准切法算出来的 token id **可能压根不会出现**。

    工作方式：每一步把尾巴的文字抠出来，若它正好落在某个目标的**真前缀**上
    （比如目标是 `<think>`，尾巴已经写到 `<thin`），就**把词表里所有"能接着
    往这个目标上写"的 token 压掉** —— 既包括"只差一个 `>`"的，也包括
    "一口气写成 `>\\n`"的。

    ⚠ **`强` 用 `-1e4` 而不是 `-inf`。** 有些后端对 `-inf` 的 softmax 会出
    nan；给一个足够大的负数效果一样，但不会把整行概率算崩。
    """
    try:
        import llama_cpp
    except Exception:
        return None
    目 = [s for s in ((x or '').strip() for x in (序列们 or ())) if s]
    if not 目:
        return None
    表 = _词表索引(实例)
    if not 表:
        return None

    def 处理(input_ids, scores):
        try:
            ids = [int(x) for x in input_ids]
            宽 = len(scores)
        except Exception:
            return scores
        # ⚠ 只看**最后 24 个 token** 的文字：全量 detokenize 是 O(长度)，
        # 挂在每一步采样上会拖垮生成。目标都很短，24 个够。
        try:
            尾 = 实例.detokenize(ids[-尾长:], special=True).decode('utf-8', 'replace')
        except Exception:
            return scores
        for T in 目:
            # 尾巴结尾是不是 T 的**真前缀**（不能是完整的 T —— 那说明已经写出去了）
            前 = 0
            for k in range(1, len(T)):
                if 尾.endswith(T[:k]):
                    前 = k
            if 前 <= 0:
                continue
            剩 = T[前:]                      # 还差这几个字就写成了
            for i, s in (表.get(剩[0]) or ()):
                if not s or i < 0 or i >= 宽:
                    continue
                # 两种都要挡：
                #   `s` 是 `剩` 的开头（只写了一半，比如只剩 `>` 时来一个 `>\n`）
                #   `剩` 是 `s` 的开头（还差更多，比如剩 `>\n` 时来一个 `>`）
                if s.startswith(剩) or 剩.startswith(s):
                    scores[i] = 强
        return scores

    return llama_cpp.LogitsProcessorList([处理])


def 要禁的(控):
    """
    这次该掐哪些。回一个元组，可能空。

    = `默认禁吐`（自称 AI 的整句）+ 用户加的，除非设定里写 `中间层='关'`。

    ⚠ **思维标记（`<think>`）单独一个开关 `掐思维='开'`，默认不开** ——
    实测它会让模型**疯狂复读**（见 `思维标记` 上面那段）。想试的自己开，
    而且**要真跑一段看效果**。

    ⚠ **默认禁吐是开的**（跟 `要点` / `预填` 相反），因为它是**保护性**的：
    只会"少说"，不会"多说"。但它**确实会改变所有模型的输出**，所以留了
    `中间层='关'` 这个逃生口 —— 判定错了当场能关。
    """
    控 = 控 or {}
    用户 = tuple(x for x in (控.get('禁吐') or ()) if x)
    关 = str(控.get('中间层') or '').strip().lower() in ('关', 'off', '0', '否', '不')
    if 关:
        return 用户
    出 = list(思维标记) if str(控.get('掐思维') or '').strip().lower() in \
        ('开', 'on', '1', '是') else []
    for x in 默认禁吐 + 用户:
        if x and x not in 出:
            出.append(x)
    return tuple(出)


# ══ 输出侧：分流 ═══════════════════════════════════════════════════
#
# ⚠ **推理模型的思维链是"草稿纸"，不是给用户看的东西。**
#
# 实测（2026-09-20，GLM-Z1-9B-0414，聊天链路）：给它 160 token，**305 字全是
# `<think>` 里的草稿、正文一个字都没有**；给到 400 token 才勉勉强强出来正文。
# 它的模板里有 `content.split('</think>')[-1]`，说明**它期望历史里带着思维链、
# 渲染时自动剥掉** —— 但那是"历史"，**当轮吐出来的原文照样流到界面**。
#
# ⚠ **更好的解法是"别让它想"（`渲染` 的 `预填`），不是"想完再剪"。**
# 预填让模型看到 `<|assistant|>` 后面已经有内容，它就**不会从头"嗯让我想想"**
# ——思考根本没发生，token 一个不烧。实测：同一个模型，加预填后 `<think>`
# 完全消失。分流只是**兜底**，给那些预填也压不住的模型用。

#: 各家的思维链标记。**闭合标记是必须的**（DeepSeek-R1 蒸馏系只吐 `</think>`
#: 不吐开标记），开标记只是用来判断"有没有在想"。
思考闭标记 = ('</think>', '<|end_of_thought|>', '<|/think|>')
思考开标记 = ('<think>', '<|begin_of_thought|>', '<|think|>')


class 分流:
    """
    流式分流：**把思维链扣住不给用户看，只吐正文。**

    用法：

        f = 分流()
        for 帧 in 流:
            for 段 in f.喂(帧):
                yield 段          # 给界面
        for 段 in f.完():
            yield 段

    然后看 `f.只思维` —— 它说"这次出了闭合标记，而闭合标记之前是草稿"。

    ⚠⚠ **不要无条件开！先问 `该分流吗()`。** 这是这个类最容易用错的地方：

        对一个**不思考**的模型（比如 Qwen3.5 默认就是"不思考"——模板给它预填了
        一个**已经闭合**的空 `<think></think>`），它生成的字里**根本没有
        `</think>`**。无条件开的话，`分流`会一路扣着不放，直到撞上 `上限`
        —— 用户盯着空白等几千字才看到东西。**比不剥还坏。**

    所以开关必须是**"有证据才开"**：证据 = 提示词尾部有**未闭合**的 `<think>`
    （那些"先思考再回答"的模型，模板会把思考位留开着），或者模型名字本身
    就是已知的推理型号。见 `该分流吗`。

    ⚠ **收尾时还在扣着的内容会放出来**，不是吞掉。理由：吞掉是**静默**的
    （用户看到空白，不知道发生了什么），而放出来的是**可见的异常**（他一眼
    看出"这模型在自说自话"）。这个项目的立场一贯是"宁可难看，不许不响"。

    ⚠ **只认闭合标记定位切点。** 有些模型（R1 蒸馏系）只吐 `</think>` 不吐
    `<think>`，按开标记判会一路扣到底。
    """

    #: 最多扣住多少字。超了就**认账放出来** —— 防"它一直不吐闭合标记，
    #: 用户盯着空白等"。
    #:
    #: ⚠ **这个数是拍的**，没有任何实测依据。接进链路时按真实模型的草稿长度调
    #: （GLM-Z1-0414 在 400 token 上限下吐了约 700 字草稿，所以 6000 对它等于没有上限）。
    #:
    #: ⚠ **不需要"留尾缓冲"这种东西。** 缓冲本来就把整段扣着，跨帧被切开的
    #: 半个闭合标记下一帧接上就认出来了 —— 早先想过加一个 `留尾`，实现完发现
    #: 根本用不到，删了。
    上限 = 6000

    def __init__(self, 开=思考开标记, 闭=思考闭标记):
        self._开 = tuple(开)
        self._闭 = tuple(闭)
        self._扣 = ''          # 还没放出去的（疑似草稿）
        self._过了 = False     # 已经过了闭合标记，后面全是正文
        self._放了 = False     # 放过正文没有

    @property
    def 只思维(self):
        """
        这次**出了闭合标记，但一个字正文都没有** —— 全是草稿。

        ⚠ 它是**算出来的**，不是随手记的标记。写成标记会有一个很难发现的
        时序 bug：闭合标记到达时正文还没来（余为空），于是记成"只思维"；
        下一帧正文到了，那个标记却没人去清 —— 报出来的就是错的。
        （这个 bug 在自测里真撞到过。）
        """
        return self._过了 and not self._放了

    def 喂(self, 段):
        """吃一段，回**这一段里该给用户看的**（可能空）。"""
        if not 段:
            return []
        if self._过了:
            self._放了 = True
            return [段]
        self._扣 += 段
        位 = self._第一个闭标记()
        if 位 is not None:
            self._过了 = True
            余 = self._扣[位:]
            self._扣 = ''
            if 余:
                self._放了 = True
            return [余] if 余 else []
        if len(self._扣) > self.上限:
            # 认账：它一直不吐闭合标记，再扣下去用户就干等了
            出 = self._扣
            self._扣 = ''
            self._过了 = True
            self._放了 = bool(出)
            return [出]
        return []

    def 完(self):
        """收尾。还在扣着的**放出来**（见类说明）。"""
        余 = self._扣
        self._扣 = ''
        if 余:
            self._放了 = True
            return [余]
        return []

    def _第一个闭标记(self):
        """扣着的缓冲里，最早出现的闭合标记**之后**的位置。没有回 `None`。"""
        最早, 位 = None, 0
        for 记 in self._闭:
            i = self._扣.find(记)
            if i >= 0 and (最早 is None or i < 最早):
                最早 = i
                位 = i + len(记)
        return 位 if 最早 is not None else None


#: ⚠ **这是一份"已知型号名单"，不是一串用来猜的模式。**
#:
#: 判推理模型**唯一可靠的判据**是 `思考没闭合()`（提示词尾部有没有把思考位
#: 留开着）—— 那是**事实**。但有一类模型**模板里根本没有思考标记、却天生会想**，
#: 最典型的是 DeepSeek 的 R1 蒸馏系：模板里没有 `<think>`，可它张口就是一大段
#: 草稿。对这类，除了"它是什么型号"没有别的办法。
#:
#: ⚠ **别往里加 `'think'` / `'reason'` 这种模糊词。** 那是"用模式猜"，会误伤
#: （`xxx-thinking` 出现在无关模型上就中招）—— 而"判据只查字符串"这个病，
#: 这个项目已经踩过两次（`tool_call` vs `tools`、`item['tools']`）。
#: **只加确切的型号片段。** 要扩就加型号，不要加词根。
推理型号 = ('deepseek-r1', 'qwq', 'glm-z1', 'magistral')

#: 明确**不思考**的型号 —— 它们的生成里根本不会有 `</think>`，对它们开分流
#: 等于把正常输出扣住。名字撞上这个名单**一票否决**（优先于上面那张）。
非推理型号 = ('instruct-2507',)


def 思考没闭合(串):
    """
    提示词尾部有没有**未闭合**的 `<think>` —— 也就是"模板把思考位留开着"。

    这是**比任何名字判据都硬的证据**：模板都明说要思考了，那它生成里就会先
    吐草稿。反过来，Qwen3.5 默认给的是一个**已经闭合**的空 `<think></think>`
    （等于说"思考完了，直接答"），那就不能扣。
    """
    尾 = (串 or '')[-200:]              # 只看尾部，够判断当前是不是在思考位
    for 开 in 思考开标记:
        i = 尾.rfind(开)
        if i < 0:
            continue
        # 这个开标记后面有没有配对的闭合标记？没有 = 留开着
        后 = 尾[i + len(开):]
        if not any(闭 in 后 for 闭 in 思考闭标记):
            return True
    return False


def 该分流吗(实例=None, 提示词='', 名字=''):
    """
    这个模型**这次生成**该不该开输出分流。**默认不开** —— 有证据才开。

    证据①②是**两件不同性质的事**，别混着看：

        ① **提示词尾部有未闭合的 `<think>`** —— 这是**判据**。
           模板自己把思考位留开着，那它必然先吐草稿。看的是**事实**。
        ② **名字撞上 `推理型号` 名单** —— 这是**查表**，不是判据。
           R1 蒸馏系那种模板里没有 `<think>` 却天生会想的，只能靠"它是什么
           型号"来认，而那份名单是**已知事实的登记**。
        ③ 名字撞上 `非推理型号` → **一票否决**（优先于 ②）。

    ⚠ **都判不出来就不开。** 开了而它其实不思考，用户会盯着空白等几千字 ——
    比不剥还坏（见 `分流` 的类说明）。

    ⚠ **`推理型号` 那份名单迟早要变成可配的**（用户自己的本地模型可能不在
    名单里）。现在硬编码在模块里，是因为还没想好挂在哪儿 —— 挂接口配置行是
    最自然的位置，但那是 UI 的活。
    """
    名 = str(名字 or '').lower()
    if any(标 in 名 for 标 in 非推理型号):
        return False
    if 思考没闭合(提示词):
        return True
    if 名 and any(标 in 名 for 标 in 推理型号):
        return True
    return False



