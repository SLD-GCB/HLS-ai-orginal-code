# -*- coding: utf-8 -*-
"""
通用协议层 —— **把「模型差异」关在这一个模块里。**

上层（聊天页 / 编程助手）永远只看到统一的 messages 和文本。这一层负责回答
两个问题：**"这条消息该怎么发给它"** 和 **"它回的东西是什么意思"**。

    ┌─ 输入侧 ─────────────────────────────────────────────┐
    │ 画像    读元信息 + 渲染自检 → 这个模型到底是什么样     │
    │ 渲染    messages → 按它母语格式的提示词                │
    │ 自检    我们的人格**真的装进去了吗**（实证，不是查字符串）│
    │ 安装    装不进去就换位置（并进第一条 user）            │
    │ 控制    要点复述（recency）+ 预填（锁住它张口那一刻）  │
    │ 兜底    模板缺失时按族给默认，**不再静默退 llama-2**   │
    └───────────────────────────────────────────────────────┘
    ┌─ 输出侧 ─────────────────────────────────────────────┐
    │ 分流    思维链扣住不给用户看，只吐正文                 │
    │ 停止    模板给的 + 按族补的回合标记                    │
    └───────────────────────────────────────────────────────┘
    ┌─ 外层 ───────────────────────────────────────────────┐
    │ 填卡    `{{char}}` / `{{user}}` 占位符，让角色卡可移植  │
    │ 记录    这次实际发出去了什么（给界面看）               │
    └───────────────────────────────────────────────────────┘

⚠ **这个模块的立场：我们自己执行，不让库替我们决定。**

    原来这条路上是 `create_chat_completion(messages=…)` —— 库内部挑模板、
    拿模板渲染、转成 token，**中间产物一个字都留不下来**。于是"这个模型认
    不认 system 插槽、我们的人格到底有没有装进去"全凭它自己决定，**而且错了
    不报错**。表现是"模型演不了角色"，而用户无从知道为什么。

    现在：用**库自己那套渲染器**（同一份 `tokenizer.chat_template`、同一套
    jinja）渲染，把中间产物截下来，然后自己喂 `create_completion`。**渲染逻辑
    一行没改**，所以对模板正常的模型，结果与原路径**逐字节相同**（2026-09-20
    拿 Qwen3.5-9B / GLM-Z1-9B-0414 / Phi-3.5-mini 三个真模型逐 token 验过）——
    区别只是我们现在**看得见**，看见不对还能当场改。

**纯逻辑**：不碰 Qt、不碰存储 —— 跟 `酒馆工具` / `酒馆记忆` 同一个定位。
"""

