def 路说明(路, 系统):
    """
    把"这次走了哪条路"翻成一句人话，给界面用。见 `酒馆本地.流式块`。

    `路` 的取值：

        `模板`      按模型自带模板渲染，设定进了它的 system 插槽
        `并入首条`  模板不吃 system，设定被挪进第一条用户消息
        `装不进去`  两条路都试过还是没进去（**救不了**的那类，必须说出来）
        `族默认`    模板缺失，用了族默认兜底（**best-effort**）
        `回退`      模板缺失且兜不了，退回旧路（库会静默退 llama-2）
    """
    if 路 == '并入首条':
        return ('这个模型的模板**不吃 system**（角色设定会被丢掉），已自动把它'
                '并进第一条用户消息 —— 这是"没有 system 插槽"的标准补偿，'
                '不是针对某个模型的特判。')
    if 路 == '族默认':
        return ('⚠ 这个 GGUF **没有聊天模板**，用了**按架构猜的兜底模板**。'
                '兜底只是 best-effort，**不是精确还原**，效果可能明显打折 —— '
                '建议换一个带模板的量化重下。')
    if 路 == '模板':
        if not (系统 or '').strip():
            return '这次没有角色设定要装；用这个模型自带的聊天模板渲染。'
        return '用这个模型自带的聊天模板渲染，角色设定已装进它的 system 插槽。'
    if 路 == '装不进去':
        return ('⚠ **角色设定没能装进去。** 这个模型的模板把 system 丢了，'
                '换到"第一条用户消息"这个位置之后**还是没进去** —— 这个模型'
                '的聊天模板多半跟它自己的训练格式对不上（第三方量化常见）。'
                '换一个量化重下，或者把这个 GGUF 的模板情况报出来查。')
    return ('这个 GGUF **没有可用的聊天模板**，渲染不了，已回退到库的默认行为。'
            '⚠ 库在没有模板时会**静默退成 llama-2 格式**，模型大概率不认，'
            '表现是答非所问或胡言乱语。换一个带模板的量化重下。')


