#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
酒馆对话.py — 会话和消息的存取

一个角色可以有很多段对话（`会话`，落在 `酒馆数据/会话.json`），每段对话里
是一条条 `消息`（落在 `酒馆数据/消息/<会话编号>.json`）。

**消息按 `序号` 排序，序号就是对话顺序。** 这一条撑着三件事：

  · 天然唯一 —— 同一个会话里不可能出现两条序号相同的消息；
  · 天然有序 —— 按序号排就是对话顺序，不用额外的时间列；
  · **重新生成 = 覆盖同一个序号的条目** —— 不会长出重复行。

第三条最要紧。要是重新生成靠"再追加一条"，对话里就会冒出两条回答。

**消息整份读写，不逐条追写文件。** 一段会话撑死几千条，读出来改一条再
整份写回去，比维护"追加到文件尾巴"的半个状态简单得多；而且盘上永远是
自洽的一份，不会有半条记录、也不会有两个进程写出同一行。
"""

from 酒馆模型 import 会话, 消息, 写JSON, 说话人 as 说话人们
from 酒馆存储 import 酒馆错误, 毫秒

__all__ = ['建会话', '取会话', '列会话', '改会话', '删会话', '改标题',
           '追加消息', '覆盖消息', '删消息', '清空消息',
           '取消息', '取最近', '消息数', '下个序号', '说话人们']

会话列 = ('编号', '角色编号', '标题', '接口编号', '创建于', '更新于')

会话可改 = frozenset(会话.列名()) - {'编号', '创建于'}


# ── 会话 ────────────────────────────────────────────────────────────

def 建会话(库, 角色编号, 标题='', 接口编号=0, 预设=None):
    """
    开一段新对话，返回建好的（带着发下来的编号）。

    `接口编号 = 0` 表示"用默认那套接口配置"，由 `酒馆接口.取或默认()`
    在真要发请求的时候兜底。
    """
    现在 = 毫秒()
    行 = {'编号': 库.发号('会话'), '角色编号': 角色编号, '标题': 标题 or '',
          '接口编号': 接口编号 or 0, '预设': 写JSON(预设),
          '创建于': 现在, '更新于': 现在}
    库.存('会话', 行)
    return 会话.从行(行)


def 取会话(库, 编号):
    """按编号取一段会话。没有就返回 `None`。"""
    行 = 库.取('会话', 编号)
    return 会话.从行(行) if 行 else None


def 列会话(库, 角色编号=None):
    """
    列出会话。给了 `角色编号` 就只列那个角色的。

    **按 `更新于` 降序** —— 最近说过话的排前面，这是列表要的顺序。
    每一次 `追加消息` 都会把会话的 `更新于` 顶上去，所以它就是"最近活跃"。
    """
    行们 = 库.全都('会话')
    if 角色编号 is not None:
        行们 = [行 for 行 in 行们
               if int(行.get('角色编号') or 0) == int(角色编号)]
    行们.sort(key=lambda 行: int(行.get('更新于') or 0), reverse=True)
    return [会话.从行({k: 行.get(k) for k in 会话列}) for 行 in 行们]


def 改会话(库, 编号, **字段):
    """改几个字段，`更新于` 自动跟着走。改到了返回 `True`。"""
    if '预设' in 字段 and not isinstance(字段['预设'], str):
        字段['预设'] = 写JSON(字段['预设'])
    坏的 = set(字段) - 会话可改
    if 坏的:
        raise 酒馆错误('改不了这些字段：%s（能改的是 %s）'
                      % ('、'.join(sorted(坏的)), '、'.join(sorted(会话可改))))
    with 库.独占():          # 读-改-写要是一整段，见 `库.独占` 那条
        整行 = 库.取('会话', 编号)
        if 整行 is None:
            return False
        if not 字段:
            return False
        整行.update(字段)
        整行['更新于'] = 毫秒()
        库.存('会话', 整行)
    return True


def 改标题(库, 会话编号, 标题):
    """只改标题。单独开一条是因为"自动起标题"那条路天天用。"""
    with 库.独占():
        整行 = 库.取('会话', 会话编号)
        if 整行 is None:
            return False
        整行['标题'] = 标题 or ''
        整行['更新于'] = 毫秒()
        库.存('会话', 整行)
    return True


def 删会话(库, 编号, 连带消息=True):
    """
    删一段会话。`连带消息=True`（默认）把里面的消息一起删。

    **先消息后会话**：真停在中间，留下的是一个空会话，界面上还看得见、
    还能再删一次；反过来先删会话，剩下的消息就再也找不到了。
    """
    if 连带消息:
        库.删消息们(编号)
    return 库.删('会话', 编号)


# ── 消息 ────────────────────────────────────────────────────────────

def 下个序号(库, 会话编号):
    """
    这段会话下一个该用的序号。**每回都从盘上现算**，不用内存计数器：
    序号算错了不是"顺序乱一点"，是**把已有的消息覆盖掉**。

    现算多读一次文件，换掉一整类静默丢数据的可能，这个价钱很便宜。
    """
    行们 = 库.消息们(会话编号)
    return (int(行们[-1].get('序号') or 0) + 1) if 行们 else 1


def _查说话人(说话人):
    说话人 = (说话人 or '').strip()
    if 说话人 not in 说话人们:
        raise 酒馆错误('说话人只能是 %s 之一（给的是 %r）'
                      % ('、'.join(说话人们), 说话人))
    return 说话人


def 追加消息(库, 会话编号, 说话人, 内容, 元信息=None):
    """
    往会话尾巴上加一条，返回加好的那条。

    消息先写，"把会话的 `更新于` 顶上去"后做。真停在中间，最坏是会话的
    `更新于` 没跟着动（列表排序偏一点），消息本身不会丢——它在前面。
    """
    说话人 = _查说话人(说话人)
    现在 = 毫秒()
    # ⚠ **整段套 `独占`。**「读出来 → 加一条 → 整份写回去」三步分开取锁的话，
    # 工人线程和生成线程同时往一个会话里追加，两边都读到"现在 7 条"、各自写出
    # "8 条"那一份——先写的那条被整份盖掉，静默丢一条消息。
    with 库.独占():
        行们 = 库.消息们(会话编号)
        序号 = (int(行们[-1].get('序号') or 0) + 1) if 行们 else 1
        行 = {'会话编号': 会话编号, '序号': 序号, '说话人': 说话人,
              '内容': 内容, '元信息': 写JSON(元信息), '创建于': 现在}
        行们.append(行)
        库.存消息们(会话编号, 行们)
        改会话(库, 会话编号)             # 顶 `更新于`，不传别的字段
    return 消息.从行(行)


def 覆盖消息(库, 会话编号, 序号, 说话人, 内容, 元信息=None):
    """
    覆盖已有的那条消息 —— **重新生成走这条**。

    序号是定死的，所以这里**必须覆盖不能追加**：追加的话对话里会冒出
    两条回答，而用户只按了一次"重说"。
    """
    说话人 = _查说话人(说话人)
    行 = {'会话编号': 会话编号, '序号': int(序号), '说话人': 说话人,
          '内容': 内容, '元信息': 写JSON(元信息), '创建于': 毫秒()}
    with 库.独占():                      # 同 `追加消息`：读-改-写要是一整段
        行们 = 库.消息们(会话编号)
        换过 = False
        for i, 旧 in enumerate(行们):
            if int(旧.get('序号') or 0) == int(序号):
                行['创建于'] = 旧.get('创建于') or 行['创建于']  # 别把原时间抹了
                行们[i] = 行
                换过 = True
                break
        if not 换过:
            行们.append(行)
        库.存消息们(会话编号, 行们)
        改会话(库, 会话编号)
    return 消息.从行(行)


def 删消息(库, 会话编号, 序号):
    """删掉一条。删到了返回 `True`。"""
    with 库.独占():
        行们 = 库.消息们(会话编号)
        留 = [行 for 行 in 行们 if int(行.get('序号') or 0) != int(序号)]
        if len(留) == len(行们):
            return False
        库.存消息们(会话编号, 留)
        改会话(库, 会话编号)
    return True


def 清空消息(库, 会话编号):
    """把一段会话里的消息全删掉，返回删了几条。会话本身留着。"""
    return 库.删消息们(会话编号)


def 取消息(库, 会话编号, 上限=None):
    """
    这段会话的消息，**按序号升序**（= 对话顺序）。

    `上限` 给的是**最近**那么多条（不是最前面那些）——界面上要的是
    "最新的几屏"。
    """
    行们 = 库.消息们(会话编号)
    if 上限 is not None:
        行们 = 行们[-max(0, int(上限)):] or []
    return [消息.从行(行) for 行 in 行们]


def 取最近(库, 会话编号, 条数):
    """
    最近 `条数` 条，**按序号升序返回**（老 → 新），拼上下文直接用。
    """
    if 条数 is None or int(条数) <= 0:
        return []
    return 取消息(库, 会话编号, 上限=int(条数))


def 消息数(库, 会话编号):
    return len(库.消息们(会话编号))
