#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
酒馆助手线.py — 编程助手那条线程

**为什么不复用 `酒馆工人.生成线`。** 三条理由，一条比一条硬：

  1. **接口形状对不上。** `生成线.排(会话编号, 序号, 系统, 消息们, 配置, 设定)`
     和它的 `分块/结束/坏了` 全是"一段会话、一个序号、一次流式回复"的模型。
     编程助手是**无会话、多轮循环、带副作用的异构事件流**（模型文本 / 工具
     卡片 / 审批请求 / 折叠 / 上下文用量）。硬塞进去等于把"会话/序号"这套
     聊天概念漏进 agent，或者反过来 —— 两个方向都违背"新行为限制在目标链路"。
  2. **`生成线` 的定义就是"一个字节的存储都不碰"**，它手上没有能误用 `库` 的
     引用，那是它的**安全形状**。编程助手要写文件、跑命令、改工作目录，
     继承一条"为纯数据流设计"的线程就把这个形状破了。
  3. **`生成线` 只跑阻塞 requests、没有 Qt 事件循环**，停它只有置旗一条路。
     编程助手需要**审批握手**（暂停等主线程回话），跟"置旗即停"是两套机制，
     混在一起会互相污染。

所以另起一条。**聊天链路一个字节都不用动。**

════════════════════════════════════════════════════════════════════
审批握手为什么是"阻塞式"
════════════════════════════════════════════════════════════════════

`要批` 信号发出去之后，这条线程 `事件.wait(超时)` 停住，等主线程的
`回批()` 把事件置上再继续。**不用模态弹窗**，因为模态会挡住用户看前面几步
的转录本 —— 而那正是判断"该不该批"的关键上下文。而且嵌套事件循环里回调
重入极难推理。

超时（默认 5 分钟）当成**拒绝**：用户走开了，任务不该永远挂在那儿。
"""

import threading

from PySide6.QtCore import QThread, Signal

import 酒馆大脑
import 酒馆本地
import 酒馆助手

__all__ = ['助手线']

#: 审批最多等多久（秒）。到点按拒绝处理 —— 用户走开了，任务不该永远挂着。
等批秒 = 300


class 助手线(QThread):
    """
    跑一次编程任务。**一次一个任务**，跑完回到空闲，可以再排。

    信号：

        阶段(str, str)     (阶段名, 说明)  界面拿它画顶部那条状态
        正文(str)          模型正在写的文本（流式）
        卡(int, object)    (卡片号, 卡片数据)
        要批(int, object)  (卡片号, 审批请求) —— **发完就阻塞等 `回批`**
        步(int, int, int)  (第几步, 共几步, 估算 token)
        预算(object)       `分预算` 那一份（总/系统/转录本/输出/余量）
        完(object)         结果 dict。**真跑过的话多一个 `转录本` 键**
                           （`酒馆助手.抄本.到字典()` 那一份），给界面落盘用；
                           配置缺 / 协议不是 local 这种没跑起来的早退没有它。
    """

    阶段 = Signal(str, str)
    正文 = Signal(str)
    卡 = Signal(int, object)
    要批 = Signal(int, object)
    步 = Signal(int, int, int)
    预算 = Signal(object)
    完 = Signal(object)

    def __init__(self, 父=None):
        super().__init__(父)
        self._活 = None               # (根, 任务, 配置, 设置)
        self._锁 = threading.Lock()
        self._醒 = threading.Event()  # 有新活
        self._停 = threading.Event()
        self._收工 = False            # 线程该退出了
        self._回 = {}                 # {审批号: [Event, 准不准]}
        self._在跑 = False
        self._号 = 0                  # 审批号的发号器

    # ── 外面用的 ──

    def 排(self, 根, 任务, 配置, 设置=None):
        """排一个任务。**非阻塞**，已经有了就不排（界面那边按钮也禁着）。"""
        with self._锁:
            if self._在跑:
                return False
            self._活 = (根, 任务, 配置, dict(设置 or {}))
            self._在跑 = True
        self._停.clear()
        self._醒.set()
        return True

    def 在跑(self):
        return self._在跑

    def 打断(self):
        """
        喊停。**置旗，不强关任何东西。**

        生效点是分阶段的，界面必须分别说实话（见 `酒馆助手页`）：

            两次调用之间   立刻
            解码（在写字） 最长一个块，几十毫秒
            prefill         **不能**（llama.cpp 绑定掐不断提示词处理）
            跑命令          到超时或命令自己结束
        """
        self._停.set()
        # 正卡在审批上也一起放掉，否则要一直等到超时
        with self._锁:
            项们 = list(self._回.values())
        for 项 in 项们:
            项[0].set()

    def 回批(self, 号, 准):
        """主线程回话：这一条批不批。`助手线` 正阻塞等着这个。"""
        with self._锁:
            项 = self._回.get(号)
        if 项:
            项[1] = bool(准)
            项[0].set()

    def 停(self, 毫秒=6000):
        """
        收尾。**返回值不能扔** —— `True` 才是真停了。

        先喊停（放过正卡着的审批），再置收工旗并叫醒 `wait`，最后等它退。
        """
        self._停.set()
        self.打断()
        with self._锁:
            self._在跑 = False
            self._收工 = True
        self._醒.set()
        return self.wait(毫秒)

    # ── 线程里 ──

    def run(self):
        while True:
            self._醒.wait()
            self._醒.clear()
            if self._收工:
                return
            with self._锁:
                活 = self._活
                self._活 = None
            if not 活:
                with self._锁:
                    self._在跑 = False
                continue
            try:
                self._干(活)
            except Exception as 错:
                self.完.emit({'坏': '%s：%s' % (type(错).__name__, 错), '步': 0})
            finally:
                with self._锁:
                    self._在跑 = False
                    self._回 = {}

    def _要批(self, 卡):
        """
        发审批请求，**阻塞等主线程回话**。超时按拒绝。

        ⚠ **审批号必须自己发号，不能用 `卡['号']`。** 那个号是"这一步里的第
        几个调用"，每步都从 1 重来 —— 拿它当键的话，第二步的第 1 个调用会
        顶掉第一步还没回话的那条，事件被置错、界面回批回给别的卡片。
        """
        with self._锁:
            self._号 += 1
            号 = self._号
        事 = threading.Event()
        with self._锁:
            self._回[号] = [事, False]
        self.要批.emit(号, 卡)
        if not 事.wait(等批秒):
            with self._锁:
                self._回.pop(号, None)
            return False                 # 超时 → 拒绝，见文件头
        with self._锁:
            项 = self._回.pop(号, None)
        return bool(项[1]) if 项 else False

    def _干(self, 活):
        根, 任务, 配置, 设置 = 活

        缺 = 酒馆大脑校验(配置)
        if 缺:
            self.完.emit({'坏': '这套接口配置用不了，缺：%s' % '、'.join(缺), '步': 0})
            return

        协议 = 配置.协议 or 'local'
        设置 = dict(设置 or {})
        # ⚠ **`'自动'` 必须真的去解析，不能当"已经设好了"。**
        #
        # 这儿原来是 `设置.get('工具协议') or 默认工具协议(配置)` —— 而传进来的
        # `设` 是 `dict(酒馆助手.默认设置)`，里面写死的正是 `'自动'`。`'自动'`
        # 是真值，`or` 右边**永远不执行**，于是 `默认工具协议` 成了死代码、
        # 下面那句 `是否原生` 永远是 False，**四家协议无一例外全退到文本协议**。
        # 症状是"接口明明支持工具，模型却只顾着自言自语"。
        选 = str(设置.get('工具协议') or '自动')
        设置['工具协议'] = 默认工具协议(配置) if 选 == '自动' else 选

        # 这套配置声明的**工具调用形状**（「接口配置」里那格：自动 / JSON / XML）。
        # `式样()` 已经把认不出来的值归一成「自动」了，这儿不用再判一次 ——
        # 老数据没有这一列，走默认就是「自动」，跟以前的行为一模一样。
        设置['工具格式'] = 配置.式样()

        # ⚠ **只支持本地模型。** 云端那条路（逐协议的原生工具收发）已经删了，
        # 见 `酒馆大脑` 那段注释。这儿**不静默降级** —— 降级会让用户以为
        # "云端也能跑"，然后对着一个永远不动手的 agent 猜半天。
        if 协议 != 'local':
            self.完.emit({'坏': '编程助手现在只支持本地模型（协议要选 local），'
                                '这套的协议是 %s。\n'
                                '聊天照旧能用云端 —— 去「接口配置」里换一套'
                                '本地的给助手就行。' % (协议 or '空'), '步': 0})
            return

        # ⚠ **设置页手填的上下文优先，0 = 「自动」。**
        #
        # 顺序很要命：**先读出来，再让它被覆盖**。这跟上面 `'自动'` 那个坑
        # 是同一类错 —— 先覆盖再读的话，手填的值会被自己算出来的值盖掉，
        # 症状是"设置里明明填了，跑起来一点没变"。
        try:
            手填 = max(0, int(设置.get('上下文') or 0))
        except (TypeError, ValueError):
            手填 = 0

        # ⚠ **把接口配置里的 `n_ctx` 传下去，预算按它分。** 早先预算是写死的
        # 4300 token —— 那是按"每轮全量 prefill"的错误前提定的。实测下来
        # 追加式对话每轮只要 0.4~0.7 秒（跟提示词总长几乎无关），所以
        # **写得下就别折**：折一次比跑好几轮还慢，折掉的还是模型刚读过的代码。
        try:
            本机 = int(配置.参数().get('n_ctx') or 0)
        except (TypeError, ValueError):
            本机 = 0
        本机 = 本机 or 酒馆本地.默认上下文
        # ⚠ **`min` 这一下不能省。** 提示词一旦越过实例的 `n_ctx`，
        # llama.cpp 会**从前面截断**，最先丢的正是系统提示和工具协议 ——
        # 模型会毫无提示地"忘记规矩"，界面上一点异常都看不出来。
        # 这是整条链路上最隐蔽的坏法，宁可把用户填的值压回去。
        设置['上下文'] = min(手填, 本机) if 手填 else 本机

        是否原生 = (设置['工具协议'] == '原生')

        def 调模型(系统, 消息们, 工具定义们, 原生, 上限):
            self.阶段.emit('想', '模型正在想…')
            return 酒馆大脑.跑一轮(
                配置, 系统, 消息们,
                工具=工具定义们 if 原生 else None,
                要工具='auto' if 原生 else '从不',
                停=self._停, 段回=self._段, 最大输出=上限)

        def 事件(类, 数):
            if 类 == '开始':
                self.阶段.emit('开工', '工作目录 %s' % 数.get('根'))
                self.预算.emit(数.get('预算') or {})
            elif 类 == '步':
                self.步.emit(数['第'], 数['共'], 数['token'])
                self.阶段.emit('想', '第 %d / %d 步，正在处理提示词（这点时间本地模型停不下来）'
                              % (数['第'], 数['共']))
            elif 类 == '折叠':
                self.阶段.emit('折', '较早的 %d / %d 步已折叠成摘要' %
                              (数['折了'], 数['共']))
            elif 类 == '卡':
                self.卡.emit(数.get('号', 0), 数)
            elif 类 == '催':
                # ⚠ **这条以前没人接。** 模型光说打算（或者干脆一个字都没写）
                # 的时候，循环会推它一把再问一次 —— 可界面一个字都不显示，
                # 用户看到的是"停在那儿不动了几秒，然后报了个错"，完全不知道
                # 中间发生过什么。这种"看不见的重试"最容易被当成卡死。
                self.阶段.emit('催', '模型这一轮没动手，推它一把（第 %d 次）…'
                              % 数.get('次', 1))
            elif 类 == '解析催':
                # 跟 `催` 一个道理：这类重试**用户看不见**，最容易被当成卡死。
                # 而且这条更该说清 —— 要让他知道是**工具调用的格式**崩了、
                # 正在让它重写，而不是模型在发呆。
                self.阶段.emit('解析催', '工具调用的格式崩了（多半是引号没转义'
                                        '或内容被截断），让它重写一遍（第 %d 次）…'
                              % 数.get('次', 1))
            elif 类 == '完':
                pass

        酒馆本地.开始任务()
        # 抄本一建好就落进这个盒子 —— 这样下面不管是从 `跑` 正常返回、还是
        # 它抛了个预料外的错，都能拿到转录本（见 `跑` 的 `交出`）。
        兜 = {}
        try:
            r = 酒馆助手.跑(根, 任务, 调模型, 要批=self._要批, 事件=事件,
                          停=self._停, 设=设置,
                          交出=lambda 记: 兜.update(记=记))
        except Exception as 错:
            # ⚠ **自己接住，不让它冒到 `run()`。** 冒上去的话这条 `完` 里
            # 就没有转录本，这一次任务在盘上等于从没发生过 —— 而它明明跑过
            # （模型调了、文件可能都改了）。形状跟 `run()` 里那句一致。
            r = {'坏': '%s：%s' % (type(错).__name__, 错), '步': 0}
        finally:
            酒馆本地.结束任务()

        if 兜.get('记') is not None:
            # 转录本跟着 `完` 一起出去，落盘由 `助手页` 投给工位去做。
            # ⚠ **这条线仍然一个字节不碰存储** —— 它的安全形状就是手上没有
            # 能误用的 `库` 引用，见文件头第一条理由。
            r = dict(r, 转录本=兜['记'].到字典())
        self.完.emit(r)

    def _段(self, 字):
        self.正文.emit(字)


def 酒馆大脑校验(配置):
    """校验这套配置发不发得出去。"""
    return 酒馆大脑.校验配置(配置)


def 默认工具协议(配置):
    """
    这套配置该走原生工具还是文本协议。

    ⚠ **只剩本地这一路了**（云端那条已整段删掉，见 `酒馆大脑` 那段注释）。

    判据是**读 GGUF 里的聊天模板** —— 这是唯一"能真的看到"的判据：
    `qwen2.5` 系模板里有 `{%- if tools %}`，会真的把工具定义渲染进提示词；
    而 `DeepSeek-R1-Distill` 全系没有（那是它调不了工具的真正原因）。
    ⚠ 判据是 `tools` 不是 `tool_call`，见 `酒馆本地.有工具模板`。

    ⚠ **判错的场合要能绕。** 启发式一定有错的时候，所以留了「工具协议」开关
    （自动 / 原生 / 文本）：显式传 `'原生'` / `'文本'` 就轮不到这个函数。
    """
    协议 = (配置.协议 or 'local') if 配置 is not None else 'local'
    if 协议 != 'local':
        # 云端已经不给助手用了（`_干` 会当场拦住）。真要走到这儿也**不发
        # `tools=`** —— 文本协议是唯一哪家都吃不坏的那条路。
        return '文本'
    try:
        return '原生' if 酒馆本地.有工具模板(酒馆本地.定位(配置.模型)) else '文本'
    except Exception:
        return '文本'
