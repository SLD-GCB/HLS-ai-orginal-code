#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
酒馆接口.py — 模型 API 配置的存取

一套配置 = 地址 + 密钥 + 模型 + 采样参数 + 附加头。可以存很多套，
对话时挑一套用；会话没指定（`接口编号 = 0`）就落到 `默认()` 那套。

配置落在 `酒馆数据/接口配置.json`，一张表一个文件。

⚠ **密钥目前是明文存的。** 这件事换到 JSON 文件之后**没有变好**：文件就在
程序旁边，谁打得开这个目录谁就读得到密钥。`列()` 里不带密钥是因为界面列表
用不上它，**不是**因为这样就能保密。
"""

from 酒馆模型 import 接口配置, 写JSON, 协议们
from 酒馆存储 import 酒馆错误, 毫秒

__all__ = ['建', '取', '列', '改', '删', '默认', '取或默认', '协议们', '可改字段']

# 这两列存的是 JSON 文本。调用方可以直接给 dict/list，这里负责转文本
# ——让每个调用点自己 `json.dumps` 迟早会有人忘了，然后存进去一个
# Python 的 repr，读的时候解不出来还不报错。
JSON列 = ('采样参数', '附加头')

#: 清单里给的列。**故意没有 `密钥`** —— 列表要拿去渲染界面，密钥没必要
#: 跟着到处跑。要用密钥的地方自己 `取()`。
清单列 = ('编号', '名称', '协议', '地址', '模型', '创建于', '更新于')

可改字段 = frozenset(接口配置.列名()) - {'编号', '创建于'}


def _正JSON(字段):
    """把 JSON 列上的 dict/list 转成文本。原样返回一个新字典。"""
    出 = dict(字段)
    for 名 in JSON列:
        if 名 in 出 and not isinstance(出[名], str):
            出[名] = 写JSON(出[名])
    return 出


def 建(库, 名称, 协议='openai', 地址='', 密钥='', 模型='',
      采样参数=None, 附加头=None, 工具格式='自动'):
    """建一套接口配置，返回建好的（带着发下来的编号）。"""
    名称 = (名称 or '').strip()
    if not 名称:
        raise 酒馆错误('接口配置得有个名字——存多套的时候全靠它认人')
    if 协议 not in 协议们:
        raise 酒馆错误('协议只认 %s（给的是 %r）' % ('、'.join(协议们), 协议))
    现在 = 毫秒()
    行 = {'编号': 库.发号('接口配置'), '名称': 名称, '协议': 协议, '地址': 地址,
          '密钥': 密钥, '模型': 模型, '工具格式': 工具格式,
          '采样参数': 写JSON(采样参数),
          '附加头': 写JSON(附加头), '创建于': 现在, '更新于': 现在}
    库.存('接口配置', 行)
    return 接口配置.从行(行)


def 取(库, 编号):
    """按编号取一套（**含密钥**）。没有就返回 `None`。"""
    行 = 库.取('接口配置', 编号)
    return 接口配置.从行(行) if 行 else None


def 列(库):
    """
    列出全部配置，按编号升序。

    ⚠ 回来的**不含 `密钥`**（`清单列` 里故意没有它）——列表要拿去渲染界面，
    密钥没必要跟着到处跑。要用密钥的地方自己 `取()`。
    """
    行们 = []
    for 整个 in 库.全都('接口配置'):
        行们.append({k: 整个.get(k) for k in 清单列})
    return [接口配置.从行(行) for 行 in 行们]


def 改(库, 编号, **字段):
    """
    改几个字段，`更新于` 自动跟着走。改到了返回 `True`。

    底下是「读出来 → 合上新值 → 写回去」，所以**那次读必须成功**：
    读不到就当没改，绝不能拿一份空的去盖。
    """
    字段 = _正JSON(字段)
    坏的 = set(字段) - 可改字段
    if 坏的:
        raise 酒馆错误('改不了这些字段：%s（能改的是 %s）'
                      % ('、'.join(sorted(坏的)), '、'.join(sorted(可改字段))))
    if not 字段:
        return False
    if '名称' in 字段 and not str(字段['名称'] or '').strip():
        raise 酒馆错误('名字不能改成空的——列表里全靠它认人')
    if '协议' in 字段 and 字段['协议'] not in 协议们:
        raise 酒馆错误('协议只认 %s（给的是 %r）'
                      % ('、'.join(协议们), 字段['协议']))

    with 库.独占():          # 读-改-写要是一整段，见 `酒馆存储.库.独占` 那条
        整行 = 库.取('接口配置', 编号)
        if 整行 is None:
            return False
        整行.update(字段)
        整行['更新于'] = 毫秒()
        库.存('接口配置', 整行)
    return True


def 删(库, 编号):
    """删一套配置。**引用了它的会话不会跟着变**——那些会话的 `接口编号` 会变成
    一个取不到的号，`取或默认()` 会把它们兜到默认那套上。"""
    return 库.删('接口配置', 编号)


def 默认(库):
    """
    挑一套默认的：**编号最小的那套**（= 最早建的）。

    会话的 `接口编号 = 0` 就是这个意思。用"最早建的那套"而不是"最后用的那套"，
    是因为后者需要一个额外的状态位，在多线程下是个共享可变状态——为省一次
    点击引入一个要同步的东西，不划算。
    """
    行们 = 库.全都('接口配置')          # `全都` 按主键升序，第一条就是编号最小的
    return 接口配置.从行(行们[0]) if 行们 else None


def 取或默认(库, 编号):
    """按编号取；取不到（或者编号是 0）就落到默认那套。都没有返回 `None`。"""
    if 编号:
        配置 = 取(库, 编号)
        if 配置 is not None:
            return 配置
    return 默认(库)
