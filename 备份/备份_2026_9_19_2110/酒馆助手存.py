#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
酒馆助手存.py — 编程助手的转录本存取

**这个文件不认识 Qt。** 它只做一件事：把「一次任务跑完之后的转录」落成盘上
的一份 JSON，并让人能按编号把它翻出来看。

两层落地，跟 `会话`+`消息` 是同一种分法：

    助手任务.json          {"<编号>": {任务 / 工作目录 / 步数 / 结局 / 创建于}}
    助手转录/<编号>.json   {任务 / 根 / 步们 / 最后(真正发出去的那一份) / …}

**为什么转录不放在小表里。** 一次任务的转录里可能有整个文件那么长的工具结果
（让模型写个网页，光一次 `write_file` 的参数就是几千字）。放进小表就是
"列一次任务清单，把全部任务的正文都读进内存" —— 而清单只想拿一行标题。

**先写大件、后写清单行。** 反过来（先清单后转录）时，要是转录写失败，列表里
就多出一条**点开是空的**记录 —— 用户看不出是失败了，只当程序坏了。先写转录
的话，最坏是盘上多一个没人引用的文件（`删任务` 的顺序同理反向）。
"""

import json

from 酒馆存储 import 酒馆错误, 毫秒

__all__ = ['结局们', '存一次', '列任务', '取任务', '取转录', '取一件', '删任务']

#: 一次任务的结局就这三种。**存的是短码，不是那句话** —— 说明文案可能有
#: 几百字，而 `助手任务` 是整张读进内存的小表。
#:   `答复` 好好干完了（带一段结论）
#:   `坏`   是明确报的错（解析失败 / 空回复 / 没有进展 / 上下文满 / 步数用尽）
#:   `停`   用户自己喊的停
结局们 = ('答复', '坏', '停')

#: 清单里那行任务摘要留多长。够认出是哪次任务就行 —— 全文一个字不少地
#: 躺在转录文件里。
摘要宽 = 60
#: `结局说明` 在小表里最多留多少字。长文案在转录里。
说明宽 = 120


def _一行(文, 宽):
    """压成一行、太长就切。**给清单用的**，不是给正文用的。"""
    文 = ' '.join(str(文 or '').split())
    return 文[:宽] + ('…' if len(文) > 宽 else '')


def _洗(对象):
    """
    把转录洗成"一定 `json.dump` 得下去"的形状。

    ⚠ **为什么不改 `酒馆存储._写` 去加 `default=str`：** 那一层是**所有**
    数据共用的出口，在那儿放宽等于把"存了个塞不进去的东西"这件事**静默**
    了 —— 别的表存进去一个 `bytes`，读回来变成字符串，谁也不报错。清洗只在
    这一条链路上做，坏形状就在这儿被挡住。

    做法是走一遍 JSON 往返（`default=str` 兜住认不出来的类型）。代价是
    落盘那一下多占一份内存，换来的是**盘上永远不会出现半份对象**。
    """
    try:
        return json.loads(json.dumps(对象, ensure_ascii=False, default=str))
    except (TypeError, ValueError) as 错:
        raise 酒馆错误('这次任务的转录里有存不下去的东西：%s' % 错, '存转录')


# ── 写 ──────────────────────────────────────────────────────────────

def 存一次(库, 转录本, 结局, 说明=''):
    """
    存一次任务。返回发下来的编号。

    `转录本` 是 `酒馆助手.抄本.到字典()` 那一份（`跑` 跑完就交出来的）。
    `结局` 是 `结局们` 里的一个；`说明` 是给人看的一句（存不下长文案）。
    """
    if not isinstance(转录本, dict):
        raise 酒馆错误('转录本得是个 dict（拿到的是 %s）'
                      % type(转录本).__name__, '存转录')
    干净 = _洗(转录本)

    # 发号 + 两次写是**一段** read-modify-write：分开取锁的话，两条线程同时
    # 存就会拿到同一个号，后写的把先写的整个盖掉（`库.独占` 那条注释）。
    with 库.独占():
        编号 = 库.发号('助手任务')
        干净['编号'] = 编号
        库.存转录(编号, 干净)                     # 先大件，见文件头
        库.存('助手任务', {
            '编号': 编号,
            '任务': _一行(干净.get('任务'), 摘要宽),
            '工作目录': str(干净.get('根') or ''),
            '步数': len(干净.get('步们') or []),
            '结局': str(结局 or ''),
            '结局说明': _一行(说明, 说明宽),
            '创建于': 毫秒(),
        })
    return 编号


def 删任务(库, 编号):
    """
    删掉一次任务（转录 + 清单行）。删到了返回 `True`。

    ⚠ **先转录、后清单行**，见文件头。反过来的话，删到一半失败就留下一个
    "清单里没有、盘上却占着"的孤儿文件，而那个文件再也没人找得到。
    """
    with 库.独占():
        有过 = 库.取('助手任务', 编号) is not None
        库.删转录(编号)
        库.删('助手任务', 编号)
    return 有过


# ── 读 ──────────────────────────────────────────────────────────────

def 列任务(库):
    """
    全部任务，**按创建时间降序**（最近跑的在最前面）。

    ⚠ 清单里**不含转录正文** —— 那正是把它分文件放的理由。要看内容得
    `取一件()`。
    """
    行们 = 库.全都('助手任务')
    行们.sort(key=lambda 行: int(行.get('创建于') or 0), reverse=True)
    return 行们


def 取任务(库, 编号):
    """一次任务的清单行。没有就返回 `None`。"""
    return 库.取('助手任务', 编号)


def 取转录(库, 编号):
    """一次任务的转录。没有（或者坏了）就返回 `None`。"""
    return 库.取转录(编号)


def 取一件(库, 编号):
    """
    `(清单行, 转录)` —— 给界面用。

    ⚠ **合成一件，不是两件。** 分两次投活的话，中间那次刷新可能正好撞上
    `删任务`，于是"行还在、转录没了"，画出来是一个空的步骤列表。
    """
    return 取任务(库, 编号), 取转录(库, 编号)
