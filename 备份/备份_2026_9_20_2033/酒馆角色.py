#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
酒馆角色.py — 角色的存取

角色落在两样东西上：`角色卡` 装字（`酒馆数据/角色卡.json`），头像装图
（`酒馆数据/头像/<编号>.json`，一角色一个文件）。

**为什么头像要单开一处：** 头像是几百 KB 的二进制，跟角色卡挤在一个文件里
就等于每次「列个角色清单」都把所有人的头像读一遍、改一个人的头像就把所有人
的重写一遍。分开之后 `列()` 只碰角色卡，头像谁要谁取。

⚠ **删角色是连带的**：他的头像、会话、消息、还有挂在角色上的长期记忆一起没。
见 `删()`。（按**工作目录**挂的编程助手项目记忆不在此列 —— 那是那个目录的。）
"""

from 酒馆模型 import 角色卡
from 酒馆存储 import 酒馆错误, 毫秒

import 酒馆记忆

__all__ = ['建', '取', '列', '改', '删', '存头像', '取头像', '删头像']

# 清单只取这几列。`人设` / `开场白` / `示例对话` 都是大段文字，列清单用不上
# ——`列()` 回来的角色卡那几个字段是空的，要就去 `取()`。
清单列 = ('编号', '名字', '简介', '标签', '创建于', '更新于')

可改字段 = frozenset(角色卡.列名()) - {'编号', '创建于'}


def 建(库, 名字, 简介='', 人设='', 开场白='', 示例对话='', 标签=''):
    """建一个角色，返回建好的（带着发下来的编号）。"""
    名字 = (名字 or '').strip()
    if not 名字:
        raise 酒馆错误('角色得有个名字——没有名字的话左栏里认不出谁是谁')
    现在 = 毫秒()
    行 = {'编号': 库.发号('角色卡'), '名字': 名字, '简介': 简介, '人设': 人设,
          '开场白': 开场白, '示例对话': 示例对话, '标签': 标签,
          '创建于': 现在, '更新于': 现在}
    库.存('角色卡', 行)
    return 角色卡.从行(行)


def 取(库, 编号):
    """按编号取一个角色（全部文字字段）。没有就返回 `None`。"""
    行 = 库.取('角色卡', 编号)
    return 角色卡.从行(行) if 行 else None


def 列(库):
    """
    列出全部角色，按编号升序（= 建的先后）。

    ⚠ 回来的角色卡**只有 `清单列` 那几个字段**，`人设` / `开场白` /
    `示例对话` 是空的。列表场景不该把每个人的全部设定都读进内存。
    """
    行们 = []
    for 整个 in 库.全都('角色卡'):
        行们.append({k: 整个.get(k) for k in 清单列})
    return [角色卡.从行(行) for 行 in 行们]


def 改(库, 编号, **字段):
    """
    改几个字段，`更新于` 自动跟着走。改到了返回 `True`。

    **只认模型上有的字段**，拼错一个当场报错——不然那句改要么安静地什么都
    不动，要么写进去一个将来没人读得懂的键，两种都难查。

    底下是「读出来 → 合上新值 → 写回去」。这里跟数据库那一版有个要紧的
    区别：**JSON 底下没有 `UPDATE` 那种只动几列的东西**，写回去的是整行
    ——所以那次读必须成功，读不到就当没改，绝不能拿一份空的去盖。
    """
    坏的 = set(字段) - 可改字段
    if 坏的:
        raise 酒馆错误('改不了这些字段：%s（能改的是 %s）'
                      % ('、'.join(sorted(坏的)), '、'.join(sorted(可改字段))))
    if not 字段:
        return False
    if '名字' in 字段 and not str(字段['名字'] or '').strip():
        raise 酒馆错误('角色名字不能改成空的')

    with 库.独占():          # 读-改-写要是一整段，见 `酒馆存储.库.独占` 那条
        整行 = 库.取('角色卡', 编号)
        if 整行 is None:                 # 读到整行才敢写回去
            return False
        整行.update(字段)
        整行['更新于'] = 毫秒()
        库.存('角色卡', 整行)
    return True


def 删(库, 编号):
    """
    删一个角色，**连带他的会话、消息、头像、还有他的长期记忆**。

    顺序是照着"半截了会怎样"排的：**先删消息、再删会话、再删记忆和头像，
    最后才删角色卡本身**。真停在中间，剩下的是"没有角色的空会话"或者
    "没有头像/记忆的角色"——界面上都还看得见、还能再删一次。反过来先删角色卡，
    剩下的就是一堆谁也认不出来的孤儿文件。

    ⚠ **要删的只有"挂在角色身上"的那份记忆**（`类型='角色'`）。编程助手那种
    **按工作目录挂的项目记忆不动** —— 它属于那个目录，不属于这个角色。
    界面上也是这么说的（见 `酒馆上下文页` 那两页的抬头）。

    回 `True` = 角色卡本身删掉了。
    """
    会话号 = [s.get('编号') for s in 库.全都('会话')
             if int(s.get('角色编号') or 0) == int(编号)]
    for 号 in 会话号:
        库.删消息们(号)              # 先消息：会话还在的话，界面上还点得进去
    for 号 in 会话号:
        库.删('会话', 号)
    酒馆记忆.删(库, 酒馆记忆.角色, 编号)   # 记忆：没了就是空的，不挡事
    库.删头像(编号)                  # 头像：没了就画成空白，不挡事
    return 库.删('角色卡', 编号)      # 最后才轮到角色卡本身


# ── 头像 ────────────────────────────────────────────────────────────

def 存头像(库, 角色编号, 图, 类型=''):
    """
    存或者换头像。

    **是覆盖不是追加**：换头像就是对同一个角色覆盖。底下 `库.存头像`
    一个角色一个文件，写下去就是整个换掉。
    """
    return 库.存头像(角色编号, 图, 类型)


def 取头像(库, 角色编号):
    """取头像，返回 `(字节, 类型)`；没有就返回 `None`。"""
    return 库.取头像(角色编号)


def 删头像(库, 角色编号):
    return 库.删头像(角色编号)
