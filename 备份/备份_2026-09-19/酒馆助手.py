#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
酒馆助手.py — 编程助手的主循环：调模型 → 看它要调什么工具 → 执行 → 回喂 → 再来

**这个文件不 import Qt。** 循环、转录本、上下文预算这三块是最需要脱开界面
反复试的东西（模型不听话时出问题的全在这儿），绑上 Qt 就没法痛快测了。

三件事：

    系统提示()   规矩 + 工具协议 + 工作目录。**每个字都占预算**，写得很省
    抄本         一次任务的转录本，四段结构 + 确定性折叠（见 `抄本.消息`）
    跑()         主循环。除了 `调模型` 和 `要批` 两个回调，它不认识外面

════════════════════════════════════════════════════════════════════
为什么这么设计（踩过的和想清楚的）
════════════════════════════════════════════════════════════════════

**一、折叠用确定性策略，不让模型摘要。** 一次摘要就是一次额外生成，在 8K
上下文里等于**为了省 token 先花一次 prefill**；而且小模型摘要经常把关键
信息摘没（"改的是哪个函数"没了）。改成把工具结果的正文换成一行存根，
**保留工具名和参数** —— 零成本、零幻觉、结果可预测。

**二、折叠要攒够了一次性折。** llama.cpp 会复用与上次输入的最长公共前缀的
KV，**折叠是改写历史中段，会把公共前缀从改写点起全部作废**，下一次要整段
重新 prefill（用户实测 17K 要 52 秒）。所以每 4 步才折一次，而不是每步都
轻轻改一点。

**三、提示词绝不越线。** 一旦 prompt 超过 `n_ctx`，llama.cpp 会**从前面
截断** —— 最先丢的正是系统提示和工具协议，模型会毫无提示地"忘记规矩"，
界面上看不出任何异常。这是整条链路上最隐蔽的一种坏法。所以折叠完还超限
就**中止任务**，不硬撑。
"""

import os
import re

import 酒馆工具

__all__ = ['助手错', '设置', '抄本', '跑', '系统提示', '文本协议', '默认设置',
           '分预算', '留白比例']


class 助手错(Exception):
    """助手这一层的错。文案写给人看。"""


#: 系统提示大概占多少 token。它是固定长度的一段（规矩 + 工具协议 + 工作目录），
#: 实测在 250~900 之间，取上限当预留。
系统预留 = 900

#: 给模板特殊 token（BOS、角色标记）和**估算误差**留的比例。
#:
#: ⚠ 留这个不是洁癖：`估token` 的公式有误差，估**低**了会让提示词真的越过
#: `n_ctx` —— 而一旦越线，llama.cpp 会**从前面截断**，最先丢的正是系统提示
#: 和工具协议，模型会在毫无提示的情况下"忘记规矩"。宁可多留。
留白比例 = 0.06


def 分预算(n_ctx, 设=None):
    """
    从 `n_ctx` 推各项预算。回 `{'系统','转录本','输出','余量','总'}`。

    ⚠ **为什么不写死一个数**（早先就是写死 4300 的，改掉了）。

    实测：agent 是**追加式**的对话，llama.cpp 的 prefix cache 让每轮只 prefill
    新增的那几百 token —— 提示词从 747 涨到 10643 token，单轮耗时只从 0.40s
    涨到 0.73s。**速度几乎不受上下文长度影响。**

    真正贵的是**折叠**（改写历史中段、把从改写点起的 KV 全作废）：同样在
    10.6K 上，折叠一轮要 6.31s，是追加的 **9 倍**，而且是平方级涨的。

    所以正确的取舍是：**用显存换上下文**。写得下就别折 —— 折一次比跑好几轮
    还慢，而且折掉的是模型刚读过的代码，它多半得重读一遍。

    写死 4300 时，转录本只够放约 8000 字符的工具结果 ≈ 3~6 步就得折一次；
    而一个真实的编程任务要 8~15 步。按 `n_ctx` 分就对了：8192 给约 5800，
    16384 给约 14000。
    """
    设 = 设 or {}
    try:
        n = int(n_ctx or 0) or 8192
    except (TypeError, ValueError):
        # `n_ctx` 是从接口配置的 `采样参数` JSON 里读的，那是**能手打的格子**，
        # 写成 `"x"` 或者 `"8k"` 都有可能。读不出来就当没设 —— 跟
        # `酒馆模型.读JSON` 那条"坏配置不该让功能打不开"一个道理。
        n = 8192
    n = max(64, n)
    出 = min(max(64, int(设.get('单步输出') or 默认设置['单步输出'])),
            max(64, n // 4))
    系 = min(系统预留, max(64, n // 6))
    余 = max(32, int(n * 留白比例))
    转 = n - 出 - 系 - 余
    if 转 < 400:
        # `n_ctx` 小到离谱（界面下限是 512）。这时候**按比例摊**，别用
        # 各项的固定下限去凑 —— 那样加起来会超过 n 本身，算出一个根本
        # 装不下的预算，比不报错还糟。摊完保证四项加起来正好是 n。
        转 = max(1, n * 2 // 5)
        系 = max(1, n // 5)
        出 = max(1, n // 5)
        余 = max(0, n - 转 - 系 - 出)
    return {'总': n, '系统': 系, '转录本': 转, '输出': 出, '余量': 余}


#: 一次任务的默认参数。界面上的「设置」就是改这几个。
#:
#: ⚠ **`提示词预算` 和 `系统预算` 不在这儿写死了** —— 它们从 `n_ctx` 推，
#: 见 `分预算`。接口配置里的 `n_ctx` 是多少，这里就跟着分多少。
#: ⚠ **`单步输出` 从 1024 抬到 4096 了，理由值得写下来。**
#:
#: 1024 是照"小模型改几个函数"定的。但**写一个网页、写一个完整文件**动辄
#: 两三千 token —— 撞上这个上限就是两种坏法，而且都不报错：
#:
#:   ① 工具调用的参数被**截在半路** → 写出来一个残缺文件，或者干脆解析失败
#:   ② 对面是带思维链的模型（deepseek 这类）时，**思维链也吃这个预算** ——
#:      思维链一写长就把额度用光，正文和工具调用一个字都生不出来，我们这边
#:      看到的是"模型什么都没输出"，而循环还以为"干完了"
#:
#: 抬到 4096 只影响装得下的那档：`分预算` 里 `出` 还被 `n_ctx // 4` 压着，
#: 所以 `n_ctx=4096` 的本地模型**一点没变**（还是 1024），大上下文的那档才拿到。
默认设置 = {
    '最大步数': 12,
    '保留步数': 6,           # 最近几步保持完整，再旧的才折
    '工具协议': '自动',       # 自动 / 原生 / 文本
    '单步输出': 4096,
    '上下文': 0,             # 实际 n_ctx；0 = 用 `酒馆本地.默认上下文`
}
设置 = dict


def _定(设, 键):
    值 = (设 or {}).get(键)
    if 值 is None:
        return 默认设置[键]
    return 值


# ── 系统提示 ────────────────────────────────────────────────────────

#: 工具协议的**文本版**：给"聊天模板里没有 tools 支持"的模型用。
#:
#: ⚠ 写得很省是有意的 —— 它整段都占预算。所以只列名字加一句参数提示，
#: 参数细节靠 `工具定义` 那边的 schema 在"原生"模式下注入；文本模式下
#: 就靠这个表和一次调用示例。
文本协议 = """可用工具（要调就输出 <tool_call>{"name":"工具名","arguments":{...}}</tool_call>）：

  read_file  {"path":"相对路径","start":1,"count":100}   读文件，带行号
  list_dir   {"path":".","depth":1}                      列目录
  search     {"pattern":"要找的字","path":".","what":"内容","limit":50}
  write_file {"path":"相对路径","content":"完整内容"}     整个覆盖写
  edit_file  {"path":"相对路径","old":"原文","new":"新文","all":"否"}
  run_cmd    {"cmd":"命令","timeout":30}                 跑命令

一次可以给多个 <tool_call>，会按顺序执行。
例：
<tool_call>{"name":"read_file","arguments":{"path":"src/main.py","start":1,"count":100}}</tool_call>"""


def 系统提示(根, 盘符=None, 协议='自动', 是否原生=False):
    """
    拼系统提示。`根` 是工作目录，`是否原生` 说明这次会不会传 `tools=`。

    ⚠ **每个字都占预算，所以写得很省。** 整段目标 ≤900 token，见 `默认设置`
    里的 `系统预算`。

    几条必须写死的规矩，各自对应小模型真会犯的错：

      · **工作目录的绝对路径要写在第一行** —— 不说它就会拿"项目名/src/a.py"
        当路径，而根其实已经是项目了
      · **不许替用户做决定 / 不许假装命令跑过了** —— 小模型最常见的毛病是
        没调工具就直接说"我已经修改好了"
      · **看到"（已截断）"要知道内容不全** —— 不说它会把半截文件当全部
      · **`[工具结果]` 前缀的消息是工具返回，不是用户说的话** —— 因为
        工具结果是用 user 角色回喂的（很多模板不认 role='tool'）
    """
    根真 = os.path.realpath(根)
    段 = [
        '你是一个在自己电脑上干活的编程助手。%s' % 酒馆工具.根目录说明(根),
        '一切路径都相对工作目录，不要写绝对路径，不要用 .. 往外跳。',
        '',
        '规矩：',
        '1. **要动手就调工具，不要只说打算。** 说"我先创建文件"而不调工具'
        '等于什么都没发生 —— 用户只会看到一句空话。',
        '2. **先建/改文件，再跑命令。** 文件还不存在就去跑它，只会拿到一句'
        '"找不到文件"，白费一步。顺序：写文件 → 跑它 → 看输出 → 改。',
        '3. 一次只做该做的那一步，等工具结果回来再决定下一步。',
        '4. 带 [工具结果] 开头的消息是工具返回的，不是你或用户说的话。',
        '5. 工具结果里出现「（已截断）」「（中间省略）」时说明内容不全。'
        '要完整内容就 read_file 带 start/count 分段读。',
        '6. 改一点内容用 edit_file（old 要在文件里唯一），别用 write_file 重写整个文件。',
        '7. 写完东西要**自己跑一遍验证**（至少 python -m py_compile 或直接运行）。'
        '没验证过就说"写好了"，多半是错的。',
        '8. 干完了、或者确实没办法了，就**直接说结论**，不要再输出 <tool_call>，'
        '也不要再说"我先…"。',
        '9. 说不清楚的时候先 list_dir 看目录，别猜。',
        '',
    ]
    if 协议 == '原生' or (协议 == '自动' and 是否原生):
        段.append('要调工具就输出 <tool_call>{"name":...,"arguments":{...}}</tool_call>。')
    else:
        段.append(文本协议)
    return '\n'.join(段)


# ── 转录本 ──────────────────────────────────────────────────────────

#: 折叠后显示的存根前缀。系统提示里第 4 条解释了它。
折叠标 = '[已折叠]'


class 抄本(object):
    """
    一次任务的转录本。**四段固定结构**：

        ① 系统提示（不算在这儿，`消息` 里现拼）
        ② 任务原文 —— **永不丢**
        ③ 已折叠步骤的存根
        ④ 最近 K 步的完整记录

    `步` 的粒度 = **一条助手输出 + 它引发的所有工具结果**。这个粒度是对的：
    折叠时"做了什么、拿到什么"要成对保留才有意义。
    """

    def __init__(self, 根, 任务, 协议='自动', 是否原生=False, 设=None):
        self.根 = 根
        self.任务 = 任务
        self.协议 = 协议
        self.是否原生 = 是否原生
        self.设 = 设 or {}
        self.步们 = []
        self.折到 = 0          # 前多少步已经被折了
        self.上次折 = 0        # 上次折叠时是第几步（见文件头第二条）

    # ── 记 ──

    def 记助手(self, 正文, 原始=''):
        self.步们.append({'助手': 正文, '原始': 原始, '结果们': []})

    def 记结果(self, 名, 参, 文本):
        if not self.步们:
            self.步们.append({'助手': '', '原始': '', '结果们': []})
        self.步们[-1]['结果们'].append({'名': 名, '参': 参, '文': 文本})

    def 记催(self):
        """记一次"推它一把"。当成一条系统消息挂在当前步的结果里。"""
        self.记结果('（系统）', {}, 催话)

    # ── 拼 ──

    def _存根(self, 步):
        """一步 → 一行存根。**保留工具名和参数**，那是"我做过什么"的记忆。"""
        条 = []
        for r in 步['结果们']:
            参 = r['参'] if isinstance(r['参'], dict) else {}
            简短 = '，'.join('%s=%r' % (k, v) for k, v in list(参.items())[:3])
            首 = (r['文'] or '').split('\n')
            摘要 = 首[0][:60] if 首 else ''
            条.append('%s %s(%s) → %s' % (折叠标, r['名'], 简短, 摘要))
        if not 条:
            条.append('%s 说了一段话：%s' % (折叠标, (步['助手'] or '')[:60]))
        return '\n'.join(条)

    def _尺寸(self, 折到):
        """折到第 `折到` 步之后，整个提示词大概多少 token。"""
        尺寸 = 酒馆工具.估token(self.任务)
        for 步 in self.步们[:折到]:
            尺寸 += len(self._存根(步)) // 2      # 存根很短，粗算即可
        for 步 in self.步们[折到:]:
            尺寸 += 酒馆工具.估token(步['助手'])
            for r in 步['结果们']:
                尺寸 += 酒馆工具.估token(r['文'] or '')
        return 尺寸

    def _存根块(self, 折到, 预算):
        """
        折起来那几步的存根，拼成一块。

        ⚠ **存根本身也会攒爆。** 十步的存根加起来能比预算还大 ——
        折叠本身没解决问题，只是把"大结果"换成了"很多小存根"。所以
        存根块也有上限：超了就从**最旧的**开始丢，只留最近的，前面用
        一行说明丢了几步。丢的是存根不是记录，`步们` 一直留着全文。
        """
        行们 = [self._存根(步).strip() for 步 in self.步们[:折到]]
        丢 = 0
        while 丢 < len(行们) - 1 and len('\n'.join(行们[丢:])) // 2 > 预算:
            丢 += 1
        头 = ''
        if 丢:
            头 = '（更早的 %d 步已略去，只留着最近的。）\n' % 丢
        return 头 + '\n'.join(行们[丢:])

    def 消息(self, 预算=None, 保留=None, 折了=None):
        """
        拼出给模型的 `messages`。**顺便决定折叠到第几步**（`折了` 是回调）。

        折的顺序是**从最旧的一端连续折**，绝不挖中间 —— 挖中间会把公共
        前缀从那一处起全部作废，比从头折还贵（见文件头第二条）。

        ⚠ **折的时候要多折一点，一次折够。** 因为折叠是改写历史中段，
        下一次调用的 KV 公共前缀从改写点起全部作废、要整段重新 prefill。
        每步只折一丁点的话，就是每步都付一次全额 prefill。所以一旦确定
        要折，就折到预算的 3/4 —— 换几次"本来还得再折"的来回。

        ⚠ **不能为了"少折几次"就不折。** 早先的写法是"没攒够间隔就把这次
        折叠退回去"，那样上下文会重新超限、然后被硬上限误杀 —— 用户看到
        的是"任务莫名其妙停了"。**越线比多付一次 prefill 严重得多。**
        """
        预算 = int(预算 if 预算 is not None
                 else 分预算(_定(self.设, '上下文'), self.设)['转录本'])
        保留 = max(1, int(保留 if 保留 is not None else _定(self.设, '保留步数')))

        系统 = 系统提示(self.根, 协议=self.协议, 是否原生=self.是否原生)
        系统小号 = 酒馆工具.估token(系统)
        上限步 = max(0, len(self.步们) - 保留)      # 最多能折到这儿

        折到 = self.折到
        while 折到 < 上限步 and (self._尺寸(折到) > 预算
                              or len(self.步们) - 折到 > 保留):
            折到 += 1

        if 折到 > self.折到:
            # 已经在折了，就一次折够（见上面第二条）
            目标 = 预算 * 3 // 4
            while 折到 < 上限步 and self._尺寸(折到) > 目标:
                折到 += 1
            self.折到 = 折到
            if 折了:
                折了(self.折到)

        存根 = self._存根块(self.折到, max(200, 预算 // 2)) if self.折到 else ''
        小号 = 系统小号 + self._尺寸(self.折到)
        if 存根:
            小号 += len(存根) // 2

        消息 = [{'role': 'user', 'content': '任务：%s' % self.任务}]
        if 存根:
            消息.append({'role': 'assistant',
                        'content': '（前面这些步骤的结果已经被折叠了）'})
            消息.append({'role': 'user',
                        'content': '[工具结果] 前面已完成的步骤：\n%s\n'
                                   '（这些是存根，要细节就重新读文件）' % 存根})
        for 步 in self.步们[self.折到:]:
            文 = 步['助手'] or ''
            原 = 步.get('原始') or ''
            消息.append({'role': 'assistant', 'content': 原 or 文 or '（继续）'})
            if 步['结果们']:
                块 = []
                for r in 步['结果们']:
                    参 = r['参'] if isinstance(r['参'], dict) else {}
                    头 = '%s(%s)' % (r['名'], ', '.join(
                        '%s=%r' % (k, v) for k, v in list(参.items())[:4]))
                    块.append('[工具结果] %s\n%s\n[/工具结果]' % (头, r['文'] or '（空）'))
                消息.append({'role': 'user', 'content': '\n'.join(块)})
        return 消息, 系统, 小号


# ── 无进展检测 ──────────────────────────────────────────────────────

#: 无进展检测：同 `(工具, 参数)` 连着来这么多次，就当它在原地打转。
重复上限 = 3
#: 连着这么多步没有任何文件变化、命令退出码也没变，就停。
干转上限 = 4

#: 一次任务里最多"推"模型几回。见 `_像在打算盘`。
催上限 = 2

#: 模型说这种词、又没调工具 —— 多半是在**说打算**而不是在**动手**。
#:
#: 小模型（尤其 3B）特别爱这样收尾：
#:
#:     "看起来 todo.py 还没有创建。我先创建它，然后尝试添加内容。"   ← 然后就停了
#:     "看来不能作为模块导入，我直接运行它来添加内容。"              ← 也停了
#:
#: 它不是干完了，是**没动手**。而循环把"没有工具调用"当成"干完了"，
#: 于是任务在这儿结束，用户看到的是一句承诺。
#: ⚠ **标记要按"真的会出现的样子"写。** 我先写了 `'看来'`，但模型写的是
#: `'看起来'` —— `看来` 不是 `看起来` 的子串（中间夹了个"起"），白写了。
#: 所以这里同时收 `看来` / `看起来` / `看着`，别指望一个词覆盖。
空话标记 = ('我先', '接下来', '下面', '现在', '让我', '我来', '我会',
          '将要', '准备', '打算', '首先', '接着', '然后我', '下一步',
          '我直接', '我将', '看看能不能', '尝试',
          '看来', '看起来', '好像', '似乎')

#: 推它那一下说的话。**要明确让它输出 `<tool_call>`** —— 只说"请继续"
#: 小模型会继续写一段废话。
催话 = ('[系统] 你上一轮说要做什么，但没有调用任何工具，所以什么也没发生。\n'
       '要动手就直接输出 <tool_call>{"name":…,"arguments":{…}}</tool_call>，'
       '不要只说打算。\n'
       '如果确实已经做完了，就直接给出结论，不要再说"我先…"。')


def _指纹(名, 参):
    try:
        项 = sorted((str(k), str(v)) for k, v in (参 or {}).items())
    except Exception:
        项 = [('?', repr(参))]
    return (名, tuple(项))


def _像在打算盘(文, 有没有干过活):
    """
    这一轮没有工具调用 —— 是**真的干完了**，还是只**说了一句打算**？

    ⚠ 这两种情况在数据上长得一模一样（都是"没有 tool_call 的纯文本"），
    但处理方式相反：干完了要收摊，说打算要推它一把。

    判据取宽不取严：

      · **还没干过任何活**（一次工具都没调过）→ 几乎一定是说打算。
        任务刚开头就只回一段话，那不可能是干完了。
      · 文本里出现 `空话标记` 那些词 → 它在描述计划。

    宁可多推一次（代价是一次模型调用，实测约 0.5 秒），也别把一句承诺
    当成答案交出去 —— 用户看到的会是"它说要写文件，然后就结束了"。

    ⚠ **一个字都没有，也算"说打算"。** 这条是后来加的，起因是实测撞上：
    模型某一轮**正文和工具调用都是空的**（思维链把输出预算吃光了，见
    `默认设置` 那段），而"产出空"和"干完了"在数据上长得一模一样，于是循环
    收摊、界面写"干完了"。用户看到的是"让它写网页，它没写，还说完成了" ——
    比明确报错坏得多。**空回复不是答案。**
    """
    if not (文 or '').strip():
        return True
    if not 有没有干过活:
        return True
    for 词 in 空话标记:
        if 词 in (文 or ''):
            return True
    return False


def _空话(回):
    """
    模型这一轮一个字都没说时，给用户一句**能拿去查**的话。

    ⚠ **必须把"它到底回了什么"摆出来。** 光说"模型没有输出"，用户也好我们
    也好，都分不清是思维链吃光了预算、是对面把请求截了、还是模型真的哑了。
    思维链长度和停止原因是仅有的两个能分辨的证据 —— 而这两样本来是**丢掉的**
    （思维链根本不进 `正文`），所以只能一路带到这儿来。

    ⚠ `停因` 的值**三家写法不一样**（Anthropic 是 `max_tokens`/`end_turn`，
    OpenAI 系是 `length`/`stop`），所以两个都要认 —— 只认一个的话，
    正好那一家的用户看到的就是那句没用的"再试一次"。
    """
    停 = str(回.get('停因') or '')
    思 = 0
    try:
        思 = int(回.get('思维') or 0)
    except (TypeError, ValueError):
        思 = 0
    段 = ['模型这一轮什么都没写 —— 正文是空的，也没调任何工具。']
    if 思:
        段.append('它写了约 %d 字的思维链，思维链之后就没有正文了。' % 思)
    if 停:
        段.append('对面的停止原因是 %s。' % 停)
    if 停 in ('max_tokens', 'length'):
        段.append('**这就是被输出上限截断的**：思维链也算在输出里，它把额度'
                  '吃光之后，正文和工具调用就没地方写了。\n'
                  '去「设置…」把「单步输出」调大（写网页这类长东西建议 '
                  '4096 以上），或者换一个不吐思维链的模型。')
    else:
        段.append('再跑一次看看；要是每次都这样，把这一整段发出来。')
    return '\n'.join(段)


def _简短参(参):
    """参数压成一行，给"卡住了"那句话用。长的内容只留前 40 字。"""
    try:
        对 = []
        for k, v in list((参 or {}).items())[:3]:
            s = str(v).replace('\n', ' ')
            对.append('%s=%s' % (k, s[:40]))
        return '，'.join(对)
    except Exception:
        return repr(参)[:80]


