def 跑(根, 任务, 调模型, 要批=None, 事件=None, 停=None, 设=None):
    """
    跑一次任务。**除了两个回调，它不认识外面。**

    `调模型(系统, 消息们, 工具定义们, 是否原生)` → `酒馆本地.跑一轮` 那个
    `dict`。**必须把 `工具定义们` 传下去**（原生模式）或者忽略它（文本模式）。

    `要批(卡片)` → `True` 放行 / `False` 拒绝。卡片的形状见下面 `批` 那段。
    **阻塞**——助手线程会停在这儿等用户点。

    `事件(类型, 数据)` → 往界面发。类型见下面那一串。

    `停` 是带 `is_set()` 的停旗。每步开头查一次，置了就收摊。
    """
    设 = 设 or {}
    任务 = (任务 or '').strip()
    if not 任务:
        raise 助手错('任务不能是空的。')
    根 = os.path.realpath(根)
    if not os.path.isdir(根):
        raise 助手错('工作目录不存在：%s' % 根)

    最大步 = max(1, int(_定(设, '最大步数')))
    协议 = str(_定(设, '工具协议') or '自动')
    预算 = 分预算(_定(设, '上下文'), 设)
    转录本支 = 预算['转录本']
    # ⚠ **输出上限以 `分预算` 压过的那个为准，不是 `设` 里那个原始值。**
    #
    # `分预算` 会把它压进 `n_ctx // 4` —— 小上下文根本装不下 4096。而下面
    # "还装不装得下"那道硬检查，正是拿这个数去加总额的：用原始值的话，
    # `n_ctx=4096` 的本地模型会在**第一步**就被判"上下文要满了，任务停在第
    # 0 步"，而实际预算是装得下的（这正是 `单步输出` 从 1024 抬到 4096 后
    # 会撞上的事）。**两个数必须同一个来源。**
    单步出 = max(64, int(预算['输出']))

    是否原生 = (协议 == '原生')
    记 = 抄本(根, 任务, 协议=协议, 是否原生=是否原生,
             设=dict(设, 提示词预算=转录本支))

    def 发(类, 数=None):
        if 事件:
            try:
                事件(类, 数)
            except Exception:
                pass

    def 查停():
        return 停 is not None and 停.is_set()

    发('开始', {'根': 根, '最大步': 最大步, '预算': 预算})

    重复 = 0
    上指 = None
    干转 = 0
    上回状 = None
    折过 = 0
    催过 = 0

    for 第步 in range(1, 最大步 + 1):
        if 查停():
            发('完', {'停': True, '原因': '用户停了', '步': 第步 - 1})
            return {'停': True, '原因': '用户停了', '步': 第步 - 1}

        消息, 系统, 小号 = 记.消息(折了=lambda n: None)
        if 记.折到 != 折过:
            折过 = 记.折到
            发('折叠', {'折了': 折过, '共': len(记.步们)})

        # 硬上限：折叠完还超，就停。**绝不能让它继续** —— 见文件头第三条。
        # 用的是 `分预算` 给的总额，不是写死的数 —— `n_ctx` 换了这个跟着换。
        上限 = 预算['总'] - 预算['余量']
        if 小号 + 单步出 > 上限:
            发('完', {'坏': '上下文要满了（约 %d token），任务停在第 %d 步。\n'
                            '已经做完的事都记在上面了。可以新开一个任务接着做。'
                            % (小号, 第步 - 1),
                     '步': 第步 - 1})
            return {'坏': '上下文满', '步': 第步 - 1}

        发('步', {'第': 第步, '共': 最大步, 'token': 小号})

        # ── 叫模型 ──
        try:
            回 = 调模型(系统, 消息, 酒馆工具.定义们, 是否原生, 单步出)
        except Exception as 错:
            名 = type(错).__name__
            if '本地停' in 名:
                发('完', {'停': True, '原因': '用户停了', '步': 第步 - 1})
                return {'停': True, '原因': '用户停了', '步': 第步 - 1}
            发('完', {'坏': '模型这一轮出错了：%s：%s' % (名, 错), '步': 第步 - 1})
            return {'坏': str(错), '步': 第步 - 1}

        if 查停():
            发('完', {'停': True, '原因': '用户停了', '步': 第步 - 1})
            return {'停': True, '原因': '用户停了', '步': 第步 - 1}

        正文 = 回.get('正文') or ''
        调用们 = 回.get('调用们') or []
        记.记助手(正文, 回.get('原生') or '')

        # ── 没有工具调用：要么真干完了，要么只是在说打算 ──
        if not 调用们:
            if 回.get('解析失败'):
                # **原始输出必须原样交出去。** 只报"格式不合法"的话，用户
                # 看到的是模型答非所问，完全不知道是格式崩了 —— 而格式崩了
                # 恰恰是能靠改提示词/换模型解决的问题。
                原 = (回.get('原生') or '')[:2000]
                发('完', {'坏': '模型输出了工具调用但格式不合法，没法执行。\n'
                                '原始输出如下（前 2000 字）：\n\n%s' % 原,
                         '步': 第步, '原文': 原})
                return {'坏': '解析失败', '步': 第步, '原文': 原}

            干过活 = any(步['结果们'] for 步 in 记.步们)
            if 催过 < 催上限 and _像在打算盘(正文, 干过活):
                # **推它一把，别把一句承诺当答案。** 见 `_像在打算盘`。
                催过 += 1
                发('催', {'第': 第步, '次': 催过, '说': 正文[:120]})
                记.记催()
                continue

            if not (正文 or '').strip():
                # ⚠ **推过两把还是空的，就绝不能报"干完了"。** 见 `_像在打算盘`：
                # "产出空"和"干完了"在数据上长得一模一样，怎么处理却是反的。
                # 先给它机会补上（上面那次 `催`），补不上就明确报出来 ——
                # 用户看到的必须是"它一个字都没写"，不是"干完了"。
                话 = _空话(回)
                发('完', {'坏': 话, '步': 第步})
                return {'坏': '空回复', '步': 第步}

            发('完', {'答复': 正文, '步': 第步})
            return {'答复': 正文, '步': 第步}

        # ── 执行工具 ──
        for 号, 调 in enumerate(调用们, 1):
            if 查停():
                发('完', {'停': True, '原因': '用户停了', '步': 第步})
                return {'停': True, '原因': '用户停了', '步': 第步}
            名 = 调.get('名') or ''
            参 = 调.get('参数') or {}
            卡 = {'名': 名, '参数': 参, '第': 第步, '号': 号, '共': len(调用们)}

            # 不认识的工具：把"没这个工具"喂回去，**不是崩**
            if 名 not in 酒馆工具.工具名们:
                文 = ('没有 `%s` 这个工具。能用的只有：%s'
                     % (名, '、'.join(酒馆工具.工具名们)))
                记.记结果(名, 参, 文)
                发('卡', dict(卡, 态='坏', 文=文))
                continue

            # 无进展检测：**连着**同一个调用就来这么多次，说明它在原地打转，
            # 直接停任务。早先只"拒绝这一次、把话喂回去"，结果它换个说法接着
            # 来，一路跑到步数上限才停 —— 用户看着屏幕刷了二十轮一模一样的
            # 东西，还不知道为什么不停。
            指 = _指纹(名, 参)
            if 指 == 上指:
                重复 += 1
            else:
                上指, 重复 = 指, 1
            if 重复 >= 重复上限:
                发('完', {'坏': '同一个调用连着来了 %d 次（%s %s），看来是卡住了，'
                                '先停下。\n换个思路，或者把任务说得更具体一点。'
                                % (重复, 名, _简短参(参)),
                         '步': 第步})
                return {'坏': '没有进展', '步': 第步}

            # 审批
            if 酒馆工具.要审批吗(名):
                发('卡', dict(卡, 态='问'))
                try:
                    准 = 要批(卡) if 要批 else False
                except Exception:
                    准 = False
                if not 准:
                    文 = ('用户拒绝了这次操作。别原样重试——要么换个做法，'
                         '要么直接问用户想怎么办。')
                    记.记结果(名, 参, 文)
                    发('卡', dict(卡, 态='拒', 文=文))
                    continue

            # 真执行
            发('卡', dict(卡, 态='跑'))
            try:
                文 = 酒馆工具.执行(名, 根, 参, 停=停)
                记.记结果(名, 参, 文)
                发('卡', dict(卡, 态='成', 文=文))
                状 = _看变化(名, 参, 文)
                if 状 is not None:
                    干转 = 0 if 状 != 上回状 else 干转 + 1
                    上回状 = 状
            except 酒馆工具.工具错 as 错:
                文 = str(错)
                记.记结果(名, 参, 文)
                发('卡', dict(卡, 态='坏', 文=文))

        if 干转 >= 干转上限:
            发('完', {'坏': '连着 %d 步没有任何变化（文件没改、命令结果也一样），'
                            '看起来在原地打转，先停下。\n'
                            '把你想做的事说清楚一点，或者换个思路。' % 干转,
                     '步': 第步})
            return {'坏': '没有进展', '步': 第步}

    发('完', {'坏': '到了最大步数（%d 步）还没干完。\n'
                    '可以接着提一个新任务让它继续，或者把任务拆小一点。' % 最大步,
             '步': 最大步})
    return {'坏': '到步数上限', '步': 最大步}


def _看变化(名, 参, 文):
    """给"有没有进展"取一个指纹。`None` 表示这一步不参与判断（只读操作）。"""
    if 名 in ('write_file', 'edit_file'):
        return ('写', str(参.get('path')), str(文)[:80])
    if 名 == 'run_cmd':
        m = re.match(r'退出码\s+(\S+)', str(文) or '')
        return ('跑', str(参.get('cmd')), m.group(1) if m else '?')
    return None
