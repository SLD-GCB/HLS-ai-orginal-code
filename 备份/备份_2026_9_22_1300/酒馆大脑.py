def 上下文设置(设定):
    """
    会话的 `预设` → `(条数, 字数上限)`。

    ⚠ **抽出来是因为它有两个用户。** 聊天那边（`酒馆对话页._拼`）按它截，
    「上下文」那个窗口（`酒馆上下文页`）**拿它把哪几条会发出去画给用户看**。
    两处各写一份的话，界面说会发 20 条、实际发了 19 条——用户拿着界面去对，
    对不上；而这种不一致跑起来**一点症状都没有**，只能靠读代码发现。

    ⚠ **顺便把类型收干净。** `预设` 是手写 JSON，`上下文条数` 写成 `'20'`
    或者 `'abc'` 都是可能的。`从尾部截` 里要做 `总 + n > 字数上限` 这种
    比较，一个字符串进来就是 `TypeError`——而这条路上的异常会一路冒到
    "拼提示失败"，用户完全看不出是自己的预设写坏了。这儿统一成 int，
    写坏了就当没写（退回默认），和 `读JSON` 那条"坏配置不该让角色打不开"
    是一个道理。
    """
    设定 = 设定 if isinstance(设定, dict) else {}
    条数 = 默认上下文条数
    try:
        条数 = max(1, int(设定.get('上下文条数') or 条数))
    except (TypeError, ValueError):
        条数 = 默认上下文条数
    上限 = 默认字数上限
    try:
        上限 = max(1, int(设定.get('字数上限') or 上限))
    except (TypeError, ValueError):
        上限 = 默认字数上限
    return 条数, 上限


#: 聊天这条路上，`n_ctx` 里留给**生成**的份额（分母）。
#:
#: 1/4 跟 `酒馆助手.分预算` 里 `出` 的上限（`n_ctx // 4`）取同一个数 ——
#: 两处对"一步能吐多长"的看法必须一致，不然会出现"聊天发得出去、助手发不
#: 出去"（或者反过来）这种没法解释的分歧。
聊天生成分母 = 4

#: 再留这么多给 `估token` 的误差。跟 `酒馆助手.留白比例` 一个意思。
聊天留白比例 = 0.06

#: 聊天一次**最少**还留几条消息。不能丢到一条不剩 —— 全丢光等于没有上下文，
#: 模型会开始胡编。只剩一条（哪怕它自己就超了）也比空着强。
聊天最少条数 = 1


def 本机窗口(套):
    """
    这套接口**在本机**能吃下多少 token；读不到就回 `0`（= 别管它）。

    ⚠ **只有 `local` 回真值。** 云端的窗口在人家服务端，我们手上只有
    `采样参数` 里那个 `n_ctx` —— 那是我们自己填的期望，不是对面的真相。
    拿一个猜出来的数去裁用户的历史消息，等于把"猜错"变成"内容莫名其妙少了"。
    """
    if not 本地协议(套):
        return 0
    try:
        窗口 = int(套.参数().get('n_ctx') or 0)
    except (AttributeError, TypeError, ValueError):
        窗口 = 0
    return 窗口 or 酒馆本地.默认上下文


def _提示词数(系统, 数组):
    """整份提示词大概多少 token。**跟真正发出去的那一份对齐。**"""
    词 = 酒馆工具.估token(系统)
    for 条 in 数组:
        词 += 酒馆工具.估token(str(条.get('content') or ''))
    return 词


def 窗口内(角色, 会话, 候选, 设定, 套):
    """
    `候选`（已经按条数取过的那一段历史）→ **真正发得出去的那几条** + 拼好的提示。

    回 `(尾部, 系统, 数组)`。`尾部` 是消息对象（界面靠它画"哪几条没发"），
    `系统` / `数组` 就是 `拼提示` 的结果。

    ⚠ **这是聊天链路上"发哪几条"的唯一判据。** `酒馆对话页._拼` 和
    `酒馆上下文页` 都必须走它 —— 跟 `上下文设置` 那条注释是同一个道理，
    只是这次还多挂了 `n_ctx`：两处各算一遍的话，界面说会发 20 条、实际发了
    12 条，而**这种不一致跑起来一点症状都没有**。

    ⚠ **为什么非要按窗口再收一口。** `上下文设置` 的默认 `字数上限 = 24000`
    是给云端定的，本地模型有硬窗口：实测 **2.2 字一个 token**，24000 字
    ≈ **10900 token**，而本地默认 `n_ctx` 才 4096 —— **必然超**，llama.cpp
    当场抛 `Requested tokens (…) exceed context window of …`，而那句报错
    完全看不出是自己把字数上限设大了。

    ⚠ **云端一个字都不动**（`本机窗口` 回 0 就直接返回），见那个函数。

    ⚠ **做法是"丢了重拼"，不是"估算该丢几条"。** `拼提示` 会把
    `说话人='系统'` 的消息、还有"角色先开口"那一句**折进系统块** ——
    系统的实际大小依赖消息集合，所以只能丢了再拼、拼了再看。丢一条最多
    重拼一次，消息总共也就二十来条，这点开销换"算得准"完全值。
    """
    尾巴 = list(从尾部截(候选, 上下文设置(设定)[1]))
    窗口 = 本机窗口(套)
    本 = 本地协议(套)
    while True:
        系统, 数组 = 拼提示(角色, 会话, 尾巴, 设定, 本地=本)
        if 窗口 <= 0 or len(尾巴) <= 聊天最少条数:
            return 尾巴, 系统, 数组
        够吗 = (窗口 - _提示词数(系统, 数组)
              - max(256, 窗口 // 聊天生成分母)
              - int(窗口 * 聊天留白比例))
        if 够吗 >= 0:
            return 尾巴, 系统, 数组
        尾巴.pop(0)          # 从**最旧**的一端丢，绝不挖中间


def 从尾部截(消息们, 字数上限=默认字数上限):
    """
    从**最新**的往回攒，攒到超过上限为止，返回正序（老 → 新）的一段。

    只按条数封顶是不够的：一条几万字的设定楼就能把上下文顶爆，而条数上
    完全看不出来。所以条数之外再按字符数封一道。

    攒的时候**至少留一条**——消息再长也得有一条，全截没了等于没上下文。
    """
    攒, 总 = [], 0
    for m in reversed(消息们):
        n = len(m.内容 or '')
        if 攒 and 总 + n > 字数上限:
            break
        攒.append(m)
        总 += n
    return list(reversed(攒))


def 规整角色(提示):
    """
    `[{'role':..., 'content':...}]` → 三家 API 都认的合法序列。

    ⚠ **这一步不能省。** Anthropic 和 Gemini 都要求 user / assistant
    **严格交替**，且 Anthropic 要求第一条必须是 `user`。而我们的数据天然
    会违反：开场白是 `角色` 说的（首条就是 assistant），重新生成之后也会
    连着两条 assistant。**不规整就是 400，而报错信息完全不会告诉你为什么。**

    顺序是有讲究的，**不能换**：

        1. 先滤空 —— 空内容三家都不认（Anthropic 会报
           `text content blocks must be non-empty`）
        2. 再合并相邻同角色 —— **滤空必须在合并前面**。反过来的话，滤掉一条
           空串会把它两侧同角色的两条变成相邻，凭空造出一对违规
        3. 最后补首条 —— 首条不是 user 就在前面插一条 `开场占位`

    第 3 步是**插一条，不是删原来的**。删掉的话开场白就没了，模型不知道自己
    已经说过那句话。插一条占位 user 让它退到第二句，信息一点不丢。
    """
    压 = []
    for m in 提示:
        角色 = m.get('role')
        if 角色 not in ('user', 'assistant'):
            continue
        文 = (m.get('content') or '').strip()
        if not 文:
            continue                       # ① 滤空
        if 压 and 压[-1]['role'] == 角色:
            压[-1]['content'] += '\n\n' + 文    # ② 合并相邻同角色
        else:
            压.append({'role': 角色, 'content': 文})

    if not 压:
        # 历史里一条能用的都没有（比如新会话、开场白也是空的）。
        # 给一条占位，让模型有话说——比发一个空数组出去换一个 400 强。
        return [{'role': 'user', 'content': 开场占位}]
    if 压[0]['role'] != 'user':
        压.insert(0, {'role': 'user', 'content': 开场占位})   # ③ 补首条
    return 压


#: 本地小模型的扮演规矩。`%s` 是角色名。
#:
#: ⚠ **故意不用 markdown 加粗。** `**` 对模型是纯噪音——实测过，小模型会
#: 把它当成"要输出的格式"，或者干脆吞掉。
#:
#: ⚠ **故意不提"本地""模型"这些词。** 第 3 条正在禁止它自称 AI，前文再提
#: 一句"本地模型"等于自相矛盾、勾着它往那条路上跑。
#:
#: 旁白两种写法都认（全角圆括号 + 星号），**不在提示里强行统一**——用户
#: 怎么写都行，模型看多了自己会跟。
本地规矩 = (
    '扮演规则（必须一直遵守）：\n'
    '1. 始终以%s的身份和口吻说话，不要跳出角色。\n'
    '2. 不要替用户写他说的话，也不要替用户做决定、描写用户的行为。\n'
    '3. 不要自称 AI、语言模型、助手或程序。\n'
    '4. 动作、神态、场景这类旁白，用圆括号包起来，比如（她转过头）'
    '或 *她转过头*；说的话直接写。\n'
    '5. 按角色的性格和当前情景来回应，别写客套话，也别总结或复述前文。\n'
    '6. 一次回复别太长，几句话把意思说到就行。'
)


def 本地协议(套):
    """
    这套接口配置是不是走本地 GGUF。`None`（一套都没配）当成不是。

    ⚠ **抽出来是因为它有两个调用方**（`酒馆对话页`、`酒馆上下文页`）。
    两处各写一遍 `套 is not None and 套.协议 == 'local'` 的话，迟早有一处
    漏掉 `None` 判断——`酒馆接口.取或默认()` 在一套接口都没建的时候回的就是
    `None`，漏了当场 AttributeError，而且报错点离这个判断隔着好几层。
    """
    return 套 is not None and (套.协议 or '') == 'local'


def 拼提示(角色, 会话, 消息们, 设定=None, 本地=False):
    """
    角色卡 + 会话设定 + 最近的消息 → `(系统提示, 消息数组)`。

    回来的消息数组**已经规整过**，四个协议直接能用。

    `说话人='系统'` 的消息**折进系统提示**，不当成 message —— 三家 HTTP
    协议里只有 OpenAI 有 `system` 这个 role，另外两家会把一条 role 叫
    "system" 的消息当成非法输入。

    `本地=True`（这套接口的协议是 `local`）时才在**系统提示最末尾**补一段
    扮演规则，见 `本地规矩`。云端那几家自带较强的人格保持，不掺这一脚。

    ══ 系统块的前后顺序，以及为什么这么排 ══════════════════════════════

        ① 身份     「你就是<名字>。」「角色简介：…」  ← 先立人格，名字永远在
        ② 人设     性格、说话方式                    ← 人格主体
        ③ 示例对话 带「这是谁说的」的抬头             ← 风格示范
        ④ 系统消息 `说话人='系统'` 折进来的            ← 位置原样不动
        ⑤ 会话系统提示 `设定['系统提示']`              ← 位置原样不动
        ⑤′ 长期记忆 `设定['__记忆__']`                ← 见下面那条注释
        ⑥ 开场白说明 「你已经说过这句：…」
        ⑦ 扮演规则（**仅 local**）                    ← 压在整个提示的最末尾

    ①②③ 是「这个角色是谁」，放最前，让模型先建立人格再谈别的。

    ④⑤ 是用户自己写的东西，**位置一个字都不挪**：`酒馆上下文页` 那个
    label 的承诺就是"拼在角色设定后面"（见那边的文案），挪了就改了用户
    原来的意思。

    ⑤′ 长期记忆夹在 ⑤ 和 ⑥ 之间：往前挪就跑到用户设定前面去了，往后挪
    会把 ⑦ 挤走（见 ⑦ 那条）。

    ⑥ 紧贴生成前重申"你已经说过这句"，防模型把开场白再复述一遍。

    ⑦ 放**整个系统提示的最末尾**：小模型对**末尾**指令的服从度最高
    （recency），把最容易翻车的几条（替用户说话 / 自称 AI / 没旁白）
    压到最后，命中率最好。

    ⚠ ⑥ 和 ⑦ 不打架：⑥ 说的是**事实**（你已说过这句，而且它是角色真实
    说过的话），⑦ 说的是**行为约束**（怎么说话）。⑦ 里"不要照抄"针对的
    是 ③ 那批**示例**，开场白不属于示例。

    ⚠ **①②的修复对云端协议也生效，是有意的。** 老代码是
    `if 人设: … elif 简介: …`——人设一非空，名字和简介双双消失，用户喊
    「乌玛」模型根本不知道那是谁。这是 bug，不是"只给本地做的风格偏好"。
    """
    # ⚠ **不能写 `设定 = 设定 or {}`。** 那样传进来一个**空 dict** 会被换成
    # 一个新的空 dict，下面塞 `__要点__` 就塞进了副本、调用方那份永远是空的。
    # （`__记忆__` 没暴露过这个坑，是因为它进来时**非空** —— 里面有 `__记忆__`。）
    # 这儿只把 `None` 兜成空 dict，**保住调用方那份的身份**。
    if 设定 is None:
        设定 = {}
    系统块 = []
    名字 = (角色.名字 or '').strip() if 角色 is not None else ''

    # ── **填卡**：外层角色设计那一半（`{{char}}` / `{{user}}` 这类占位符）──
    #
    # ⚠ **只作用于"作者写的设定文本"** —— 角色卡的简介 / 人设 / 示例对话，
    # 以及会话的系统提示、`说话人='系统'` 的消息。
    # **绝不碰历史消息**：角色说过的话里出现 `{{...}}` 是正常的（他在讲代码、
    # 讲模板），改历史等于篡改他说过的话。
    #
    # ⚠ `填卡` **认不出的占位符原样留着** —— 用户写错一个（`{{chra}}`）能当场
    # 看见并改，不会静默消失。`{{场景}}` 在角色卡里没有对应列，所以也留着
    # （要喂得走 `填卡` 的 `额外=` 参数，现在还没有调用方喂它）。
    #
    # 称呼从 `设定['用户称呼']` 取，缺省 `'你'` —— 中文角色扮演里角色就是
    # 这么称呼玩家的；这个 app **没有"用户名"这个字段**，硬加一个不如先给个
    # 合理的默认，用户不满意再在会话预设里写一个。
    称呼 = (设定.get('用户称呼') or '你').strip() or '你'
    填 = lambda t: 酒馆协议.填卡(t, 角色, 称呼)      # noqa: E731

    if 角色 is not None:
        简介 = 填((角色.简介 or '').strip())
        人设 = 填((角色.人设 or '').strip())

        # ① 身份：名字永远在，简介不再被"人设非空"挤掉。
        身份 = ['你就是%s。' % 名字 if 名字 else '你正在扮演一个角色。']
        if 简介:
            身份.append('角色简介：%s' % 简介)
        系统块.append('\n'.join(身份))

        # ② 人设：紧跟在身份后面，是人格主体。
        if 人设:
            系统块.append(人设)

        # ③ 示例对话：抬头里点明"这些是谁说的"。老版本只丢一句原样示例
        # 加一段 `**…**` 元指令，小模型既不知道谁说的、又容易被那层加粗
        # 绕晕或者直接照抄。
        示例 = 填((角色.示例对话 or '').strip())
        if 示例:
            系统块.append(
                '以下是「%s」的说话示例（只用来体会语气和用词，'
                '不要照抄，也别当成已经发生过的对话）：\n%s'
                % (名字 or '这个角色', 示例))

    # ④ `说话人='系统'` 的消息折进系统提示。按序号顺序排，保持时间感。
    # ⚠ 这些也是**作者写的**（不是角色说过的），所以照样过 `填卡`。
    临时 = []
    普通 = []
    for m in 消息们:
        if (m.说话人 or '') == '系统':
            文 = 填((m.内容 or '').strip())
            if 文:
                临时.append(文)
        else:
            普通.append(m)
    系统块.extend(临时)

    # ⑤ 会话级系统提示：用户自己写的，位置保持在角色设定后面。
    额外 = 填((设定.get('系统提示') or '').strip())
    if 额外:
        系统块.append(额外)

    # ⑤′ 长期记忆：**排在用户自己写的会话系统提示后面、开场白说明前面**。
    #
    # ⚠ **位置是定死的，两个方向都不能挪**：
    #   · 往前挪 = 插在用户的设定前面，那两条的先后语义就变了；
    #   · 挪到最末尾 = 把 ⑦`本地规矩` 挤走，而那条是靠"离生成最近"起作用的
    #     （见 docstring 里 ⑦ 的说明），挤走它模型会不听扮演规矩。
    #
    # ⚠ **它是"这一轮的瞬时数据"，由调用方算好之后塞进 `设定` 的保留键。**
    # 为什么不走函数参数：`拼提示` 在这条链上有三个调用点（`窗口内` 内部、
    # `酒馆对话页._摆气泡` 真正发出去的那份、`酒馆上下文页` 的预览），
    # 而 `设定` **是唯一能同时到达这三处的同一个对象**。参数化的话，
    # 漏掉任意一处就是两种坏法：漏 `_摆气泡` = 记忆根本没发出去；
    # 漏 `窗口内` = 裁 token 时不知道记忆占了多少，提示词越过 n_ctx、
    # llama.cpp 从最前面截断（**先丢的是系统提示**，界面上毫无症状）。
    #
    # ⚠ **这条键绝不能落盘。** 它是 `设定`（= 会话的 `预设` JSON）上的一个
    # 临时键，谁要是把手上这份 `设定` 直接 `改会话(预设=…)` 写回去，
    # 记忆就会被永久写进预设。目前的写回路径（`酒馆上下文页._保存`）是
    # "当场重读 → 只改三个键 → 写回"，不碰它 —— 改那边的时候记着这条。
    记忆 = (设定.get('__记忆__') or '').strip()
    if 记忆:
        系统块.append(记忆)

    提示 = [{'role': 'user' if m.说话人 == '用户' else 'assistant',
             'content': m.内容 or ''}
            for m in 普通 if m.说话人 in ('用户', '角色')]

    # ⑥ 首条是 assistant 的话，把它挪进系统提示里说明"你已经说过这句"，
    # 再从消息数组里去掉 —— 这样补占位那条 user 就不是凭空多出来的。
    # （`规整角色` 也能处理，但那样子系统提示里就没有角色自己说过的话。）
    if 提示 and 提示[0]['role'] == 'assistant':
        头 = 提示.pop(0)['content'].strip()
        if 头:
            系统块.append('对话是由你先开口的。你已经说过这句：\n' + 头)

    # ⑦ 本地扮演规矩：压在整个系统提示的最末尾，见 docstring。
    # ⚠ 角色卡不在了（`角色 is None`）也照样加：卡片可能被删，但历史里
    # 还有角色说过的话，本地模型不拴着就会突然变回"通用助手"。
    if 本地:
        系统块.append(本地规矩 % (名字 or '你扮演的角色'))

    # ⑧ **人格要点**：给 `酒馆协议.锁人格` 用的一两句角色核心。
    #
    # ⚠ 它跟 `__记忆__` 是**同一个路子**：本轮瞬时数据，塞进 `设定` 的保留键，
    # 因为 `设定` 是**唯一能同时到达三处**（`窗口内` 内部、`对话页._摆气泡`
    # 真正发出去那份、`上下文页` 预览）的同一个对象。参数化的话漏一处就是
    # "预览说会加、实际没加"这种查不出来的不一致。
    #
    # ⚠ **这条键绝不能落盘**（同 `__记忆__` 那条）。
    #
    # ⚠ **算出来 ≠ 会用。** `酒馆协议.取控制` 里默认是**关**的 ——
    # 要不要真的复述，得用户在会话设定里写 `人格锁='开'`。这是因为
    # 改提示词会影响**所有**模型，而收益只在部分模型上（见那边的注释）。
    要点 = ''
    if 名字:
        # ⚠ 这里**必须走 `填`**，不能直接读 `角色.简介` —— 简介里可能写着
        # `{{user}}`，不复述原样的话，要点里会带着一对**没人认得的占位符**
        # 发给模型。（实测撞到过。）
        简 = (填((角色.简介 or '').strip()) if 角色 is not None else '')
        要点 = (('你是%s。%s' % (名字, 简)).strip() if 简 else ('你是%s。' % 名字))[:120]
    设定['__要点__'] = 要点

    return '\n\n'.join(系统块), 规整角色(提示)


