def 跑(根, 任务, 调模型, 要批=None, 事件=None, 停=None, 设=None, 交出=None):
    """
    跑一次任务。**除了两个回调，它不认识外面。**

    `调模型(系统, 消息们, 单步出, 强制=False, 工具名='', 参数名='')` →
    `酒馆本地.跑一轮` 那个 `dict`。

    `强制=True` 表示**这一轮不给它"只答不做"这个选项**：引擎会在提示词末尾
    替它把工具调用**开了个头**（`本地agent协议.预填串`），它只能接着往下写，
    没有别的路。什么时候用见 `该收尾吗` —— 判据是"**还没干完**"，
    不是"模型看起来像在偷懒"。

    `工具名` / `参数名` 是**骨架**（`骨架(记)`）给的，会把预填再拨深一档：
    连"调哪个工具、用哪个参数名"都由我们写死，模型只剩一个格子填值。

    `要批(卡片)` → `True` 放行 / `False` 拒绝。卡片的形状见下面 `批` 那段。
    **阻塞**——助手线程会停在这儿等用户点。

    `事件(类型, 数据)` → 往界面发。类型见下面那一串。

    `停` 是带 `is_set()` 的停旗。每步开头查一次，置了就收摊。

    `交出(记)` → **抄本一建好就叫一次**，把 `抄本` 对象交出去。外面拿它
    落盘 / 摊开给人看（见 `酒馆助手存`）。回调里抛异常会被吞掉——它只是
    个旁路，**绝不能让它把任务带崩**。
    """
    设 = 设 or {}
    任务 = (任务 or '').strip()
    if not 任务:
        raise 助手错('任务不能是空的。')
    根 = os.path.realpath(根)
    if not os.path.isdir(根):
        raise 助手错('工作目录不存在：%s' % 根)

    最大步 = max(1, int(_定(设, '最大步数')))
    预算 = 分预算(_定(设, '上下文'), 设)
    转录本支 = 预算['转录本']
    # ⚠ **输出上限以 `分预算` 压过的那个为准，不是 `设` 里那个原始值。**
    #
    # `分预算` 会把它压进 `n_ctx // 4` —— 小上下文根本装不下 4096。而下面
    # "还装不装得下"那道硬检查，正是拿这个数去加总额的：用原始值的话，
    # `n_ctx=4096` 的本地模型会在**第一步**就被判"上下文要满了，任务停在第
    # 0 步"，而实际预算是装得下的（这正是 `单步输出` 从 1024 抬到 4096 后
    # 会撞上的事）。**两个数必须同一个来源。**
    单步出 = max(64, int(预算['输出']))
    记 = 抄本(根, 任务, 设=dict(设, 提示词预算=转录本支))

    # ⚠ **抄本一建好就交出去，不给下面那十几个 `return` 挂钩子。**
    #
    # 这个函数出口很多（正常答复 / 解析失败 / 空回复 / 没有进展 / 上下文满
    # / 到步数上限 / 用户停了 / 模型报错），每个都要"把转录带出去"的话，
    # 就是十几处改动，而且**将来新增一个出口就漏一处** —— 漏掉的那条路上
    # 用户看到的是"这次任务没记录"，而没有任何症状说明为什么。
    #
    # 改成把对象提前交出去之后，外面只要跑完（正常返回、`raise`、将来任何
    # 新的出口）再读它就行，**一处都不用挂**。
    if 交出:
        try:
            交出(记)
        except Exception:
            pass

    def 发(类, 数=None):
        if 事件:
            try:
                事件(类, 数)
            except Exception:
                pass

    def 查停():
        return 停 is not None and 停.is_set()

    发('开始', {'根': 根, '最大步': 最大步, '预算': 预算})

    重复 = 0
    上指 = None
    干转 = 0
    上回状 = None
    折过 = 0
    强制过 = 0
    解析催过 = 0
    #: 这一轮要不要**强制**（预填逼它动手）。用完立刻清 —— 见下面那句。
    强制 = False
    #: 强制轮里**骨架指定的**工具名 / 参数名（`骨架(记)` 给的）。
    #: 空 = 骨架不管这一步，预填停在老深度、工具名让模型自己填。
    强制工具, 强制参数 = '', ''

    for 第步 in range(1, 最大步 + 1):
        if 查停():
            发('完', {'停': True, '原因': '用户停了', '步': 第步 - 1})
            return {'停': True, '原因': '用户停了', '步': 第步 - 1}

        消息, 系统, 小号 = 记.消息(折了=lambda n: None)
        if 记.折到 != 折过:
            折过 = 记.折到
            发('折叠', {'折了': 折过, '共': len(记.步们)})

        # 硬上限。用的是 `分预算` 给的总额，不是写死的数 —— `n_ctx` 换了跟着换。
        #
        # ⚠ **但绝不能"一撞上就停任务"。** 早先就是那样：折叠默认只折到
        # `保留步数`（6）为止，装不下就当场收摊，用户看到的是"任务莫名其妙
        # 停了"—— 而其实再折几刀就能装下。所以撞上之后**先拼命折**：
        上限 = 预算['总'] - 预算['余量']
        if 小号 + 单步出 > 上限:
            # `保留步数` 是"舒服"的档位，不是硬约束。压到 0 = **每一步都折成
            # 存根**，提示词只剩「任务 + 系统提示 + 存根块」，那几乎一定装得下。
            #
            # 代价是模型看不到最近几步的细节了（只看到"我用 write_file 写过
            # countdown.html"这种一行存根）。但**存根里保留着工具名和参数**，
            # 要细节它自己 read_file 就回来了 —— 比"停在这儿"强得多。
            消息, 系统, 小号 = 记.消息(折了=lambda n: None, 保留=0)
            if 记.折到 != 折过:
                折过 = 记.折到
                发('折叠', {'折了': 折过, '共': len(记.步们)})

        if 小号 + 单步出 > 上限:
            # 折到只剩存根还装不下 —— 那是**窗口本身太小**，不是策略问题
            # （这时候提示词里只剩任务 + 系统提示 + 一堆一行存根）。
            发('完', {'坏': '上下文装不下，任务停在第 %d 步。\n'
                            '能折的**都折了**（每一步都只剩一行存根），还是塞不进'
                            '这个窗口 —— 剩的全是任务原文和系统提示，'
                            '那两样不能丢。\n\n'
                            '去「接口配置」把这套的 `n_ctx` 调大（现在只有 %d，'
                            '8G 显存建议 8192 起）。写整个文件时**一次调用的原文'
                            '就能占掉两千多 token**，4096 的窗口装不下一个网页。'
                            % (第步 - 1, 预算['总']),
                     '步': 第步 - 1})
            return {'坏': '上下文满', '步': 第步 - 1}

        发('步', {'第': 第步, '共': 最大步, 'token': 小号, '强制': bool(强制)})

        # ── 把这一轮真正要发的东西冻下来 ──
        #
        # ⚠ **位置只有一个正确解：`调模型` 之前、`try` 外面。**
        #   · 放 `try` 里面 → 模型抛异常那条路没冻上，而那次请求**是发出去了**
        #     （网络已经动了），记录里却像"什么都没发生"。
        #   · 放到事后（调 `记.消息()` 重算）→ 会二次折叠、二次改 `折到`；
        #     更要紧的是撞上硬上限那条路调过 `消息(保留=0)` 却**没调模型**，
        #     重算出来的是"没发出去的那一份"。
        #
        # `折到/共步` 一并冻在这里，是因为**传输本末尾那个 `折到` 会撒谎**
        # （上面那条）。外面标"哪几步被折了"必须用冻的这一份。
        #
        # ⚠ **`串` / `路` / `预填` / `画像` 不在这儿冻** —— 它们是"渲染完之后"
        # 才知道的东西，而渲染发生在 `调模型` 里面。所以调完由 `_补快照` 填回来。
        #
        # ⚠ 冻的这几个（尤其 `折到` / `共步`）**绝不能被那一下改掉** ——
        # "冻"这个动作存在的全部理由就是它们。
        记.最近发出 = {
            '系统': 系统, '消息': 消息, '小号': int(小号),
            '第': 第步, '共步': len(记.步们), '折到': int(记.折到),
            '强制': bool(强制),
        }

        # ── 叫模型 ──
        try:
            回 = 调模型(系统, 消息, 单步出, 强制=强制,
                      工具名=强制工具, 参数名=强制参数)
        except Exception as 错:
            名 = type(错).__name__
            if '本地停' in 名:
                发('完', {'停': True, '原因': '用户停了', '步': 第步 - 1})
                return {'停': True, '原因': '用户停了', '步': 第步 - 1}
            发('完', {'坏': '模型这一轮出错了：%s：%s' % (名, 错), '步': 第步 - 1})
            return {'坏': str(错), '步': 第步 - 1}

        # ⚠ **强制只管这一轮，用完立刻清。** 不清的话它会一直强制下去，
        # 而预填**取消了"给最终答复"这个可能** —— 模型会永远调工具、永远
        # 收不了尾。（要再强制，得由下面 `该收尾吗` 那一路重新置上。）
        强制 = False
        强制工具, 强制参数 = '', ''

        if 查停():
            发('完', {'停': True, '原因': '用户停了', '步': 第步 - 1})
            return {'停': True, '原因': '用户停了', '步': 第步 - 1}

        正文 = 回.get('正文') or ''
        调用们 = 回.get('调用们') or []
        记.记助手(正文, 回.get('原生') or '')
        _补快照(记, 回)

        # ── 没有工具调用：该收尾了吗 ──
        if not 调用们:
            if 回.get('解析失败'):
                # ⚠ **先重问，别一撞上就中止整个任务。** 实测的崩法都是
                # "重写一遍就能好"的，而原来的代码当场收摊 —— 明明只差一次
                # 重问。喂回去的话见 `_解析催话`，里面带着原文和三条具体改法。
                if 解析催过 < 解析催上限:
                    解析催过 += 1
                    发('解析催', {'第': 第步, '次': 解析催过})
                    记.记结果('（系统）', {}, _解析催话(回))
                    continue

                # 重试用尽。**原始输出必须原样交出去** —— 只报"格式不合法"的话，
                # 用户看到的是模型答非所问，完全不知道是格式崩了；而格式崩了
                # 恰恰是能靠改提示词 / 换模型 / 调「单步输出」解决的问题。
                原 = (回.get('原生') or '')[:2000]
                发('完', {'坏': '模型输出了工具调用，但格式一直不合法 —— '
                                '重问了 %d 次还是没修好，先停下。\n'
                                '原始输出如下（前 2000 字）：\n\n%s'
                                % (解析催上限, 原),
                         '步': 第步, '原文': 原})
                return {'坏': '解析失败', '步': 第步, '原文': 原}

            行不行, 为啥 = 该收尾吗(回, 记)
            if not 行不行:
                if 强制过 < 强制上限:
                    # **推它一把 —— 这次是硬的，它没有拒绝的余地。**
                    #
                    # ⚠ 从前这一下是"喂一句话让它继续"（`催话`，软的），小模型
                    # 想不听就不听；现在是引擎替它把工具调用**开了个头**
                    # （`本地agent协议.预填串`），它只能接着往下写。
                    # 判据也从一张空话词表换成了 `该收尾吗` 那三条客观条件。
                    #
                    # ⚠ **工具名由骨架给**（`骨架(记)`），不由模型挑 ——
                    # "动手做什么"这一格也收回来。骨架盖不住的状态它回空，
                    # 那时候才让它自己决定。
                    强制过 += 1
                    强制 = True
                    强制工具, 强制参数, 骨为啥 = 骨架(记)
                    发('催', {'第': 第步, '次': 强制过,
                              '说': 骨为啥 or 为啥, '工具': 强制工具})
                    continue

                # 推了 `强制上限` 次还是不动手 —— 收摊，但**要说清卡在哪一条**。
                # 光说"没有进展"，用户没法判断该换模型还是改任务。
                发('完', {'坏': '推了 %d 次它还是不动手（%s），先停下。\n\n'
                                '多半是这个模型压不住这套协议 —— 换一个再试；'
                                '或者把任务说得更具体一点，让它没得猜。'
                                % (强制上限, 为啥),
                         '步': 第步})
                return {'坏': '没有进展', '步': 第步}

            if not (正文 or '').strip():
                # ⚠ **判据说"可以收尾"，可它一个字都没写 —— 那是空回复，
                # 不是答案。** "产出空"和"干完了"在数据上长得一模一样，
                # 怎么处理却是反的：用户看到的必须是"它一个字都没写"，
                # 不是"干完了"。
                话 = _空话(回)
                发('完', {'坏': 话, '步': 第步})
                return {'坏': '空回复', '步': 第步}

            发('完', {'答复': 正文, '步': 第步})
            return {'答复': 正文, '步': 第步}

        # ── 执行工具 ──
        for 号, 调 in enumerate(调用们, 1):
            if 查停():
                发('完', {'停': True, '原因': '用户停了', '步': 第步})
                return {'停': True, '原因': '用户停了', '步': 第步}
            名 = 调.get('名') or ''
            参 = 调.get('参数') or {}
            卡 = {'名': 名, '参数': 参, '第': 第步, '号': 号, '共': len(调用们)}

            # 不认识的工具：把"没这个工具"喂回去，**不是崩**
            if 名 not in 酒馆工具.工具名们:
                文 = ('没有 `%s` 这个工具。能用的只有：%s'
                     % (名, '、'.join(酒馆工具.工具名们)))
                记.记结果(名, 参, 文)
                发('卡', dict(卡, 态='坏', 文=文))
                continue

            # 无进展检测：**连着**同一个调用就来这么多次，说明它在原地打转，
            # 直接停任务。早先只"拒绝这一次、把话喂回去"，结果它换个说法接着
            # 来，一路跑到步数上限才停 —— 用户看着屏幕刷了二十轮一模一样的
            # 东西，还不知道为什么不停。
            指 = _指纹(名, 参)
            if 指 == 上指:
                重复 += 1
            else:
                上指, 重复 = 指, 1
            if 重复 >= 重复上限:
                发('完', {'坏': '同一个调用连着来了 %d 次（%s %s），看来是卡住了，'
                                '先停下。\n换个思路，或者把任务说得更具体一点。'
                                % (重复, 名, _简短参(参)),
                         '步': 第步})
                return {'坏': '没有进展', '步': 第步}

            # 审批
            if 酒馆工具.要审批吗(名):
                发('卡', dict(卡, 态='问'))
                try:
                    准 = 要批(卡) if 要批 else False
                except Exception:
                    准 = False
                if not 准:
                    文 = ('用户拒绝了这次操作。别原样重试——要么换个做法，'
                         '要么直接问用户想怎么办。')
                    记.记结果(名, 参, 文)
                    发('卡', dict(卡, 态='拒', 文=文))
                    continue

            # 真执行
            发('卡', dict(卡, 态='跑'))
            try:
                文 = 酒馆工具.执行(名, 根, 参, 停=停)
                记.记结果(名, 参, 文)
                发('卡', dict(卡, 态='成', 文=文))
                状 = _看变化(名, 参, 文)
                if 状 is not None:
                    干转 = 0 if 状 != 上回状 else 干转 + 1
                    上回状 = 状
            except 酒馆工具.工具错 as 错:
                文 = str(错)
                记.记结果(名, 参, 文)
                发('卡', dict(卡, 态='坏', 文=文))

        if 干转 >= 干转上限:
            发('完', {'坏': '连着 %d 步没有任何变化（文件没改、命令结果也一样），'
                            '看起来在原地打转，先停下。\n'
                            '把你想做的事说清楚一点，或者换个思路。' % 干转,
                     '步': 第步})
            return {'坏': '没有进展', '步': 第步}

    发('完', {'坏': '到了最大步数（%d 步）还没干完。\n'
                    '可以接着提一个新任务让它继续，或者把任务拆小一点。' % 最大步,
             '步': 最大步})
    return {'坏': '到步数上限', '步': 最大步}


def _首参(工具名):
    """
    这个工具**声明的第一个参数名**。骨架靠它决定预填拨到哪一格。

    ⚠ **从 `酒馆工具.定义们` 读，不写死。** 写死的话，以后调换参数顺序
    就会出现"预填进去了一个不是我们想让它填的参数" —— 而那**不报错**，
    只是模型被引到了另一格。
    """
    for 工 in 酒馆工具.定义们:
        函 = 工['function']
        if 函['name'] == 工具名:
            键们 = list(函['parameters'].get('properties') or {})
            return 键们[0] if 键们 else ''
    return ''


def 骨架(记):
    """
    这一步**该干什么** —— 由**转录本的状态**决定，**跟模型是谁无关**。

    回 `(工具名, 参数名, 为什么)`。工具名为空 = "这一步不给它定，让它自己决定"。

    ⚠⚠ **它是"决定权"那一半。** 提示词、预填、grammar 合起来管的是
    "**你只能用合法的方式动手**"；骨架管的是"**动手做什么**"。
    没有它，模型（尤其弱的）会在合法范围内选错 —— 实测 R1 挂上 grammar 之后
    形状完全合法，但**该 `list_dir` 它选了 `search`**。

    ⚠ **只认两种状态，都是有客观证据的**：

      ① **还没成功执行过任何工具** → 先看工作目录。
         这是"开局应该先看有什么"这个**领域事实**，跟它是谁没关系；
         系统提示第 9 条本来就写着"说不清楚的时候先 list_dir 看目录"，
         这里只是**逼它照做**。
      ② **刚改过文件、之后没成功跑过命令** → 跑一遍验证。
         同样是系统提示第 7 条的原话："写完东西要自己跑一遍验证"。

    其余状态一律**放手**（回空）—— 开放式任务没法脚本化，
    **骨架盖不住的地方必须让它自己走**，否则 agent 就退化成脚本了。

    ⚠ **它只在强制轮生效。** 自由轮一个字不动 —— 强模型第一轮就做对的事，
    骨架不该插一脚。这也是"骨架为默认、自由为兜底"的落法。

    ⚠ ② 有代价：写文档（.md / .txt）这类**本来就不需要跑命令**的任务，
    也会被逼着跑一条。收益是"改完必须验证"这条规矩对代码任务真的生效，
    代价是一次多余的命令 + 一轮。**能接受，但得知道。**

    `参数名` 取的是这个工具**声明的第一个参数**（`_首参`），
    所以它也是从工具定义来的，不是我们拍脑袋写的。
    """
    # ① 开局：一次工具都没成功执行过
    if not any(步['结果们'] for 步 in 记.步们):
        return 'list_dir', _首参('list_dir'), '还没看过工作目录里有什么'

    # ② 刚改过文件、还没验过
    改过, 验过 = False, False
    for 步 in 记.步们:
        for r in (步['结果们'] or []):
            if r['名'] in ('write_file', 'edit_file'):
                改过, 验过 = True, False
            elif r['名'] == 'run_cmd' and _退出码(r['文']) == 0:
                验过 = True
    if 改过 and not 验过:
        return 'run_cmd', _首参('run_cmd'), '刚改过文件，该跑一遍验证'

    return '', '', ''


def 自检(根, 调模型, 设=None):
    """
    开跑之前先问一句：**这个模型在这套协议下到底能不能干活。** 回 `(行不行, 为什么)`。

    ⚠⚠ **这是"第三态"。** 协议层能解决"形状"（grammar）和"服从"（预填），
    **解决不了"它填不出能用的值"** —— 实测 R1 挂上 grammar 之后形状完全合法，
    但它调 `search` 只给 `pattern`，没有 `path`，工具照样报错。
    **那种不是协议能修的，只能判出来。**

    ⚠ **判据是"真跑一次、真执行一次"，不是查名字、不是查模板。**
    这个项目在"字符串判据"上栽过三次（`tool_call` vs `tools`、
    `item['tools']`、还有各种清单），不再来第四次。
    做法：把工具名和参数名都用骨架和预填锁死（`list_dir` + `path`），
    **只留一个值给它填**，然后**真拿这个值去执行一次** ——
    执行过了就是过了，报错就是没过。**零解释空间。**

    ⚠ 探针**只碰只读工具**（`list_dir`），而且就一条，所以没有副作用。

    ⚠ **误判方向是"严"**：偶尔一次手滑的模型会被判掉。
    所以留了逃生口（`设['跳过自检']`）—— 判错了用户能绕过，
    而不是被一个自动判定挡在门外。
    """
    系 = 系统提示(根, 记忆=(设 or {}).get('记忆'))
    甲 = [{'role': 'user', 'content': '任务：看看当前目录下有哪些文件。'}]
    try:
        回 = 调模型(系, 甲, 256, 强制=True, 工具名='list_dir', 参数名='path')
    except Exception as 错:
        return False, ('自检这一轮模型就出错了：%s：%s\n'
                      '（这跟任务本身无关，是这套配置发不出去。）'
                      % (type(错).__name__, 错))
    调用们 = 回.get('调用们') or []
    if not 调用们:
        return False, ('自检只让它做一件事 —— 列出工作目录里的文件。'
                      '它**一条工具调用都没产出**。\n'
                      '（停止原因 %s，思维链约 %s 字）'
                      % (回.get('停因') or '未知', 回.get('思维') or 0))
    调 = 调用们[0]
    参 = 调.get('参数') or {}
    if not str(参.get('path') or '').strip():
        return False, ('自检只让它做一件事 —— 列出工作目录里的文件。'
                      '它调了 `%s`，但**没给路径**：%r' % (调.get('名'), 参))
    try:
        酒馆工具.执行(调.get('名') or '', 根, 参)
    except 酒馆工具.工具错 as 错:
        return False, ('自检只让它做一件事 —— 列出工作目录里的文件。'
                      '它调了 `%s`，参数 %r，工具报错：\n%s'
                      % (调.get('名'), 参, 错))
    except Exception as 错:
        return False, '自检执行工具时出了预料外的错：%s：%s' % (type(错).__name__, 错)
    return True, ''


def _补快照(记, 回):
    """
    把**真发出去的那一串**补进快照。

    ⚠ **位置只有一个正确解：`调模型` 返回之后立刻。** 快照本身是**调模型之前**
    冻的（那是为了给界面"这次发了什么"），可 `串` / `路` / `预填` / `画像`
    这几样**只有引擎渲染完才知道** —— 渲染就在 `调模型` 里面。所以只能调完
    往回填。

    ⚠ **它只许"补"，不许"改"。** `折到` / `共步` / 第几步那几个键是快照存在
    的全部理由（转录本末尾那个 `折到` 会撒谎，见 `跑` 里那段注释），
    这里一个字都不碰。
    """
    if not isinstance(getattr(记, '最近发出', None), dict):
        return
    记.最近发出.update({
        '串': 回.get('串') or '',
        '路': 回.get('路') or '',
        '预填': 回.get('预填') or '',
        '画像': 回.get('画像') or {},
        '禁生效': bool(回.get('禁生效')),
    })


def _看变化(名, 参, 文):
    """给"有没有进展"取一个指纹。`None` 表示这一步不参与判断（只读操作）。"""
    if 名 in ('write_file', 'edit_file'):
        return ('写', str(参.get('path')), str(文)[:80])
    if 名 == 'run_cmd':
        码 = _退出码(文)
        return ('跑', str(参.get('cmd')), '?' if 码 is None else str(码))
    return None
