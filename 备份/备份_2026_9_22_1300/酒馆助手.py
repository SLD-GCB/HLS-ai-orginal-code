#: 无进展检测：同 `(工具, 参数)` 连着来这么多次，就当它在原地打转。
重复上限 = 3
#: 连着这么多步没有任何文件变化、命令退出码也没变，就停。
干转上限 = 4

#: 一次任务里最多**强制**模型几回（用预填逼它动手）。见 `该收尾吗`。
#:
#: ⚠ 定 2 是有意的。强制轮比自由轮贵两层：预填串本身占一点提示词，而且
#: **强制轮注定不产生答复**（它只能调工具），所以每来一次就是实打实多一轮
#: 模型调用。但**一次都不给也不行**：实测小模型"我先看看目录"之后就停在那儿，
#: 而它其实只差被人从背后推一下。
#:
#: ⚠ 从前推那一下是**一句话**（`催话`，软的，它想不听就不听），现在是一个
#: **已经开了头的工具调用**（硬的，它没有拒绝的余地）—— 见 `本地agent协议.预填串`。
强制上限 = 2

#: 一次任务里最多**"因为工具调用格式崩了"重问几回**。见 `_解析催话`。
#:
#: ⚠ 定 2 是有意的：这类重试比 `催` 贵 —— 喂回去的话里要带上一轮的原文
#: （不然模型不知道改哪儿），一进一出就是上千 token。但**一次都不给也不行**：
#: 实测两种崩法（引号没转义、内容被截断）都是**重写一遍就能好的**，
#: 而原来的代码一撞上就整个任务中止 —— 明明只差一次重问。
解析催上限 = 2

def _指纹(名, 参):
    try:
        项 = sorted((str(k), str(v)) for k, v in (参 or {}).items())
    except Exception:
        项 = [('?', repr(参))]
    return (名, tuple(项))


def 该收尾吗(回, 记):
    """
    这一轮**没有工具调用** —— 允许收工了吗？回 `(行不行, 为什么不行)`。

    ⚠ **这是"收尾权"归谁的问题。** 从前是模型说了算：它不调工具，我们就当
    它干完了（顶多拿一张空话词表猜一猜它是在说打算还是真完了）。结果是它
    可以在第一步就说一句"我先创建这个文件"，任务当场结束 —— 用户看到的是
    **一句承诺**，磁盘上什么都没发生。

    改成**客观判据**：它说完了不算数，得有证据。

      ① **上一轮被输出上限截断了** → 不算。话可能只写了一半
         （带思维链的模型尤其常见，草稿也吃这个预算）。
      ② **一次工具都没成功执行过** → 不算。没动过手不可能是干完了。
      ③ **最后一次跑命令是砸了的** → 不算。改完没验过、或者还在报错，
         它不是干完了，是**放弃了**。

    三条都为假才放行。

    ⚠ **判据刻意不要求"改了代码就必须跑一遍"。** 写 README、写配置这类任务
    根本不需要跑，硬要它跑会把它卡死在那儿出不来。这条管的是**别把失败当
    收工**，不是"每步都得有验证"。

    ⚠ **正文空着另有说法**（见 `_空话`）—— "一个字没写"和"干完了"在数据上
    长得一模一样，处理方式却相反，不能混在这儿判。
    """
    if str(回.get('停因') or '') == 'length':
        return False, '上一轮被输出上限截断了，话可能没说完'
    if not any(步['结果们'] for 步 in 记.步们):
        return False, '一次工具都还没成功调过'
    码 = _最后退出码(记)
    if 码 is not None and 码 != 0:
        return False, '最后一次跑命令是失败的（退出码 %d），得先修好' % 码
    return True, ''


def _退出码(文):
    """
    `跑命令` 回的那段**开头就是** `退出码 N`（见 `酒馆工具.跑命令`）。

    取不到回 `None` —— 那说明这一条不是命令结果（比如是"用户拒绝了"），
    或者格式变了：**不参与判断**，别拿 `None` 当"失败"。
    """
    m = re.match(r'退出码\s+(-?\d+)', str(文 or ''))
    return int(m.group(1)) if m else None


def _最后退出码(记):
    """转录本里**最后一次** `run_cmd` 的退出码。没跑过命令回 `None`。"""
    码 = None
    for 步 in 记.步们:
        for r in 步['结果们']:
            if r['名'] == 'run_cmd':
                码 = _退出码(r['文'])
    return 码


def _空话(回):
    """
    模型这一轮一个字都没说时，给用户一句**能拿去查**的话。

    ⚠ **必须把"它到底回了什么"摆出来。** 光说"模型没有输出"，用户也好我们
    也好，都分不清是思维链吃光了预算、是对面把请求截了、还是模型真的哑了。
    思维链长度和停止原因是仅有的两个能分辨的证据 —— 而这两样本来是**丢掉的**
    （思维链根本不进 `正文`），所以只能一路带到这儿来。

    ⚠ `停因` 的值**三家写法不一样**（Anthropic 是 `max_tokens`/`end_turn`，
    OpenAI 系是 `length`/`stop`），所以两个都要认 —— 只认一个的话，
    正好那一家的用户看到的就是那句没用的"再试一次"。
    """
    停 = str(回.get('停因') or '')
    思 = 0
    try:
        思 = int(回.get('思维') or 0)
    except (TypeError, ValueError):
        思 = 0
    段 = ['模型这一轮什么都没写 —— 正文是空的，也没调任何工具。']
    if 思:
        段.append('它写了约 %d 字的思维链，思维链之后就没有正文了。' % 思)
    if 停:
        段.append('对面的停止原因是 %s。' % 停)
    if 停 in ('max_tokens', 'length'):
        段.append('**这就是被输出上限截断的**：思维链也算在输出里，它把额度'
                  '吃光之后，正文和工具调用就没地方写了。\n'
                  '去「设置…」把「单步输出」调大（写网页这类长东西建议 '
                  '4096 以上），或者换一个不吐思维链的模型。')
    else:
        段.append('再跑一次看看；要是每次都这样，把这一整段发出来。')
    return '\n'.join(段)


def _解析催话(回):
    """
    模型写了 `<tool_call>`，但里面**没抠出任何一条可用的调用** → 把原文 +
    照着改的清单喂回去，让它重写一遍。

    ⚠ **这不是"多推一把"，是唯一安全的做法。** 硬猜的后果是**静默写出一个
    坏文件**：文件写成了、界面报"已写入"、退出码也是 0，内容却是错的。
    `酒馆工具.改文件` 那段注释把这件事定过性 —— 比"读不到"糟糕一个数量级。
    所以**宁可多问一次，也不猜**。

    ⚠ **原文要带回去，而且要带尾巴。** 只说一句"格式不合法"，模型不知道自己
    哪儿写坏了；而内容被截断的坏点**在末尾**，只给开头等于没给。两头各截
    一段、中间省略，一千二百字上下，是一次重问能接受的开销。

    ⚠ **这份清单是按我们自己的协议写的**（XML 形状，见 `本地agent协议`）。
    从前那三条是 JSON 的毛病 —— **引号没转义 / 写了真换行 / 少括号**。
    在这个形状下**一条都不存在**（值就是原文，压根没有转义这回事），
    照抄过来等于让它去改一个不存在的错，越改越乱。
    """
    原 = 回.get('原生') or ''
    样板 = 原 if len(原) <= 1200 else (原[:600] + '\n…（中间省略）…\n' + 原[-600:])
    return (
        '[系统] 你上一轮输出了 <tool_call>，但里面**没有一条能用的调用**，'
        '所以那次调用没有执行。\n'
        '你的输出（共 %d 字）：\n'
        '----\n%s\n----\n'
        '这套协议长这样，照它写：\n'
        '<tool_call>\n<function=工具名>\n<parameter=参数名>值</parameter>\n'
        '</function>\n</tool_call>\n'
        '最常见的三种毛病，照着改：\n'
        '1. **值外面少了 `<parameter=名字>` 这一层** —— 每个参数都要有'
        ' `<parameter=名字>` 和收尾的 `</parameter>`，值就写在中间。\n'
        '2. **少了收尾标签** —— `</parameter>` / `</function>` / `</tool_call>`'
        ' 一个都不能少。多半是内容太长被输出上限截断了：这种情况**别一次写完'
        '整个文件**，先用 write_file 写个小骨架，再用 edit_file 一块一块补进去。\n'
        '3. **工具名写错了** —— 只能用工具清单里列出的那六个名字，一个字都不能差。\n'
        '重写一遍，只输出工具调用，不要解释。'
        % (len(原), 样板))


def _简短参(参):
    """参数压成一行，给"卡住了"那句话用。长的内容只留前 40 字。"""
    try:
        对 = []
        for k, v in list((参 or {}).items())[:3]:
            s = str(v).replace('\n', ' ')
            对.append('%s=%s' % (k, s[:40]))
        return '，'.join(对)
    except Exception:
        return repr(参)[:80]


