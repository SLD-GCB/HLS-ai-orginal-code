#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
酒馆模型.py — 五个东西长什么样

纯数据：不认识存储，也不认识界面。三个域模块（角色 / 接口 / 对话）
负责在模型和盘上的 JSON 之间来回搬。

**时间一律是 epoch 毫秒的 int。** 存的就是它，读回来也是它，中间不经过
任何格式化——所以不用解析日期字符串，也不丢精度。要给人看的时候在下游
格式化，不在这一层。

**空值换回字段自己的默认值。** 文件里那一列可能压根没有（老数据、手改过），
而模型这一层空字符串、0 比 `None` 好用：调用方少一堆 `if x is None`。
"""

import json
from dataclasses import dataclass, fields

__all__ = ['角色卡', '接口配置', '会话', '消息', '说话人', '协议们',
           '读JSON', '写JSON', '工具格式们', '用途们']


# ── JSON 列 ─────────────────────────────────────────────────────────
#
# 采样参数、附加头、会话预设、消息元信息这几样是**嵌套结构**，模型这一层
# 拿到的却是纯文本，所以按 JSON 文本存：模型是扁平的（每一列对到一个字段），
# 嵌套的东西进去出来都从这两个口走，不许在别处 `json.dumps`。

def 读JSON(文本, 默认=None):
    """
    表里的 JSON 文本 → 对象。

    **空或者坏掉就给默认值，不抛。** 这些列装的是配置（采样参数之类），
    读不出来当没配就行——为了一个坏掉的配置让整个角色打不开，是拿小
    毛病换大毛病。
    """
    if not 文本:
        return {} if 默认 is None else 默认
    try:
        return json.loads(文本)
    except ValueError:
        return {} if 默认 is None else 默认


def 写JSON(对象):
    """对象 → 存进表里的文本。`None` 存空串（不是 `'null'`）。"""
    if 对象 is None:
        return ''
    if isinstance(对象, str):
        return 对象
    return json.dumps(对象, ensure_ascii=False, sort_keys=True)


class _底(object):
    """
    五个模型共用的一点点行为。

    **故意不是 dataclass**：它一个字段都没有，只挂着两个类方法。做成
    dataclass 的话它的子类会多出一个空基类的构造参数。
    """

    @classmethod
    def 列名(cls):
        return tuple(f.name for f in fields(cls))

    @classmethod
    def 从行(cls, 行):
        """
        一行查询结果 → 模型。

        只认模型上有名字的列（查出来多的列直接忽略），列缺了就留默认值
        ——所以「只查列表要的几个列」是安全的，不用把每个字段都捞回来。
        """
        出 = {}
        for f in fields(cls):
            if f.name in 行:
                v = 行[f.name]
                出[f.name] = f.default if v is None else v
        return cls(**出)

    def 到字典(self):
        return {f.name: getattr(self, f.name) for f in fields(self)}


# ── 角色 ────────────────────────────────────────────────────────────

@dataclass
class 角色卡(_底):
    """
    一个 AI 角色。

    `头像` **不在这里**——它在 `角色头像` 表上单独存。头像动辄几百 KB
    到几 MB，混进这张表会让每一次「列个角色清单」都把全部头像读进内存。
    """

    编号: int = 0
    名字: str = ''
    简介: str = ''
    人设: str = ''
    开场白: str = ''
    示例对话: str = ''
    标签: str = ''
    创建于: int = 0
    更新于: int = 0


# ── 接口配置 ────────────────────────────────────────────────────────

协议们 = ('openai', 'anthropic', 'gemini', 'local')

#: 模型把工具调用吐成**哪种形状**。这是**模型的性格，不是协议的** ——
#: 同一个 `tools=` 发下去，`qwen2.5` 系回 JSON、`Qwen3` 系回 XML（实测过，
#: 见 `酒馆本地._取XML调用` 那段注释），所以只能按模型一套套声明。
#:
#: `自动` 是**两种都认**（解析器本来就两种都吃），只是不特别教哪一种。
工具格式们 = ('自动', 'JSON', 'XML')

#: 这套接口配置**给谁用**。聊天和编程助手是两条独立的配置路线 —— 给 agent 调成
#: 0.2 的温度（别啰嗦）不该把聊天也带走。
#:
#: ⚠ **`''` 是"老数据"**（这一列是后加的，盘上那几行都没有）。它的语义是
#: **两边都能用、两边都看得见** —— 不自动给用户的东西打标签，那样改数据太粗暴；
#: 用户改一次归属就归到一边了。
用途们 = ('对话', 'agent')


@dataclass
class 接口配置(_底):
    """
    一套模型 API 的配置。可以存很多套，对话时挑一套用。

    密钥目前**明文存在 `酒馆数据/接口配置.json` 里**——就在程序旁边，谁
    打得开这个目录谁就读得到。`酒馆接口.列()` 不带密钥是因为界面列表用不上
    它，**不是**因为这样就保住了密。
    """

    编号: int = 0
    名称: str = ''
    协议: str = 'openai'
    地址: str = ''
    密钥: str = ''
    模型: str = ''
    用途: str = ''              # 对话 / agent / ''（老数据，见 用途们）
    工具格式: str = '自动'      # 自动 / JSON / XML，见 工具格式们
    采样参数: str = ''          # JSON 文本，见 读JSON / 写JSON
    附加头: str = ''            # JSON 文本
    创建于: int = 0
    更新于: int = 0

    def 参数(self):
        return 读JSON(self.采样参数)

    def 头们(self):
        return 读JSON(self.附加头)

    def 式样(self):
        """
        归一化后的工具格式，回 `'自动'` / `'JSON'` / `'XML'`。

        ⚠ **认不出来一律回 `'自动'`，不抛。** 这一格是能手打的 JSON，写
        `"json"`、`"xml"`、`"Json"` 都该认；写成别的（或者老数据压根没这一列）
        就当没设 —— 跟 `读JSON` 那条"坏配置不该让功能打不开"一个道理。
        """
        值 = str(self.工具格式 or '').strip().lower()
        for 名 in 工具格式们:
            if 值 == 名.lower():
                return 名
        return '自动'

    def 归谁(self):
        """
        归一化后的用途，回 `'对话'` / `'agent'` / `''`。

        ⚠ **认不出来一律回 `''`（= 老数据、两边都能用），不抛。** 理由同
        `式样()`：这一列可能是能手打的 JSON 里的值，写成别的就当没设。
        **不能在这里把不认识的归到某一边** —— 那等于替用户做决定，而他
        那一行会从另一边凭空消失。
        """
        值 = str(self.用途 or '').strip()
        for 名 in 用途们:
            if 值 == 名:
                return 名
        return ''


# ── 会话 ────────────────────────────────────────────────────────────

@dataclass
class 会话(_底):
    """一个角色的一段对话。一个角色可以有很多段。"""

    编号: int = 0
    角色编号: int = 0
    标题: str = ''
    接口编号: int = 0           # 0 = 用默认的那套接口配置
    预设: str = ''              # JSON 文本：这一段的提示词/采样覆盖
    创建于: int = 0
    更新于: int = 0

    def 设定(self):
        return 读JSON(self.预设)


# ── 消息 ────────────────────────────────────────────────────────────

# `说话人` 就这三种。存的是文本不是数字——排错时一眼看得懂，
# 而且多一种说话人（比如"系统提示"）不用改表结构。
说话人 = ('用户', '角色', '系统')


@dataclass
class 消息(_底):
    """
    一条消息。

    主键是 `(会话编号, 序号)`，**不靠发号器**：天然唯一、天然有序。
    重新生成某条消息 = 对同一个主键用 `替换` 覆盖，不会长出重复行。
    """

    会话编号: int = 0
    序号: int = 0
    说话人: str = '用户'
    内容: str = ''
    元信息: str = ''            # JSON 文本：模型、耗时、token 数之类
    创建于: int = 0

    def 附加(self):
        return 读JSON(self.元信息)
