#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
酒馆工人.py — 两条线程：一条独占存储，一条跑模型

    ┌──────────────┐        ┌──────────────────────────────┐
    │  工人线程     │        │  生成线程                     │
    │  （工位/工人）│        │  （生成线）                   │
    │              │        │                              │
    │  独占 `库`    │        │  **一个字节的存储都不碰**      │
    │  界面投活给它 │        │  跑 requests 流式，只发信号    │
    └──────────────┘        └──────────────────────────────┘
             ▲                            ▲
             │ 投活 / 回话（Qt 信号）      │ 分块 / 结束（Qt 信号）
             └──────────── 主线程 ────────┘

**为什么要两条。** 一次生成动辄几十秒。只扔工人线程的话，用户在这期间点个
别的角色会一起卡住，要等整段生成完。所以生成必须自己一条。

**为什么生成线不碰存储。** 这是这一层最要紧的一条。它能碰的话：
`消息们`（读出来）和 `存消息们`（整份写回去）之间就有个窗口，两条线程同时
往一段会话里追加，后写的那份会把先写的那条**整份盖掉**；而且它并不总是
"两条线程"——`酒馆存储.库` 里那把 `RLock` 只护得住每一次调用，护不住
"读一次、改一改、再写一次"这一整段（`库.独占` 才是护那个的）。

不碰存储之后，全项目**只剩工人线程一条碰 `库`**：生成线程手上压根没有能
误用的引用。代价只是生成前后那两次动作要由主线程投给工人线程——本来也要
等网络，白赚。

⚠ **`库.独占` 这个口子还是留着。** 因为 `追加消息` 自己就是"读-改-写"，
而它已经被 `独占` 套上了；将来真出现第二条碰 `库` 的线程时，底下那一层
已经把该锁的锁住了——不用回头再补一遍。

形状是照霸下 `界面_接驳.py` 的 `工人` / `工位` / `停` 抄的（那份在生产里
跑着）。抄的时候守住了它三个教训：

  · `干活` 里 **什么错都要回话**，绝不 re-raise——工人被打死就全完了
  · 投活**非阻塞**，工人线程干完发信号回来，**回话在主线程里被叫**
  · `停()` **返回 bool，返回值不能扔**

跟霸下那份的差别只有一个：`生成线` 是它没有的东西（霸下没有流式）。
"""

import queue
import threading

from PySide6.QtCore import QObject, QThread, Signal, Slot

import 酒馆大脑

__all__ = ['工人', '工位', '生成线']


class 工人(QObject):
    """
    活在工人线程里，**独占 `库`**。

    一件「活」就是一个收 `库` 做参数的函数（`def 活(库): ...`）。界面把活
    投过来，工人拿 `库` 跑它，把值或者错误发回去。

    **`库` 那个引用只存在这个对象里。** 界面拿不到它，所以它想在界面线程上
    调也调不着——这是形状，不是纪律。
    """

    完成 = Signal(str, object)     # (活号, 值)
    出错 = Signal(str, str)        # (活号, 错误文本)

    def __init__(self):
        super().__init__()
        self._库 = None
        self._号 = 0
        # 这条工人线程的 ident。**开线程之后由 `记线程` 在那个线程里填**——
        # 在主线程上问不到，`QThread` 的 ident 要等它真跑起来才存在。
        #
        # ⚠ `QThread.start()` 是**异步**的：`started` 信号要等事件循环转一圈
        # 才发。所以构造完**立刻**读这个属性拿到的是 `None`，而
        # `None != 主线程号` 恰好是 `True`——任何「对不上主线程就算过」的
        # 断言在这个时刻是**假绿**。要判就判 `is not None and != 主线程号`。
        self.线程号 = None

    def 接上(self, 库):
        self._库 = 库

    @Slot()
    def 记线程(self):
        self.线程号 = threading.get_ident()

    @Slot(object, object)
    def 干活(self, 号, 活):
        try:
            值 = 活(self._库)
        except Exception as exc:       # 什么错都要回话，不能把工人打死
            self.出错.emit(号, '%s：%s' % (type(exc).__name__, exc))
            return
        self.完成.emit(号, 值)


class 工位(QObject):
    """
    界面对着的那一头。**界面只会说「去干这个活」，它拿不到 `库`。**

        self._工位.干(lambda 库: 酒馆角色.列(库), self._收角色列表)

    `回话` 在主线程里被叫，签名叫 `回话(值, 错)`——**两个里总有一个是
    `None`**。投活是非阻塞的，界面投完就回去重绘了。

    **传进来的是 `None` 也算「成了」**（比如「没有这个角色」返回的是
    `酒馆角色.取(库, 999)` = `None`）。分不清「活干完了，值就是 None」和
    「活炸了」的话，界面就得靠猜。所以失败一律走 `错`，`None` 永远是
    合法的返回值。
    """

    派活 = Signal(str, object)

    def __init__(self, 库, 父=None):
        super().__init__(父)
        self._等 = {}
        # 投活那个计数器：**现在只有界面线程在用**，但上锁的代价等于零，
        # 而撞号的后果不是「慢」，是**甲的回话被叫给了乙**。留着。
        self._锁 = threading.Lock()
        # `工位` 是在界面线程上造的（窗口就是这么造它的）。记下来当闸门用。
        self._主线程号 = threading.get_ident()

        self.库 = 库
        self._线程 = QThread()
        self._工人 = 工人()
        self._工人.moveToThread(self._线程)
        self._工人.接上(库)
        self.派活.connect(self._工人.干活)
        self._工人.完成.connect(self._收完成)
        self._工人.出错.connect(self._收出错)
        # `started` 是在**新线程里**发的，正好用来记那个线程的 ident
        self._线程.started.connect(self._工人.记线程)
        self._线程.start()

    def 在工人线程上(self):
        """这会儿是不是在工人线程上跑。给「只许在这儿调」的把关。"""
        return (self._工人.线程号 is not None
                and threading.get_ident() == self._工人.线程号)

    def _取号(self):
        with self._锁:
            self._工人._号 += 1
            return str(self._工人._号)

    def 干(self, 活, 回话=None):
        """
        投一件活。**非阻塞**——回话在主线程里被叫，签名 `回话(值, 错)`。

        `回话` 给 `None` 就是「投出去不管结果」。别拿这个当默认行为用，
        错了会静默丢掉——那是这个项目最不想要的失败样子。
        """
        号 = self._取号()
        if 回话 is not None:
            self._等[号] = 回话
        self.派活.emit(号, 活)

    def _收完成(self, 号, 值):
        回话 = self._等.pop(号, None)
        if 回话 is not None:
            回话(值, None)

    def _收出错(self, 号, 错):
        回话 = self._等.pop(号, None)
        if 回话 is not None:
            回话(None, 错)

    def 停(self):
        """
        停工人线程。**返回 `wait` 的结果——`True` 才是真停了。**

        这个返回值不能扔。`quit()` 只是让事件循环在**当前这件活跑完之后**
        退出；工人手上正压着一次大的读写（一大段会话的消息整份进出）时三秒
        根本不够，`wait` 会超时返回 `False`，而**线程还在跑、`库` 还被它
        捏着**。那种情况下接着 `库.关()` 就是让一条活着的线程往一个关掉的
        库上写。

        `_等` 那张回话表**只在停干净的时候才清** —— 没停干净的话，还有
        活着的线程要往回发话，清了就是把它的回话扔了。这是霸下那版的
        原话，照留。
        """
        self._线程.quit()
        停了 = self._线程.wait(3000)
        if 停了:
            self._等.clear()
        return 停了


class 生成线(QThread):
    """
    跑模型的那条线程。**它不碰存储，手上也没有能误用的引用。**

    进这一条的东西全是**已经拼好、已经取好**的纯数据（系统提示、消息数组、
    接口配置），出这一条的是**信号**。存储那两次动作（生成前取上下文、
    生成后存消息）都由主线程投给 `工位` 去做，所以「生成的东西存到哪个库」
    这个问题根本不存在——问不到。

    ⚠ **它跑的是阻塞的 `requests` 读，没有 Qt 事件循环。** 所以：

      · `quit()` 对它是**空操作**，`wait()` 必然超时——别指望霸下 `停()`
        那一套在这儿能用；
      · 停它只有一条路：**置停旗**（`打断()`）。旗子是被 `流式` 里那个
        **取块循环**每 `酒馆大脑.等块秒` 看一次的，所以最长 0.1 秒就出来，
        跟这次生成正卡在哪一步无关。**别指望靠"关连接"去打断一次阻塞读**
        ——实测关不掉，原因写在 `酒馆大脑._读客` 那份记录里。

    排活 / 打断都从主线程调；`分块` / `结束` / `坏了` 都是队列投递回主线程的。
    """

    分块 = Signal(int, int, str)          # (会话编号, 序号, 这一块的字)
    结束 = Signal(int, int, str, bool)    # (会话编号, 序号, 全文, 是不是被打断的)
    坏了 = Signal(int, int, str)          # (会话编号, 序号, 错误文本)

    def __init__(self, 父=None):
        super().__init__(父)
        self._队 = queue.Queue()
        # 当前这次生成的停旗。`打断` 从主线程置它，生成线程每收一块看一次。
        # 换引用在 CPython 里是原子的，所以不用锁。
        self._停旗 = None

    def 排(self, 会话编号, 序号, 系统, 消息们, 配置, 设定=None):
        """把一次生成排进队。**非阻塞**，排完就回。"""
        self._队.put((会话编号, 序号, 系统, 消息们, 配置, 设定))

    def 打断(self):
        """
        让正在跑的那次生成停下来。**最长 0.1 秒生效。**

        `停旗.set()` 顺手还会把挂着的响应关掉——那是为了让被放弃的那条读
        线程早点自己结束，**不是打断的手段**（关不掉一次已经阻塞住的读，
        见 `酒馆大脑._读客`）。真正让这里立刻生效的是旗子。
        """
        旗 = self._停旗
        if 旗 is None:
            return False
        旗.set()                       # 置旗 + 掐连接，两件一起做
        return True

    def run(self):
        while True:
            活 = self._队.get()
            if 活 is None:             # 停的哨兵，见 `停`
                return
            会话编号, 序号, 系统, 消息们, 配置, 设定 = 活
            旗 = 酒馆大脑.停旗()
            self._停旗 = 旗
            罐 = []
            try:
                for 段 in 酒馆大脑.流式(配置, 系统, 消息们, 旗, 设定):
                    罐.append(段)
                    self.分块.emit(会话编号, 序号, 段)
            except 酒馆大脑.已打断:
                pass                   # 停是我们自己点的，不是故障
            except Exception as 错:
                self._停旗 = None
                self.坏了.emit(会话编号, 序号, '%s：%s' % (type(错).__name__, 错))
                continue
            self._停旗 = None
            self.结束.emit(会话编号, 序号, ''.join(罐), 旗.is_set())

    def 停(self, 毫秒=6000):
        """
        停这条线。**返回 `wait` 的结果，跟 `工位.停` 一样不能扔。**

        先打断（不然它可能正卡在一次长读上，哨兵排在队尾也轮不到），
        再塞哨兵，再等。
        """
        self.打断()
        self._队.put(None)
        return self.wait(毫秒)
