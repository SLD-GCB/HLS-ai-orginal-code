def 流式块(系统, 消息们, 参数, 路径, 控=None):
    """
    本地生成，**逐块吐字符串**。是个生成器。

    ⚠ **整条生成都握着 `锁`**——Llama 不是线程安全的，这期间谁要换
    模型都得等。`_在生成` 是给界面的提示位，让它在"生成中"把切换/删除
    按钮按掉，而不是真去等锁把界面卡死。

    采样参数**原键名直通**：temperature / top_p / top_k / max_tokens /
    repeat_penalty。`n_ctx` / `n_gpu_layers` 在 `_取实例` 里 pop 掉了，
    不会漏进生成调用。

    `控` 是**人格控制**（`酒馆协议.取控制` 出来的那份）。缺省 = 什么都不加，
    跟没有这个功能时一模一样。

    ══ 这条路现在分五步走 ══════════════════════════════════════════

        ⓪ **控制**   把人格复述到离生成最近的位置（`锁人格`）—— 默认关
        ① **渲染**   用模型自己的模板，把 messages 变成"它真正吃掉的那串"
        ② **自检**   我们的人物设定**真的在那串里吗**（`装进去了吗`）
                     不在 → **换位置再渲染一次**（并进第一条 user）
        ③ **发送**   喂 token 表 + 停止串（**模板给的 + 按族补的回合标记**）
        ④ **分流**   思维链扣住不给用户看（`分流`）—— 只有推理模型才开

    这几步合起来就是"**把模型撬开、把人格装进去、再管住它说什么**"。

    渲染不了（没有模板 / 模板坏了）→ 先试**族默认模板**（比静默退成
    `llama-2` 强得多）；连族也认不出来才**退回旧的 `create_chat_completion`**，
    并且**把原因记在快照里**，界面上一眼看得见。

    ⚠ **`预填` 会被"回吐"**：它是提示词的一部分，**不在生成结果里**，
    所以在开吐之前先 `yield` 一次 —— 不然界面上这条回复**缺开头**
    （那个动作没了）。见下面那段。

    ⚠ 无 system、无控制时 `消息` 就是原来那串，行为与改动前逐字节相同。
    """
    global _在生成
    控 = 控 or {}
    要点 = str(控.get('要点') or '').strip()
    预填 = str(控.get('预填') or '').strip()
    参数 = dict(参数)                    # _取实例 要 pop，别动调用方那份
    with 锁:
        实例 = _取实例(路径, 参数)
        _在生成 = True
        try:
            消息 = ([{'role': 'system', 'content': 系统}] if 系统 else []) \
                  + list(消息们)
            # ── ⓪ 控制：人格复述（默认关，见 `酒馆协议.取控制`）──
            if 要点:
                消息 = 酒馆协议.锁人格(消息, 要点)
            # ⚠ **铺完再盖，不是 `create_chat_completion(messages=…, **参数)`。**
            # 后一种写法在 `参数` 里已经有同名键时会抛
            # `TypeError: got multiple values for keyword argument`。
            # 这两条路（`跑一轮` 和这儿）是同一个坑，一起按同一种写法处理。
            体 = dict(参数)
            体['stream'] = True
            # ⚠⚠ **`max_tokens` 不填的话，两条路的默认值差了十万八千里。**
            #
            #     `create_chat_completion` 的默认是 `None` → **不限**（只受 n_ctx 约束）
            #     `create_completion`      的默认是 **16**
            #
            # 不补这一句的话，接口配置里没填 `max_tokens` 的会话，**每次生成都会
            # 被砍在 16 个 token（中文十来个字）**，而且是从**句子中间**断开 ——
            # 看上去像"模型话说一半就停了"，完全看不出是参数问题。
            #
            # ⚠ **这个坑是接完渲染层、拿真模型跑真链路才撞出来的**
            # （2026-09-20）：三个模型全在 9~31 个字处断掉。之前每次测试都
            # **显式传了 `max_tokens`**，所以一直没露头 —— 这正说明
            # **"拿真链路真跑一遍"和"单测函数"是两件事**。
            体.setdefault('max_tokens', None)

            # ── ⓪ 画像：一次问清楚"这个模型到底是什么样" ──
            #
            # ⚠ 它值两样东西，都**不是**"白渲染一遍"：
            #   · `认system` 是**预判** —— 早知道它不吃 system，就不用先渲染一次
            #     带 system 的、再渲染一次并进首条的。**省掉一次注定白做的全量渲染。**
            #   · 它是**全链路唯一一处**说"这个模型是什么"的地方（族 / 认system /
            #     认tools / 模板丢没丢），记进快照给界面看。
            #
            # 代价是一次**探针渲染** —— 消息只有两条，比真实提示词便宜得多，
            # 而且下面本来就要渲染，净账是省的。
            画 = 酒馆协议.画像(实例)

            # ── ① 渲染 + ② 自检 ──
            有设 = bool((系统 or '').strip())
            路 = '模板'
            渲 = None
            # ⚠ **没有 system 时无条件走第一条路。** 画像的 `认system` 说的是
            # "这个模板认不认 system 插槽"，而我们压根没东西要装 —— 这时候拿它
            # 去否决第一步渲染，会得出"并入首条"这种**根本没发生过的动作**。
            if 画['认system'] or not 有设:
                渲 = 渲染对话(实例, 消息, 预填=预填, 用默认模板=True)
                if 渲 is not None and 有设 and not 装进去了吗(渲['串'], 系统):
                    渲 = None                             # 这份不要了，下面换位置
            if 渲 is None and 有设:
                # 要么早知道它不吃 system，要么真渲染出来确实没进去。
                # **换到它一定会读的位置再试一次** —— 第一条 user 是任何指令
                # 模型都会读的位置。
                换 = 渲染对话(实例, _并进首条(消息, 系统),
                            预填=预填, 用默认模板=True)
                if 换 is not None:
                    渲 = 换
                    路 = '并入首条' if 装进去了吗(换['串'], 系统) else '装不进去'
            if 渲 is not None and 渲.get('默认模板'):
                # 兜底这件事**比"装进去了"更该被看见** —— 它意味着我们喂了
                # 一份猜的模板，效果可能明显打折。所以它盖过上面那两个路标。
                路 = '族默认'

            # ── ③ 停止串：模板给的 + 按族补的回合标记 ──
            #
            # ⚠ 补的是**回合标记**（GLM 的 `<|user|>`、Llama3 的 `<|eot_id|>`…）——
            # 模型答完想接着演用户时吐的就是它们，不在 stop 里就拦不住。
            # ⚠ 这张表**还没在真模型上逐个验过**（`酒馆协议.族停` 上有标注）。
            补停 = 画['停']

            # ── ④ 分流：思维链剥不剥（只有推理模型才开）──
            开分流 = 酒馆协议.该分流(控, 实例, 渲['串'] if 渲 else '',
                                    酒馆协议.模型名(路径))

            # ── ④′ 中间段：解码期的干预（**token 还没生成**）──
            #
            # ⚠ 这一段在"输入"和"输出"之间。跟 `分流` 是**两个不同的位置**：
            #   · 这儿   —— 采样时掐掉，**它压根吐不出来**（token 不烧）
            #   · 分流   —— 已经吐完了再扣住不给用户看（token 白烧了）
            # 同一个问题（推理模型的草稿），这儿是**正解**，分流只是**兜底**。
            #
            # ⚠ 默认**开**（跟要点/预填相反），因为它只会"少说"不会"多说"。
            # 拿不准就写设定 `中间层='关'` 全关 —— 见 `酒馆协议.要禁的`。
            禁 = 酒馆协议.要禁的(控)
            器禁 = 酒馆协议.禁吐(实例, 禁) if 禁 else None
            if 器禁 is not None:
                体['logits_processor'] = 器禁

            # ── ⑤ 发送 ──
            if 渲 is None:
                路 = '回退'
                体['messages'] = 消息
                if 补停:
                    旧 = 体.get('stop') or []
                    体['stop'] = ([旧] if isinstance(旧, str) else list(旧)) + 补停
                try:
                    流 = 实例.create_chat_completion(**体)
                except ValueError as 错:
                    raise (_超窗(错, 实例) or 错)
            else:
                # ⚠ **摘掉"聊天专用"的键。** `create_completion` 不认它们，留着
                # 就抛 `TypeError: unexpected keyword argument '…'`。
                #
                # 这些键**老路径一直是容忍的**（`create_chat_completion` 全认），
                # 而「采样参数」那一格是**能手打的 JSON** —— 老代码的注释里就
                # 点过名："用户手写 `messages` / `stream` 也会一样炸"。
                # 聊天链路从来不下发 `tools` 这一类，所以摘掉不会丢任何东西。
                for 聊天专用 in ('messages', 'functions', 'function_call',
                                 'tools', 'tool_choice', 'response_format',
                                 'top_logprobs'):
                    体.pop(聊天专用, None)
                体['prompt'] = 渲['token们']
                停 = list(渲['停'])
                for 条 in 补停:
                    if 条 not in 停:
                        停.append(条)
                if 停:
                    旧 = 体.get('stop') or []
                    体['stop'] = ([旧] if isinstance(旧, str) else list(旧)) + 停
                if 渲['停止'] is not None:
                    体['stopping_criteria'] = 渲['停止']
                try:
                    流 = 实例.create_completion(**体)
                except ValueError as 错:
                    raise (_超窗(错, 实例) or 错)

            # 快照在**开始吐第一个字之前**就冻住：界面要的是"这次发了什么"，
            # 不是"发完之后还剩什么"。
            # 快照存在 `酒馆协议` 里 —— 读它的是界面，跟引擎这一层无关。
            酒馆协议.记下发(串=渲['串'] if 渲 else '',
                          路=路,
                          模型=酒馆协议.模型名(路径),
                          说明=_路说明(路, 系统),
                          画像={'族': 画['族'], 'arch': 画['arch'],
                              '认system': 画['认system'], '认tools': 画['认tools'],
                              '回退': 画['回退'], '模板字': len(画['模板'])},
                          控制={'要点': 要点, '预填': 预填, '补停': 补停,
                              '分流': 开分流, '禁吐': list(禁),
                              '禁生效': 器禁 is not None})

            # ⚠ **预填要"回吐"。** 它是提示词的一部分、**不在生成结果里** ——
            # 不先吐一次，界面上这条回复就**缺开头**（比如预填是
            # `（沈砚搁下账本，抬眼看你）`，用户只会看到后面的台词，那个动作没了）。
            if 渲 is not None and 预填:
                yield 预填

            器 = 酒馆协议.分流() if (开分流 and 渲 is not None) else None
            for 帧 in 流:
                try:
                    段 = (帧['choices'][0].get('text') if 渲 is not None
                          else 帧['choices'][0]['delta'].get('content'))
                except (KeyError, IndexError, TypeError, AttributeError):
                    段 = None
                if not 段:
                    continue
                if 器 is None:
                    yield 段
                else:
                    for 块 in 器.喂(段):
                        yield 块
            if 器 is not None:
                for 块 in 器.完():
                    yield 块
                # ⚠ **只出了草稿、没有正文** —— 用户看到的是空白，必须让他知道
                # 为什么。这是唯一一处**事后**补写快照的地方：`只思维` 只有到
                # 最后才知道，而快照在开吐前就冻住了（那是为了给界面"这次发了
                # 什么"，这儿补的是"这次收成了什么"，两件事）。
                if 器.只思维:
                    酒馆协议.记下发(**dict(酒馆协议.最近发出(), 只思维=True))
        finally:
            _在生成 = False


