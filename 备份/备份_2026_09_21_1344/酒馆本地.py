def 有工具模板(路径):
    """
    这个模型的聊天模板里到底认不认 `tools`。认就给 `tools=`，不认就给文本协议。

    ⚠ **判据是模板里有没有 `tools` 这个变量，不是 `tool_call`。** 这两个
    容易搞混，实测踩过：

        qwen2.5-3b      有 `{%- if tools %}` 那段，把工具定义渲染进提示词   → 认
        R1-Distill-Qwen 模板里**没有** `tools`，但**有** `tool_call`
                        （它只是渲染 role='tool' 的历史消息，不渲染工具定义）→ 不认

    按 `tool_call` 判的话 R1 会被判成"认"，于是我们传了 `tools=` 但模板
    根本没把它渲染进去 —— 模型压根不知道有哪些工具，表现是**完全无视工具、
    自顾自地思考**（实测就是这样）。按 `tools` 判才对得上。

    ⚠ **这个函数现在没有调用方了**（`agent` 侧不再按模型挑形状，见
    `本地agent协议`）。留着是因为 `酒馆协议.认工具` 的判据就在下面那段
    —— 而聊天链路的画像还在用它（`画像['认tools']` 进 `流式块` 的快照）。
    从前的「工具协议」开关（自动 / 原生 / 文本）已经删了，所以这个启发式
    判错的场合**不再有绕过的开关** —— 但它也不再决定任何事。

    ⚠ **`item['tools']` 那种"挂在消息上"的写法要单独判死（2026-09-20 加）。**
    实测 GLM-4-9B-Chat 的官方模板里写的是：

        {% if item['tools'] is defined %} … {% endif %}

    工具定义挂在**某条 message** 上，**不是模板顶层的 `tools` 变量**。而
    `llama-cpp-python` 的 `Jinja2ChatFormatter` 只给模板传顶层 `tools`
    （见它的 `__call__`），所以这种模板**永远收不到我们下发的 `tools=`** ——
    渲染出来一行工具定义都没有。

    只看 `'tools' in 模板` 的话它会被判成"认"，于是自动走了原生模式、
    传了 `tools=`、模板一个字没渲染 —— 模型压根不知道有哪些工具，表现是
    **完全无视工具、自顾自地想**。这正是"判据只是个字符串"会踩的第二种坑
    （第一种是拿 `tool_call` 当判据，见上）。

    所以这里把"模板里有 `['tools']` 这种下标写法"当作**不认**：它自动落到
    文本协议，由提示词把工具讲清楚 —— 那条路对 GLM 是通的。

    ⚠ **判据本身已经搬去 `酒馆协议.认工具()`**（它跟"绘画像"是一件事，
    不该留在引擎这一层）。这儿只剩"把模型加载起来、把模板喂给它"。

    读的是 `实例.metadata`，加载时就拿到了；模型没加载就先加载一次。
    """
    try:
        实例 = _取实例(路径, {})
    except 本地错:
        return False
    return 酒馆协议.认工具(酒馆协议.模板文本(实例))


