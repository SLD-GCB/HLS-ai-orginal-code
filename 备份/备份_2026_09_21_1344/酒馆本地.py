#: 语法文本 → `LlamaGrammar` 对象。**编一次就够，别每个 token 都编。**
#:
#: ⚠ **llama-cpp-python 0.3.35 的 `create_completion` 不收语法字符串** ——
#: 它把这个值原样递给 `_init_sampler` → `add_grammar`，那边直接摸
#: `grammar._grammar`，于是报 `'str' object has no attribute '_grammar'`。
#: 所以这一步转换**不能省**（实测撞到的，不是我防患于未然）。
_语法器缓存 = {}


def _语法器(语):
    """语法文本 → `LlamaGrammar`。编不出来就当场报，**不退化成"没有语法"**。"""
    器 = _语法器缓存.get(语)
    if 器 is not None:
        return 器
    try:
        from llama_cpp import LlamaGrammar
    except Exception as 错:
        raise 本地错('中间层的语法用不了：没装上 llama-cpp-python（%s）' % 错)
    try:
        器 = LlamaGrammar.from_string(语)
    except Exception as 错:
        # ⚠ **不静默退回"没语法"** —— 那等于用户以为被控制住了、其实没有。
        raise 本地错('中间层的语法没能装上（%s：%s）。\n'
                    '把设定里那个 `语法` 写成「关」可以先绕开它。'
                    % (type(错).__name__, 错))
    if len(_语法器缓存) < 8:            # 语法只有一份，8 是白给的余量
        _语法器缓存[语] = 器
    return 器


class 本地停(Exception):
    """
    用户喊了停，`跑一轮` 从流里退出来。

    **正常收场，不是故障** —— 跟 `酒馆大脑.已打断` 一个意思。分开定义只是
    为了不让引擎这一层 import 上层。
    """


def 跑一轮(系统, 消息们, 参数, 路径, 停=None, 段回=None, 最大输出=1024,
           强制=False, 控=None, 工具名='', 参数名='', 工作目录=''):
    """
    本地生成，**一次拿完整条**。给编程助手用（`流式块` 是聊天用的，两者分开）。

    ⚠ **这条路现在自己渲染提示词**（`酒馆协议.备料`），跟聊天链路一样。
    这不是为了好看：**"预填"只能在渲染之后接字** —— `create_chat_completion`
    的提示词是库内部拼的，插不进任何东西。而预填是这套协议**唯一**能把
    "模型愿不愿意动手"从**服从问题**变成**格式问题**的手段。
    **不拿渲染权，整套控制就是空的。**

    ⚠ **不再有"原生 / 文本"之分，也没有 `工具=` / `要工具=` 了。**
    工具清单由 `本地agent协议.协议文本` 写进系统提示，调用形状由
    `本地agent协议` 定死。这条路上**没有一处**在问"这个模型会不会调工具"。

    `强制=True` 要求这一轮**不给模型"只答不做"这个选项**。做法是：先渲染一次
    拿到真串，按 `本地agent协议.起点(真串, 工具名, 参数名)` 造出**预填**，
    **再渲染一次**把它接到末尾。两个后果：

      ① 模型只能接着那几个字往下写 —— 这是把"愿不愿意"从**服从问题**变成
         **格式问题**的地方（`create_chat_completion` 那条路做不到这件事，
         这也是拿到渲染权的价值之一）
      ② 预填要**回吐**进 `原生` —— 这次输出的原文 = 预填 + 生成。
         不拼的话 `<tool_call>` 的开标签丢了、`解工具调用` 看到的是半截，
         判出来是"格式不合法" —— **方向完全指错**（模型其实一次就做对了）

    ⚠ **渲染两遍是有意的。** 预填要不要先补一个 `</think>`，取决于**渲染出来
    的真串**尾巴（`酒馆协议.思考没闭合`）—— 那个**只能渲染完才知道**，看模型
    名字猜不出来（Qwen3.5 的模板自己就给了一个**已闭合**的空思考块，替它补
    反而多出个野的收尾符）。多一遍 jinja 渲染跟一次模型调用比是噪声，
    不值得为省它去把 `渲染` 的接口改复杂。

    `工具名` / `参数名` 是**骨架**给的（`酒馆助手.骨架`），会把预填拨深一档。
    ⚠ **预填和语法一并由 `起点` 产出** —— 它们必须描述同一个切点，
    分开调用过一次事故（见 `本地agent协议.起点`）。

    回 `{'正文', '调用们', '原生', '提示词token', '停过', '解析失败', '停因',
    '思维'}`，外加协议层这几样：`串`（**真发出去的那一串**）、`路`（走了哪条
    安装路）、`预填`、`画像`、`禁生效`。`停因` / `思维` 跟 `酒馆大脑.跑一轮`
    对齐（那边是思维链**字数**）。`思维` 是**被切掉的思维链有多长**
    （2026-09-21 起才有值；从前恒为 0，因为本地这条路从来没单独量过它）。
    `酒馆助手._空话` 靠它分辨"思维链把输出预算吃光了"和"模型真的哑了"。

    `提示词token` 是**这次提示词的 token 数**（不是 dict）—— 上下文仪表靠它，
    取法和为什么这么取见下面那段注释。拿不到就是 0。

    `段回` 给了的话，每收到一块就调一次 `段回(段)` —— 界面拿它做"模型在写"
    的实时感。`停` 是带 `is_set()` 的东西，每收一块查一次，置了旗就抛 `本地停`。

    ⚠ **`流式块` 一个字都没动。** 那 6 行样板（`dict(参数)` → `with 锁` →
    `_取实例` → `_在生成=True` → `finally`）这儿重写了一遍，换的是聊天
    链路零风险——它天天在跑，不值得为省几行去动它。
    """
    global _在生成
    参数 = dict(参数)                    # _取实例 要 pop，别动调用方那份
    # ⚠ **别在这儿 pop `n_ctx` / `n_gpu_layers`** —— `_取实例` 正是从
    # `参数` 里读这两个来决定"开多大上下文、多少层上显卡"。提前吃掉的话
    # 它会以为没配，回头按默认值（纯 CPU、4096）建实例，而且一声不响。
    with 锁:
        实例 = _取实例(路径, 参数)
        _在生成 = True
        try:
            # ── 备料：渲染 + 自检 + 安装补偿 + 停止串（见 `酒馆协议.备料`）──
            料 = 酒馆协议.备料(实例, 系统, 消息们, 控=控)
            渲 = 料['渲']
            # 强制轮：**先拿到真串，才知道该不该替它把思考块闭合**（见上面那段）。
            #
            # `工具名` / `参数名` 是**骨架**给的（`酒馆助手.骨架`）—— 给了就把
            # 预填拨深一档：连"调哪个工具、用哪个参数名"都由我们写死，
            # 模型只剩一个格子填值。不给就停在老深度。
            预填, 语 = '', None
            if 强制 and 渲 is not None:
                # ⚠⚠ **预填和语法一次产出，绝不在外面分开调。**
                # 它们必须描述**同一个切点**（预填说"我写到这儿了"，
                # 语法说"从这儿往后该长什么样"）—— 分开调过一次事故：
                # 加深了预填却忘了语法，生成的第一口被逼着写工具名，
                # 表现成"4 个模型都很蠢"。见 `本地agent协议.起点`。
                起手 = 本地agent协议.起点(渲['串'], 工具名, 参数名)
                预填, 语 = 起手['预填'], 起手['语法']
                if 预填:
                    料 = 酒馆协议.备料(实例, 系统, 消息们, 预填=预填, 控=控)
                    渲 = 料['渲']
            # ⚠ **先铺 `参数`，这几个显式的键最后盖上去 —— 不是 `dict(键=值, **参数)`。**
            #
            # 后一种写法在 `参数` 里已经有同名键时会直接抛
            # `TypeError: dict() got multiple values for keyword argument 'max_tokens'`。
            # 而 `参数` 就是从接口配置的「采样参数」JSON 来的 —— 那里面
            # **本来就有 `max_tokens`**（接口页上那个格子），所以这条路必炸。
            # 用户手写 `messages` / `stream` 也会一样炸。
            #
            # 铺完再盖：显式的永远赢，而且要哪个键都不会撞。
            体 = dict(参数)
            体['stream'] = True
            try:
                体['max_tokens'] = int(最大输出 or 体.get('max_tokens') or 1024)
            except (TypeError, ValueError):
                体['max_tokens'] = 1024      # 配置里写坏了，退回默认，别崩
            # ── 中间段：解码期的干预（**token 还没生成**）──
            #
            # ⚠ **agent 这条路上默认不挂**，跟聊天那边相反。理由：
            #   · `要禁的(None)` 默认是**聊天那套**"自称 AI"的整句（兑现
            #     `本地规矩` 第 3 条），而 agent 没有那条规矩 —— 它在写代码，
            #     不需要替它挡这个；
            #   · 这一层**从没在真模型上验过**（聊天那边也还没），而 agent
            #     每步都要过它一遍，代价是每步一次小范围候选扫描。
            # 所以留成"谁传 `控` 谁才开"：能力在，默认不动行为。
            if 控 is not None:
                禁 = 酒馆协议.要禁的(控)
                器禁 = 酒馆协议.禁吐(实例, 禁) if 禁 else None
            else:
                器禁 = None
            if 器禁 is not None:
                体['logits_processor'] = 器禁
            if 渲 is None:
                # ── 回退：这个模型没有可用的聊天模板 ──
                #
                # ⚠ **这条路上"预填"是用不上的**（提示词由库内部拼，插不进东西）
                # —— 也就是强制手段失效。这不静默：`路='回退'` 会跟着快照出去，
                # 界面上看得见。（没有模板的模型本来就是极端情况。）
                体['messages'] = ([{'role': 'system', 'content': 系统}]
                                if 系统 else []) + list(消息们)
                try:
                    流 = 实例.create_chat_completion(**体)
                except ValueError as 错:
                    raise (_超窗(错, 实例) or 错)
            else:
                # ⚠ **摘掉"聊天专用"的键。** `create_completion` 不认它们，留着
                # 就抛 `TypeError: unexpected keyword argument '…'`。
                #
                # 这些键**老路径一直是容忍的**（`create_chat_completion` 全认），
                # 而「采样参数」那一格是**能手打的 JSON** —— 老代码的注释里就
                # 点过名："用户手写 `messages` / `stream` 也会一样炸"。
                for 聊天专用 in ('messages', 'functions', 'function_call',
                                 'tools', 'tool_choice', 'response_format',
                                 'top_logprobs'):
                    体.pop(聊天专用, None)
                体['prompt'] = 渲['token们']
                # ── 中间层：采样期约束（**token 还没生成**）──
                #
                # ⚠ **只在强制轮挂，而且这就是它该待的位置。**
                # 套上语法之后模型**只能输出工具调用、给不出答复** ——
                # 自由轮带上它等于把"收尾"这条路封死。
                # 判据用 `预填` 是不是空的：它非空 ⟺ 这一轮是强制轮。
                #
                # ⚠ **默认开，留个逃生口。** 它是**保护性**的（只会让它更规矩，
                # 不会让它多说），按项目那条"保护性的默认开"。但它是**第一次
                # 接进链路**，所以 `控['语法']='关'` 能当场关掉。
                if 预填 and 语 and str((控 or {}).get('语法') or '').strip().lower() \
                        not in ('关', 'off', '0', '否', '不'):
                    # ⚠ **`语` 是 `起点` 跟预填一起产出的** —— 它俩必然
                    # 落在同一个切点上，外面没法把它们配错。见 `起点`。
                    体['grammar'] = _语法器(语)
                # ⚠ **停止串 = 模板自带的 + 回合标记（模型自己的 bos/eos + 模板里写死的）。**
                #
                # ⚠ **不再用 `酒馆协议.族停` 那张手写族表** —— 实测对不上
                # （R1-Distill 的回合标记是全角 `<｜User｜>`，表里没有；
                # `画像['停']` 对它还返回空）。改成从**模型自己的 bos/eos**
                # 加**模板里写死的字面量**：那是**事实**，编表是猜。
                # ⚠ 尤其 **bos 也当停止串**：模型在生成里吐 bos，
                # 只有一个意思 —— 它在开新一轮（"活干完了也不停"就是这么来的）。
                # 见 `本地agent协议.回合标记`。
                停串 = list(料['停']) + list(本地agent协议.回合标记(
                    实例, 料['画']['模板']))
                if 停串:
                    旧停 = 体.get('stop') or []
                    体['stop'] = ([旧停] if isinstance(旧停, str)
                                else list(旧停)) + 停串
                if 渲['停止'] is not None:
                    体['stopping_criteria'] = 渲['停止']
                try:
                    流 = 实例.create_completion(**体)
                except ValueError as 错:
                    raise (_超窗(错, 实例) or 错)
            罐, 提示, 末帧, 停过 = [], 0, None, False
            for 帧 in 流:
                if 停 is not None and 停.is_set():
                    停过 = True
                    raise 本地停()
                末帧 = 帧
                # ⚠ **流式拿不到 `usage`**（那只在非流式的返回里）。但它有
                # 更好的东西：`n_tokens` 就是 KV 缓存当前的占用位置。第一帧
                # 到达时提示词已经 prefill 完、才生成了 1 个 token，所以
                # **此刻的 `n_tokens - 1` 就是这次提示词的 token 数**。
                # 上下文仪表靠它——不用自己估，是精确值。
                if 提示 == 0:
                    try:
                        提示 = max(1, int(实例.n_tokens) - 1)
                    except Exception:
                        提示 = 0
                # ⚠ **两条路的帧长得不一样**：`create_completion` 给的是
                # `text`，`create_chat_completion` 给的是 `delta.content`。
                # 只认一种的话，换路之后**每一帧都取不到东西** —— 而那表现出
                # 来是"模型一个字都没输出"，不是报错。
                try:
                    格 = 帧['choices'][0]
                    段 = (格.get('text') if 渲 is not None
                          else (格.get('delta') or {}).get('content'))
                except (KeyError, IndexError, TypeError, AttributeError):
                    段 = None
                if 段:
                    罐.append(段)
                    if 段回:
                        段回(段)
        except 本地停:
            raise
        finally:
            _在生成 = False

    # ⚠ **预填要"回吐"。** 它在提示词里、**不在生成结果里** —— 不拼的话
    # `<tool_call>` 的开标签丢了，`解工具调用` 看到的是半截东西，
    # 判出来是"格式不合法"。方向完全指错：模型其实一次就做对了。
    #
    # ⚠ **回退那条路不能拼**（那边预填压根没生效），所以按 `渲` 在不在判。
    完整 = ''.join(罐)
    if 渲 is not None and 预填:
        完整 = 预填 + 完整
    原生, 停因 = None, ''
    if isinstance(末帧, dict):
        try:
            原生 = 末帧['choices'][0]['message'].get('tool_calls') or None
        except (KeyError, IndexError, TypeError, AttributeError):
            原生 = None
        # ⚠ 本地的 `finish_reason` 是 `stop` / `length` —— 后者同样意味着
        # "被输出上限截断"（`max_tokens` 那一格）。**跟云端那条要给出一致的
        # 解释**，不然同一个病在两条路上说成两种话，`_空话` 就白写了。
        try:
            停因 = str(末帧['choices'][0].get('finish_reason') or '')
        except (KeyError, IndexError, TypeError, AttributeError):
            停因 = ''
    # ⚠ **`给过工具=True` 是对的**：工具清单**每次都在系统提示里**，模型确实
    # 看过。裸 JSON 那条兜底（`解工具调用` ④）靠它开门，而那道门后面还有一道
    # `认得的` 名单校验 —— 模型正文里展示一段带 `name` 的示例 JSON，
    # 名字撞不进我们的工具名清单，收不上来。
    # ⚠ **解析前先把思维链切掉。** 推理模型的草稿里写一个 `<tool_call>` 示例，
    # 和真要调的那条在文本上一模一样 —— 不切的话**两个都会被收下来执行两遍**
    # （`run_cmd` 是真会跑两次）。见 `本地agent协议.剥思维`。
    剥过 = 本地agent协议.剥思维(完整)
    调用们, 残, 失败 = 解工具调用(剥过, 原生=原生, 给过工具=True,
                                  认得的=set(酒馆工具.工具名们))
    # ⚠ **参数值归一，在记录之前做。** 模型把 `path` 写成「当前目录」、
    # `count` 写成「100 行」、给值套一层引号 —— 都是**意思对、说法不对**，
    # 工具吃不下会报错。见 `本地agent协议.整参数`。
    #
    # ⚠ **归一放在这儿、而不是执行前那一下**，是为了让**转录本里存的、
    # 界面上摊开的、真正执行的**是同一份 —— 三处不一样的话，出了事没人说得清
    # 到底发生了什么。
    for 调 in 调用们:
        调['参数'] = 本地agent协议.整参数(调.get('名'), 调.get('参数'), 工作目录)
    # 被切掉的思维链有多长 —— `_空话` 靠它分辨"思维链把预算吃光了"和
    # "模型真的哑了"。从前本地这条路恒为 0（思维链根本没单独量过），
    # 而现在我们**本来就要把它切掉**，顺手量一下是白赚的。
    思维字 = len(完整) - len(剥过)
    return {'正文': 残, '调用们': 调用们, '原生': 完整,
            '提示词token': 提示, '停过': 停过, '解析失败': 失败,
            '停因': 停因, '思维': 思维字,
            '串': (渲['串'] if 渲 is not None else ''),
            '路': 料['路'], '预填': 预填,
            '画像': {'族': 料['画']['族'], 'arch': 料['画']['arch'],
                   '认system': 料['画']['认system'],
                   '认tools': 料['画']['认tools'],
                   '回退': 料['画']['回退'],
                   '模板字': len(料['画']['模板'])},
            '禁生效': 器禁 is not None}


def 卸载全部():
    """
    把实例放掉。**关窗时叫**——在生成线停干净之后（`酒馆窗口` 关窗流程），
    别在生成中途叫：锁会等到生成跑完才放，主线程就这么卡死了。
    """
    global _实例, _键
    with 锁:
        _实例 = None
        _键 = None
        gc.collect()


#: 上一次「让路」动了什么。给界面读 —— 不报出来的话，用户不知道它做了事。
_最近让路 = {}


def 最近让路():
    """上一次 `让路` 干了什么。见 `让路`。"""
    return dict(_最近让路)


def _清暂存空壳():
    """
    把 `模型目录/_暂存/` 下的**空目录**删掉。回删了几个。

    ⚠ **绝不碰 `.part` / `._____temp` / `.msc` / `.mdl`。** 那些是**断点续传
    的锚点**（见 `_hf直下` 和 `下载` 里的说明）—— 删了的话下次同一个下载要从
    头再来，几 G 白下。所以只删**真正空的**目录：文件已经被 `_挪进模型目录`
    挪走了，壳才剩在那儿。
    """
    根 = os.path.join(模型目录(), '_暂存')
    if not os.path.isdir(根):
        return 0
    数 = 0
    for 现, _子, _件 in os.walk(根, topdown=False):
        if os.path.normcase(现) == os.path.normcase(根):
            continue                        # 暂存根自己不删
        try:
            if not os.listdir(现):
                os.rmdir(现)
                数 += 1
        except OSError:
            continue
    return 数


def 让路():
    """
    下载完之后**把本进程能放的东西放掉**，给接下来的模型加载腾地方。

    ⚠ **先说清楚它做不到什么 —— 免得它背了背不动的锅：**

      · **没有「下载进程」可以清。** 下载就在**本进程的工人线程**里跑
        （`下载` 是一次阻塞调用，见那份说明）。下完线程就结束了，不存在
        什么外部进程占着我们。所以这不该叫「进程管理器」——**它管的是
        我们自己进程里的占用**。
      · **Windows 的页缓存（standby 内存）碰不到。** 刚下完那几 G 的文件
        会被系统放进页缓存；那部分**只有系统自己能回收**，Python 没有接口
        （`EmptyStandbyList` 那类要外部工具，不该由我们的软件偷偷跑）。

    **它能清的是「本进程内我们自己的占用」，三样：**

      ① **把挂着的模型实例放掉。** ⚠ **这是最要紧的一样** —— 下载的时候引擎
         那边**很可能还挂着上一个模型，它一直占着显存**；这时候去加载新模型，
         **两棵同时在**，峰值就是这么叠出来的。
         顺序走 `卸载全部`（先断引用再 `gc.collect()`，mmap 才放得掉）。
         ⚠ 模型页那条「**生成中不给下载**」的闸门保证了叫到这儿时没有生成在
         跑，所以这时候放是安全的 —— **别把它挪到别的地方去叫**。
      ② **收一遍垃圾。** 下载期间 SDK 攒下的 response / 分片列表 / 缓冲，
         靠引用计数不一定当场回收。
      ③ **清掉这次下载留下的空壳暂存目录**（只删空的，见 `_清暂存空壳`）。

    回一个 dict 说明**动了什么**，同时存进 `最近让路()` 给界面读 ——
    **不报出来的话，用户根本不知道它做了什么**，那跟没做没区别。
    """
    global _最近让路
    出 = {'放模型': False, '收垃圾': 0, '清暂存': 0}
    try:
        if not 在生成():
            with 锁:
                挂着 = _实例 is not None
            if 挂着:
                卸载全部()                  # 里面已经有 gc.collect()
                出['放模型'] = True
    except Exception:
        pass
    try:
        出['收垃圾'] = int(gc.collect())
    except Exception:
        pass
    try:
        出['清暂存'] = _清暂存空壳()
    except Exception:
        pass
    _最近让路 = 出
    return 出


