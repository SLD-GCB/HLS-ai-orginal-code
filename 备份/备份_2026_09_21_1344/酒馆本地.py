def _超窗(错, 实例):
    """
    llama.cpp 提示词超窗时那个 `ValueError` → 一句人话。别的错回 `None`（原样放回）。

    ⚠ **那句原文是对用户最没用的东西。** `Requested tokens (4359) exceed
    context window of 4096` —— 四个数字，一个能动的旋钮都没有。而它背后其实
    只有一个原因：**我们按"估算"裁的提示词，估漏了。**

    ⚠ **两条路都要包**（聊天 `流式块` / 编程助手 `跑一轮`）。两边现在都按窗口
    裁了（`酒馆大脑.窗口内` / `酒馆助手.分预算`），可裁的都是**估算值**，
    总会有撞上的时候 —— 撞上时得说人话，不能把四个数字甩给用户。
    """
    文 = str(错 or '')
    if 'exceed context window' not in 文:
        return None
    try:
        几 = int(实例.n_ctx())
    except Exception:
        几 = 0
    return 本地错(
        '这一轮的提示词超过模型的窗口了。\n'
        '（原始报错：%s）\n\n'
        '窗口只有 %d token。提示词是按估算裁的，估漏了 —— 这是程序该修的地方，'
        '不用你做什么。临时能拧的两处：\n'
        '  · 去「接口配置」把这套的 n_ctx 调大（8G 显存建议 8192 起）；\n'
        '  · 聊天的话，去「上下文」把字数上限或上下文条数调小。'
        % (文, 几))


