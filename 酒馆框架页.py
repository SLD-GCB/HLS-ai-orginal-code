#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
酒馆框架页.py — 「模型框架配置」框

菜单「接口 → 模型框架配置…」开它。三个单选，定本地模型用哪套框架：

```
┌──────────────────────────────────────────────────────────┐
│ 本地模型用哪套框架                                       │
│  ┌────────────────────────────────────────────────────┐  │
│  │ (•) 自动       有显卡就先用 GPU，起不来落回 CPU    │  │
│  │ ( ) 只用 CPU   完全不碰 CUDA 的东西（最稳，最慢）  │  │
│  │ ( ) 只用 GPU   只认 lib/ 那套（自己编的那份）      │  │
│  └────────────────────────────────────────────────────┘  │
│  包里这两套：                                            │
│    lib/       ✓ CUDA 版（62.1 MB，2026-09-19 21:33）     │
│    lib_cpu/   ✓ 在                                       │
│  这一次启动用的是：GPU 版                                │
│  ⚠ 改完要重启软件才生效。                                │
│                              [保存]      [关闭]          │
└──────────────────────────────────────────────────────────┘
```

**为什么改完必须重启。** 两套框架就是两套 DLL，靠 `LLAMA_CPP_LIB_PATH` 在
`import llama_cpp` **之前**指过去（见 `酒馆本地` 文件头「挑一套本地模型框架」）。
DLL 一旦加载进进程就换不掉了 —— 这是操作系统那一层的事，不是我们偷懒。
所以这个框只负责**存**，真正生效在下次启动。

⚠ **因此这个框故意不显示"已切换"，只说"重启后生效"。** 说"已保存"就够了，
说"已切换"就是骗人 —— 当前这个进程用的还是旧那套。

**为什么归在「接口」菜单下。** 它跟「本地模型…」「重编本地框架…」是一件事的三半：
模型文件、编引擎、选引擎。挑的顺序是**环境变量 > 这里存的 > 探显卡**三级，
见 `酒馆本地._挑后端`。

⚠ **「自动」是默认，也是加这个框之前唯一的行为。** 设置文件读不到、内容坏了，
一律退化成它 —— 用户不会因为一个坏文件而开不了引擎。
"""

import os

from PySide6.QtWidgets import (QButtonGroup, QDialog, QHBoxLayout, QLabel,
                               QMessageBox, QRadioButton, QVBoxLayout, QWidget)

import 酒馆编译
import 酒馆本地
import 酒馆样式

__all__ = ['框架页']


#: 每一档给用户看的一句话。键跟 `酒馆本地.框架们` 对齐。
选说明 = {
    酒馆本地.自动: ('有显卡就先用 GPU 那套，起不来自动落回 CPU。\n'
                 '没显卡的机器直接试 CPU。这是默认，也是加这个框之前的行为。'),
    'CPU': ('只用 CPU 那套，完全不碰 CUDA 的东西。\n'
            '最稳 —— 什么机器上都跑得起来；也最慢。'),
    'GPU': ('只用 GPU 那套（`lib/`，就是「重编本地框架」换上去的那份）。\n'
            '⚠ 显卡不被它支持、或者 `lib/` 根本不是 CUDA 版时，本地模型会直接起不来'
            '（不会自动落回 CPU）。'),
}


def _大小嘴(字节):
    """字节数 → 「62.1 MB」。这里只是显示用，所以够用就行。"""
    for 单位 in ('B', 'KB', 'MB', 'GB'):
        if 字节 < 1024 or 单位 == 'GB':
            return '%.1f %s' % (字节, 单位)
        字节 /= 1024.0
    return ''


def _库现状():
    """
    `lib/` 和 `lib_cpu/` 各是个什么情况。回两行给人看的话。

    ⚠ `lib_cpu/` 是从 `库目录()`（`<包>/lib`）的**上一级**拼出来的：`酒馆编译`
      没为它单开一个公开函数，而这里只要"在不在"，不值得为它加一个。
    """
    lib = 酒馆编译.库目录()
    if lib is None:
        return '包里的两套：**找不到 llama_cpp 包**（依赖库/llama_cpp 不在了？）'
    一套 = 酒馆编译.当前库()
    if not 一套['在']:
        第一 = '  lib/       没找到（本地模型用不了）'
    elif 一套['后端']:
        第一 = ('  lib/       ✓ %s（%s，%s 换的）'
              % (酒馆编译.后端短话[一套['后端']], _大小嘴(一套['大小']),
                 一套['时间'] or '时间不明'))
    else:
        第一 = ('  lib/       ⚠ **不是 GPU 版**（%s）—— 它吃不了显卡'
              % _大小嘴(一套['大小']))
    cpu = os.path.join(os.path.dirname(lib), 'lib_cpu')
    第二 = ('  lib_cpu/   ✓ 在' if os.path.isdir(cpu)
            else '  lib_cpu/   ⚠ 不在（选「只用 CPU」会没得用）')
    return '包里这两套：\n' + 第一 + '\n' + 第二


class 框架页(QDialog):
    """
    「模型框架配置」框。**它只存选择，不做切换** —— 切换发生在下次启动，
    见文件头。
    """

    def __init__(self, 父=None):
        super().__init__(父)
        self.setWindowTitle('模型框架配置')
        self.resize(560, 400)

        外 = QVBoxLayout(self)

        题 = QLabel('本地模型用哪套框架', self)
        外.addWidget(题)

        # ── 三档 ──
        框 = QWidget(self)
        框排 = QVBoxLayout(框)
        框排.setContentsMargins(8, 4, 8, 4)
        self._组 = QButtonGroup(self)
        self._钮 = {}
        现在 = 酒馆本地.框架()
        for 名 in 酒馆本地.框架们:
            钮 = QRadioButton(名, 框)
            钮.setChecked(名 == 现在)
            self._组.addButton(钮)
            self._钮[名] = 钮
            框排.addWidget(钮)
            小字 = 酒馆样式.灰色小字(选说明[名], 框)
            小字.setWordWrap(True)
            小字.setContentsMargins(24, 0, 0, 8)
            框排.addWidget(小字)
        外.addWidget(框)

        # ── 现状 ──
        外.addWidget(QLabel(_库现状(), self))
        self._运行标 = QLabel('', self)
        self._运行标.setWordWrap(True)
        外.addWidget(self._运行标)

        提醒 = QLabel('⚠ 改完要**重启软件**才生效：两套框架是两套 DLL，程序一启动'
                     '就把其中一套加载进内存了，运行中换不掉。', self)
        提醒.setWordWrap(True)
        外.addWidget(提醒)
        外.addStretch(1)

        # ── 按钮 ──
        钮行 = QHBoxLayout()
        钮行.addStretch(1)
        钮行.addWidget(酒馆样式.做按钮('保存', self._保存,
                                     '存下来，下次启动用这套', self))
        钮行.addWidget(酒馆样式.做按钮('关闭', self.reject, '', self))
        外.addLayout(钮行)

        self._刷运行()

    # ── 刷新 ──────────────────────────────────────────────────────

    def _刷运行(self):
        """
        把"**这一次启动**实际用的是哪套、跟存着的选的是不是一回事"写出来。

        ⚠ 这两件事**必须分开写**：用户刚改完还没重启时，它们就是不一样的 ——
          只报一个数会让人以为开关没生效。
        """
        存 = 酒馆本地.框架()
        用 = 酒馆本地.后端() or '（引擎没起来）'
        话 = '这一次启动用的是：%s 版' % 用 if 用 != '（引擎没起来）' else 用
        if 存 != 酒馆本地.自动 and 用 and 用 != 存:
            话 += '\n存的是「%s」，本次启动用的还是旧的 —— **重启之后才是「%s」**。' % (存, 存)
        elif 存 == 酒馆本地.自动:
            话 += '（选的是「自动」：有显卡先试 GPU，起不来落回 CPU。）'
        if not 酒馆本地.可用():
            话 += '\n⚠ 引擎现在起不来：%s' % (酒馆本地.不可用原因() or '')
        self._运行标.setText(话)

    def _当前选(self):
        """现在单选里点中的是哪一档。一个都没选中时按「自动」算。"""
        for 名, 钮 in self._钮.items():
            if 钮.isChecked():
                return 名
        return 酒馆本地.自动

    # ── 动作 ──────────────────────────────────────────────────────

    def _保存(self):
        新 = self._当前选()
        旧 = 酒馆本地.框架()
        if 新 == 旧:
            QMessageBox.information(self, '没变化', '还是「%s」，什么都没改。' % 新)
            return
        try:
            酒馆本地.写框架(新)
        except Exception as 错:
            QMessageBox.warning(self, '存不下来',
                                '写不进设置文件：%s：%s' % (type(错).__name__, 错))
            return
        # ⚠ 只说"重启后生效"，**不说"已切换"** —— 当前进程用的还是旧那套，
        #   说已切换就是骗人（这个框存在的最大意义就是别骗人）。
        QMessageBox.information(
            self, '存好了，重启后生效',
            '下一次启动就用「%s」了。\n\n'
            '⚠ **现在还没换**：两套框架是两套 DLL，程序启动时就把其中一套加载进内存，'
            '运行中换不掉。把软件关掉重开，就切过去了。' % 新)
        self._刷运行()
